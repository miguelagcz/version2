                <section id="tres-tipos-de-publico">
                    <h2>Los tres tipos de público en el Administrador de Anuncios</h2>
                    <p>
                        Antes de entrar a los públicos personalizados y similares, vale la pena ubicarlos dentro del panorama completo. El Administrador de Anuncios de Meta ofrece tres formas principales de definir a quién le vas a mostrar un anuncio:
                    </p>
                    <ul>
                        <li><strong>Segmentación detallada.</strong> Acota tu público objetivo usando datos demográficos, intereses y comportamientos, como educación, actividades digitales o páginas que le gustan a la gente.</li>
                        <li><strong>Públicos personalizados.</strong> Se construyen a partir de datos que ya tienes: visitantes de tu sitio web, tu lista de clientes o personas que ya interactuaron con tu contenido.</li>
                        <li><strong>Públicos similares (lookalike).</strong> Se construyen a partir de un público personalizado de origen; Meta busca a otras personas dentro de su base de usuarios que comparten características con ese grupo.</li>
                    </ul>
                    <p>
                        La segmentación detallada es tu punto de partida cuando apenas empiezas y todavía no tienes datos propios. Los públicos personalizados y similares se vuelven cada vez más poderosos conforme tu negocio acumula tráfico, leads y clientes, porque le dan al algoritmo información real sobre quién sí te compra, en lugar de una suposición basada solo en intereses declarados.
                    </p>
                </section>

                <section id="que-son-publicos-personalizados">
                    <h2>Qué son los públicos personalizados</h2>
                    <p>
                        Un público personalizado es un grupo de personas dentro de las tecnologías de Meta que ya tuvo algún tipo de relación con tu negocio: visitó tu sitio web, llenó un formulario, vio un video tuyo, interactuó con tu página de Facebook o cuenta de Instagram, o aparece en una lista de clientes que subiste directamente. En lugar de adivinar quién podría interesarse en tu oferta, le hablas a personas que ya demostraron algún nivel de interés real, lo que casi siempre se traduce en un CTR más alto y un costo por lead más bajo que la segmentación por intereses genéricos.
                    </p>
                    <p>
                        Para crear o usar un público personalizado o similar necesitas tener instalado el Pixel de Meta y, de preferencia, la API de Conversiones en tu sitio web, además del SDK de Facebook si tu negocio también tiene una app. Sin estas herramientas configuradas correctamente, Meta no tiene forma de identificar quién visitó tu sitio o completó una acción específica, así que este tipo de público simplemente no se puede construir con precisión.
                    </p>
                </section>

                <section id="tipos-de-publicos-personalizados">
                    <h2>Los orígenes de un público personalizado</h2>
                    <p>
                        Dentro del Administrador de Anuncios puedes construir un público personalizado a partir de distintos orígenes, y cada uno sirve para un momento distinto de tu embudo de ventas en Facebook:
                    </p>
                    <ul>
                        <li><strong>Visitantes del sitio web.</strong> Personas que visitaron tu página gracias al Pixel de Meta y la API de Conversiones. Puedes segmentar incluso por páginas específicas, como quienes vieron una propiedad en particular dentro de tu sitio.</li>
                        <li><strong>Usuarios de la app.</strong> Personas que interactuaron con tu aplicación móvil, identificadas a través del SDK de Facebook.</li>
                        <li><strong>Quienes enviaron un formulario.</strong> Personas que ya completaron un formulario instantáneo dentro de una campaña anterior de clientes potenciales.</li>
                        <li><strong>Visores de video.</strong> Personas que vieron cierto porcentaje de un video tuyo, útiles para retomar contacto con alguien que mostró interés pero no dio el siguiente paso.</li>
                        <li><strong>Listas de clientes.</strong> Correos electrónicos o números de teléfono de tu propia base de datos, que puedes subir directamente para encontrar a esas personas dentro de Meta.</li>
                    </ul>
                    <p>
                        Estos públicos son también la base de casi cualquier estrategia de remarketing o retargeting: en lugar de mostrarle tu anuncio a alguien nuevo, se lo muestras a alguien que ya te conoció y todavía no completó la conversión. Profundizamos en esta estrategia en nuestro artículo dedicado a <a href="/blog/retargeting-en-meta-ads">retargeting en Meta Ads</a>.
                    </p>
                </section>

                <section id="como-crear-publico-personalizado">
                    <h2>Cómo crear un público personalizado paso a paso</h2>
                    <p>
                        Puedes crear un público personalizado desde dos lugares dentro del Administrador de Anuncios: la pestaña "Públicos" en el panel lateral, útil cuando quieres reutilizar ese público en varias campañas, o directamente en el nivel del conjunto de anuncios mientras estás creando una campaña nueva. Los pasos generales son los siguientes:
                    </p>
                    <ul>
                        <li>Entra a la pestaña "Públicos" y haz clic en "Crear público".</li>
                        <li>Selecciona "Público personalizado".</li>
                        <li>Elige el origen: sitio web (Pixel de Meta o API de Conversiones), lista de clientes, actividad en la app, o interacción con tus tecnologías de Meta.</li>
                        <li>Define los parámetros específicos: por ejemplo, "visitó mi sitio en los últimos 30 días" o "vio al menos el 75% de mi video en los últimos 60 días".</li>
                        <li>Ponle un nombre claro a tu público (algo como "Visitantes landing preventa, 30 días") para no perderte cuando tengas varios públicos guardados.</li>
                        <li>Guarda el público; puede tardar unas horas en llenarse con las personas que cumplen esos parámetros.</li>
                    </ul>
                </section>

                <section id="que-son-lookalike">
                    <h2>Qué son los públicos similares (lookalike)</h2>
                    <p>
                        Un público similar, también conocido como lookalike, es un grupo de personas dentro de Meta que comparten características con un público de origen que tú eliges, normalmente tus mejores clientes o tus leads más calificados. La lógica es simple: si un grupo de personas ya te compró o ya se convirtió en un lead de calidad, es razonable pensar que otras personas parecidas a ellas, en cuanto a comportamiento, intereses y datos demográficos, también tienen más probabilidades de interesarse en tu oferta.
                    </p>
                    <p>
                        Esta herramienta resuelve uno de los problemas más comunes en cuentas que ya llevan tiempo corriendo campañas: agotar el público personalizado disponible. Tu lista de clientes o tus visitantes del sitio web tienen un tamaño limitado; los públicos similares te permiten escalar tu alcance sin perder la precisión que te dieron tus datos propios.
                    </p>
                </section>

                <section id="como-crear-lookalike">
                    <h2>Cómo crear un público similar paso a paso</h2>
                    <ul>
                        <li>Dentro de "Crear público", selecciona "Público similar".</li>
                        <li>Elige el origen del público similar: puede ser un público personalizado ya existente, tu Pixel, tu catálogo de productos, o tu página de Facebook.</li>
                        <li>Selecciona el país o la región donde quieres buscar a este nuevo público, considerando en qué zonas realmente opera tu negocio.</li>
                        <li>Ajusta el porcentaje de similitud con el control deslizante, del 1% al 10%: más cerca del 1% te da mayor precisión pero un público más pequeño, más cerca del 10% te da mayor alcance pero menor precisión.</li>
                        <li>Puedes crear varios públicos similares del mismo origen (por ejemplo, uno al 1% y otro al 3%) para probar cuál rinde mejor en tu cuenta.</li>
                        <li>Guarda el público y dale unas horas para que Meta termine de construirlo.</li>
                    </ul>
                    <p>
                        Un detalle importante: entre mejor sea la calidad de tu público de origen, mejor será el público similar resultante. Un lookalike construido a partir de tus clientes que ya pagaron va a rendir distinto que uno construido a partir de cualquier persona que visitó tu sitio, incluyendo a quienes nunca tuvieron intención real de comprar.
                    </p>
                </section>

                <section id="publicos-guardados">
                    <h2>Públicos guardados: para no repetir el trabajo</h2>
                    <p>
