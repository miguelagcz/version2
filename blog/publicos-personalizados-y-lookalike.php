                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Cuál es la diferencia real entre un público personalizado y un público similar?</summary>
                        <p>Un público personalizado está formado exclusivamente por personas que ya tuvieron contacto directo con tu negocio: visitaron tu sitio, te compraron, llenaron un formulario o interactuaron con tu contenido. Es, literalmente, tu propia base de datos representada dentro de Meta. Un público similar, en cambio, está formado por personas completamente nuevas que Meta identifica dentro de toda su base de usuarios porque comparten patrones de comportamiento, intereses y datos demográficos con un público personalizado que tú eliges como origen. En otras palabras, el público personalizado es "a quién ya conoces" y el público similar es "a quién todavía no conoces, pero que se parece mucho a quien ya te compró". Por eso ambos suelen usarse juntos dentro de una misma estrategia: el personalizado para reconectar y cerrar, el similar para encontrar clientes nuevos con un perfil validado.</p>
                    </details>

                    <details>
                        <summary>¿Qué tan grande debe ser mi lista para crear un público personalizado o similar?</summary>
                        <p>Para un público personalizado, Meta recomienda un mínimo de alrededor de 100 personas para que la plataforma pueda empezar a mostrarle anuncios de forma consistente, aunque entre más grande y más reciente sea la lista, mejor suele rendir la campaña. Para crear un público similar a partir de ese público personalizado, generalmente se necesita un origen de al menos 100 personas dentro del país o región seleccionada, aunque los resultados más sólidos suelen aparecer con públicos de origen de varios cientos o miles de personas, porque le dan al algoritmo patrones más claros para identificar similitudes reales en lugar de coincidencias superficiales. Si tu negocio es nuevo y todavía no tienes ese volumen de datos propios, lo más práctico es empezar con segmentación detallada por intereses y comportamientos, e ir construyendo tus públicos personalizados conforme el Pixel acumula visitas y conversiones.</p>
                    </details>

                    <details>
                        <summary>¿Qué porcentaje de similitud debo elegir en un público lookalike?</summary>
                        <p>No hay una regla fija que aplique a todos los negocios, pero sí una lógica general que vale la pena seguir. Si tu prioridad es la precisión, por ejemplo cuando vendes un producto de alto ticket como un desarrollo inmobiliario o una instalación solar completa, conviene empezar con un porcentaje cercano al 1%, porque te da el grupo de personas más parecido posible a tu público de origen, aunque el alcance total sea más pequeño. Si tu prioridad es el volumen, por ejemplo cuando quieres generar reconocimiento de marca o estás en una fase de expansión agresiva, un porcentaje más cercano al 10% te da un público mucho más amplio, aunque con menor precisión. Muchas cuentas maduras terminan corriendo dos o tres públicos similares en paralelo, con distintos porcentajes, para comparar directamente cuál genera el mejor costo por resultado antes de decidir en cuál concentrar el presupuesto.</p>
                    </details>

                    <details>
                        <summary>¿Puedo excluir a mis clientes actuales de una campaña de nuevos leads?</summary>
                        <p>Sí, y de hecho es una práctica altamente recomendada. Dentro de la configuración de público de cualquier conjunto de anuncios puedes agregar exclusiones, y una de las más comunes es excluir tu público personalizado de clientes actuales o de personas que ya llenaron un formulario reciente, para no gastar presupuesto mostrándole anuncios de captación a alguien que ya está en tu embudo o que ya te compró. Esta práctica mejora la eficiencia general de tu cuenta porque evita que compitan entre sí distintas campañas con objetivos diferentes (una buscando leads nuevos, otra haciendo retargeting a quienes ya conociste), y suele bajar el costo por lead general de la cuenta al concentrar el presupuesto de captación exclusivamente en personas verdaderamente nuevas.</p>
                    </details>

                    <details>
                        <summary>¿Los públicos personalizados dejan de funcionar si no tengo suficiente tráfico en mi sitio web?</summary>
                        <p>Los públicos personalizados basados en visitantes del sitio web dependen directamente del volumen de tráfico que reciba tu página, así que un sitio con muy poco tráfico va a generar un público personalizado pequeño y, en consecuencia, un público similar de menor calidad, porque el algoritmo tiene menos datos de dónde aprender los patrones de similitud. Mientras acumulas ese volumen, puedes complementar con otros orígenes de público personalizado que no dependen del tráfico web, como una lista de clientes existente, las personas que ya interactuaron con tu página de Facebook o Instagram, o quienes vieron un porcentaje relevante de tus videos, y usar esos orígenes como base temporal para tus públicos similares mientras el Pixel de tu sitio junta suficiente información propia.</p>
                    </details>
                </section>

