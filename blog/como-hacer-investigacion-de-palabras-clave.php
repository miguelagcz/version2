                <section id="que-es">
                    <h2>Qué es la investigación de palabras clave</h2>
                    <p>
                        Es el proceso de descubrir qué escribe la gente en Google cuando busca lo que tú vendes, cuántas veces lo busca y con qué intención. En inglés se le llama <strong>keyword research</strong>, y es el primer paso de cualquier estrategia de SEO: decide qué páginas vas a crear, de qué va a tratar cada una y con qué palabras.
                    </p>
                    <p>
                        Una palabra clave casi nunca es una sola palabra. Es una frase, como "cuánto cuesta un abogado laboral" o "paneles solares para negocio", y lo que importa no es la frase exacta sino la necesidad que hay detrás. Google lo entiende así: su propia guía explica que sus sistemas conectan una página con búsquedas parecidas aunque no use las mismas palabras, así que no necesitas escribir cada variante.
                    </p>
                    <p>
                        Sirve igual para la publicidad. Las búsquedas que eliges para posicionar son las mismas que compras en <a href="/blog/que-es-google-ads-y-como-funciona">Google Ads</a>, con una diferencia: en SEO trabajas meses para ganarte el lugar y en Ads lo pagas por clic desde el primer día. La comparación completa entre los dos canales está en <a href="/blog/seo-vs-sem-cuando-invertir-en-cada-uno">SEO vs SEM</a>.
                    </p>
                </section>

                <section id="las-tres-variables">
                    <h2>Las tres cosas que mides de cada búsqueda</h2>
                    <p>
                        De cada búsqueda te interesan tres datos. Uno solo no alcanza para decidir; los tres juntos sí.
                    </p>

                    <h3>Volumen de búsqueda</h3>
                    <p>
                        Cuántas veces se busca al mes, en promedio. Cada herramienta lo estima a su manera y da un número distinto, así que tómalo como orden de magnitud: no es lo mismo 50 que 5,000, pero 480 contra 590 es prácticamente igual.
                    </p>
                    <p>
                        Cuidado con dos trampas. Las búsquedas de temporada, como paneles solares en los meses de calor o despachos fiscales cerca de la declaración anual, tienen promedios engañosos. Y en negocios de nicho, muchas búsquedas valiosas salen con volumen cero porque las herramientas no alcanzan a medirlas, no porque nadie las haga.
                    </p>

                    <h3>Intención de búsqueda</h3>
                    <p>
                        Qué quiere lograr quien escribe. Puede querer aprender ("qué es un crédito puente"), comparar ("crédito Infonavit o bancario"), contratar ("despacho contable en Guadalajara") o llegar a un sitio que ya conoce ("Infonavit iniciar sesión"). La misma persona pasa por varias de estas etapas, y cada una pide un tipo de página distinto.
                    </p>
                    <p>
                        Es el filtro que más dinero ahorra. En nuestra propia investigación para Google Ads apareció "promoción google ads" con más de 22,000 búsquedas al mes. Parece una mina de oro hasta que revisas los resultados: casi todo es gente buscando el crédito promocional que Google regala a cuentas nuevas, no dueños de negocio buscando quién les maneje la publicidad. Mucho volumen, cero clientes. Si inviertes en anuncios, ese tipo de búsquedas son justo las que conviene bloquear con <a href="/blog/palabras-clave-negativas">palabras clave negativas</a>.
                    </p>

                    <h3>Dificultad</h3>
                    <p>
                        Qué tan complicado es entrar a la primera página. Herramientas como Semrush o Ahrefs la calculan del 0 al 100 a partir de los enlaces que tienen los sitios que hoy aparecen arriba. Es una estimación de la herramienta, no un dato de Google, pero sirve para no pelear batallas perdidas.
                    </p>
                    <p>
                        La forma más confiable de medirla no cuesta nada: busca la frase en Google y mira quién aparece. Si son portales nacionales, bancos y Wikipedia, es difícil. Si son negocios de tu tamaño con páginas flojas, es tu oportunidad. Cómo leer eso a fondo está en el <a href="/blog/como-hacer-analisis-seo-de-la-competencia">análisis SEO de tu competencia</a>.
                    </p>
                </section>

                <section id="paso-a-paso">
                    <h2>Cómo hacerla paso a paso</h2>

                    <h3>1. Empieza por cómo habla tu cliente</h3>
                    <p>
                        Antes de abrir cualquier herramienta, junta las frases que usa tu cliente: las preguntas que llegan por WhatsApp, las objeciones en las juntas de ventas, lo que escribe en el formulario de contacto. Ahí están tus <strong>palabras semilla</strong>, y casi siempre son distintas a como tú describes tu servicio.
                    </p>
                    <p>
                        Google pone un ejemplo parecido en su guía de SEO: quien sabe mucho de un tema busca con palabras distintas a las de quien apenas empieza. Tú dices "sistema fotovoltaico interconectado"; tu cliente escribe "paneles solares para bajar el recibo de luz".
                    </p>

                    <h3>2. Expande con el propio Google</h3>
                    <p>
                        Escribe cada semilla en Google y anota tres cosas: lo que sugiere el autocompletado, las preguntas de la sección "Otras preguntas de los usuarios" y las búsquedas relacionadas al final de la página. Son búsquedas reales de gente real, y no te cuestan un peso.
                    </p>

                    <h3>3. Ponle números</h3>
                    <p>
                        Pasa tu lista por una herramienta para ver volumen y dificultad. El <strong>Planificador de palabras clave</strong> de Google se usa sin costo dentro de una cuenta de Google Ads, aunque si no tienes campañas activas puede mostrarte rangos en lugar de cifras exactas. Semrush y Ahrefs dan más datos, como la dificultad y las páginas que ya posicionan, pero son de paga.
                    </p>
                    <p>
                        Si tu sitio ya tiene unos meses, la fuente más valiosa es la tuya: el informe de Rendimiento de Search Console te dice qué búsquedas ya te muestran, en qué posición y con cuántos clics. Son datos de Google sobre tu sitio, no estimaciones.
                    </p>

                    <h3>4. Filtra por intención</h3>
                    <p>
                        Aquí se separa la grava del oro. Repasa la lista y, para cada búsqueda, pregúntate: si esta persona llega a mi sitio, ¿podría convertirse en cliente en los próximos meses? Las que no, fuera, por más volumen que tengan.
                    </p>
                    <p>
                        Las búsquedas de contratación directa ("agencia de...", "despacho en...") apártalas para tus páginas de servicio. El blog es para las de aprender y comparar, que son las que te ponen frente al cliente antes de que esté listo para contratar.
                    </p>

                    <h3>5. Agrupa por tema</h3>
                    <p>
                        Junta las búsquedas que piden lo mismo con frases distintas. "Cuánto cuesta un abogado laboral", "honorarios de abogado laboral" y "precio de un abogado por despido" son una sola página, no tres. Si haces tres páginas casi iguales, compiten entre sí y ninguna sube.
                    </p>
                    <p>
                        Dónde colocar cada búsqueda dentro de la página, del título al primer párrafo y los subtítulos, lo explicamos en la <a href="/blog/seo-on-page-checklist">checklist de SEO on-page</a>.
                    </p>

                    <h3>6. Prioriza</h3>
                    <p>
                        Con la lista agrupada, ordena por tres criterios y en este orden: qué tanto se parece la búsqueda a una venta, qué tan fácil se ve la primera página y cuánto volumen tiene. Para un negocio de alto ticket, una búsqueda de 30 al mes con intención de compra y competencia floja vale más que una de 3,000 que no vas a ganar.
                    </p>
                    <p>
                        Un atajo que funciona casi siempre en negocios locales es agregar la zona: "ortopedista en Zapopan" tiene una fracción de la competencia de "ortopedista". Lo aplicamos al caso inmobiliario en <a href="/blog/seo-local-para-inmobiliarias">SEO local para inmobiliarias</a>.
                    </p>
                    <p>
                        Y empieza por las que puedes ganar pronto. En nuestro propio blog, los artículos de nicho entraron a la primera página en pocas semanas, mientras que los temas generales siguen lejos. Esas primeras victorias te dan tráfico, datos y autoridad para ir después por las búsquedas más peleadas.
                    </p>
                </section>

                <section id="errores-comunes">
                    <h2>Errores comunes</h2>
                    <p>
                        Ordenados por lo que más cuestan:
                    </p>
                    <ol>
                        <li><strong>Elegir por volumen y no por intención.</strong> El caso del crédito promocional de Google Ads: miles de visitas que nunca te van a comprar. Es el error más caro porque además se come meses de contenido.</li>
                        <li><strong>Pelear la búsqueda más competida desde el día uno.</strong> "Abogados" o "paneles solares" a secas no se ganan con un sitio nuevo. Se ganan después, con autoridad acumulada.</li>
                        <li><strong>Hacer una página para cada variante.</strong> Tres artículos casi iguales se roban posiciones entre sí. Google entiende sinónimos; no tienes que escribir uno por cada forma de decirlo.</li>
                        <li><strong>Descartar todo lo que dice volumen cero.</strong> En nichos de alto ticket, muchas de las búsquedas que más venden no aparecen en las herramientas. Si tus clientes te lo preguntan en junta, alguien lo está buscando.</li>
                        <li><strong>Repetir la palabra hasta el cansancio.</strong> Meterla en cada párrafo cansa al lector, y Google considera el relleno de palabras clave como spam. Escribir natural, con sinónimos y frases relacionadas, ayuda más que repetir.</li>
                        <li><strong>Hacerla una vez y olvidarla.</strong> Las búsquedas cambian con los productos, las leyes y la temporada. Revisa tu lista cada trimestre con lo que te dice Search Console.</li>
                    </ol>
                </section>

                <section id="por-industria">
                    <h2>Cómo se ve esto en tu industria</h2>

                    <h3>Empresas de energía solar</h3>
                    <p>
                        Entre "paneles solares" y "cuánto cuesta instalar paneles solares en una casa en Monterrey" hay un mundo. La primera la pelean tiendas en línea y fabricantes; la segunda la escribe alguien que ya hizo cuentas con su recibo de luz. Las búsquedas de costo, financiamiento y ahorro son las que traen citas.
                    </p>

                    <h3>Clínicas y consultorios</h3>
                    <p>
                        El paciente busca primero el síntoma, después el tratamiento y al final al especialista con ciudad: "dolor de rodilla al subir escaleras", luego "artroscopia de rodilla recuperación", luego "ortopedista en Zapopan". Tener una página para cada etapa te pone frente a él antes que la competencia, que casi siempre aparece solo en la última.
                    </p>

                    <h3>Despachos jurídicos y contables</h3>
                    <p>
                        El cliente no busca en lenguaje legal. Escribe "me corrieron sin pagarme qué hago" o "multa del SAT por no declarar", no "despido injustificado" ni "requerimiento de la autoridad fiscal". Investigar cómo lo dice tu cliente es la diferencia entre aparecer y no existir.
                    </p>

