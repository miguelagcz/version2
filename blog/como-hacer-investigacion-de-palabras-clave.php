                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Cuál es la mejor herramienta gratis para buscar palabras clave?</summary>
                        <p>Para empezar te alcanza con tres herramientas gratuitas de Google: el autocompletado y las preguntas relacionadas del buscador para encontrar ideas, el Planificador de palabras clave de Google Ads para estimar volumen, y Search Console para ver qué búsquedas ya te traen impresiones. Las tres usan datos de Google, que al final es quien decide dónde apareces.</p>
                        <p>Las herramientas de paga, como Semrush o Ahrefs, valen la pena cuando ya publicas con frecuencia: te dan la dificultad, te dicen qué búsquedas le traen tráfico a tu competencia y te ahorran horas de trabajo manual. Para un negocio de alto ticket que apenas arranca, rinde más invertir ese dinero en escribir bien las primeras diez páginas que en una suscripción.</p>
                    </details>

                    <details>
                        <summary>¿Cuántas palabras clave debo usar en una página?</summary>
                        <p>Una principal y las variantes que buscan lo mismo. La principal va en el título, en el encabezado principal y en el primer párrafo; las variantes y las preguntas relacionadas aparecen de forma natural en los subtítulos y en las preguntas frecuentes. No hay un número correcto de repeticiones, y forzarlas es contraproducente.</p>
                        <p>La regla práctica es por intención, no por cantidad. Si dos búsquedas las resuelve la misma página, van juntas; si piden respuestas distintas, son dos páginas. Un artículo sobre el costo de un tratamiento puede cubrir quince formas de preguntar el precio, pero no debería intentar posicionar también para la recuperación de ese tratamiento.</p>
                    </details>

                    <details>
                        <summary>¿Qué son las palabras clave de cola larga?</summary>
                        <p>Son búsquedas más largas y específicas, como "despacho contable para constructoras en Querétaro" en lugar de "contador". Cada una tiene poco volumen, pero entre todas representan una parte enorme de lo que se busca, y quien las escribe ya sabe bastante bien lo que quiere.</p>
                        <p>Para un negocio de alto ticket son la mejor apuesta al empezar: menos competencia, una intención más clara y visitantes más cerca de comprar. Un sitio nuevo puede entrar a la primera página con ellas en semanas, mientras que las búsquedas cortas y genéricas toman meses o años de autoridad acumulada.</p>
                    </details>

                    <details>
                        <summary>¿Qué hago si mi palabra clave tiene volumen cero?</summary>
                        <p>No la descartes sin revisar. Volumen cero en una herramienta significa que la herramienta no alcanzó a medirla, no que nadie la busque. En nichos de alto ticket pasa todo el tiempo: las búsquedas son pocas, pero cada una puede ser un cliente de cientos de miles de pesos.</p>
                        <p>La prueba es sencilla. Si tus clientes te hacen esa pregunta en juntas, si aparece en el autocompletado de Google o si ya te llegan impresiones por ella en Search Console, existe. Escribe la página, mide tres meses y deja que los datos reales decidan. Muchas veces esas búsquedas que la herramienta marca en cero terminan siendo las que más prospectos traen.</p>
                    </details>

                    <details>
                        <summary>¿Cada cuánto tengo que hacer investigación de palabras clave?</summary>
                        <p>Una investigación a fondo al arrancar y una revisión cada tres meses. La revisión es más ligera: abres Search Console, ves qué búsquedas nuevas te están dando impresiones y cuáles bajaron, y ajustas la lista de las próximas páginas que vas a escribir.</p>
                        <p>Hay momentos que piden repetirla completa: cuando lanzas un servicio nuevo, entras a otra ciudad o cambia algo en tu industria, como una reforma fiscal o un programa de financiamiento. La forma en que tus clientes buscan cambia con esas noticias, y quien lo detecta primero se queda con esas búsquedas.</p>
                    </details>
