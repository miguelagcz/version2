                <section id="la-diferencia">
                    <h2>SEO y SEM: la diferencia en una frase</h2>
                    <p>
                        El <strong>SEO</strong> (posicionamiento orgánico) es el trabajo de que tu sitio aparezca en los resultados normales de Google sin pagar por cada clic. El <strong>SEM</strong> (marketing en buscadores) en la práctica significa anuncios pagados en Google, los resultados marcados como patrocinados que salen arriba y abajo de los orgánicos.
                    </p>
                    <p>
                        Algunos usan SEM como paraguas que incluye al SEO. En el día a día de cualquier agencia en México, cuando alguien dice SEM habla de <a href="/blog/que-es-google-ads-y-como-funciona">Google Ads</a>, y así lo vamos a usar aquí.
                    </p>
                    <p>
                        La mejor forma de entender la diferencia es pensar en un local comercial. Con Google Ads <strong>rentas</strong> el lugar: estás en la mejor esquina desde el primer día, pero el día que dejas de pagar te sacan. Con SEO <strong>compras</strong>: el enganche es alto, la escrituración tarda, pero cada mes que pasa el local es más tuyo y deja de depender de la renta.
                    </p>
                    <p>
                        Y una cosa que conviene tener clara desde el principio: Google no vende lugares en los resultados orgánicos. Los anuncios van marcados como tales y pagar por ellos no te sube ni un lugar en el orgánico. Son dos carriles distintos en la misma carretera.
                    </p>
                </section>

                <section id="como-funciona-cada-uno">
                    <h2>Cómo funciona cada uno</h2>

                    <h3>SEM: una subasta en cada búsqueda</h3>
                    <p>
                        Cada vez que alguien busca, Google hace una subasta instantánea entre los anunciantes que quieren aparecer. No gana el que más paga: Google combina tu puja con la calidad y relevancia de tu anuncio y de tu página, entre otros factores. Pagas solo cuando alguien hace clic, y normalmente menos de tu puja máxima. El detalle está en <a href="/blog/como-funciona-una-subasta-de-google-ads">cómo funciona una subasta de Google Ads</a> y en el <a href="/blog/quality-score-que-es-y-como-bajar-tu-costo-por-clic">Quality Score</a>.
                    </p>

                    <h3>SEO: ganarte el lugar</h3>
                    <p>
                        En orgánico no hay puja. Google decide quién aparece según qué tan bien responde cada página a la búsqueda, qué tan bien está hecha técnicamente y cuánta confianza le tiene al sitio. Eso se construye eligiendo bien las búsquedas con una <a href="/blog/como-hacer-investigacion-de-palabras-clave">investigación de palabras clave</a>, escribiendo páginas que respondan mejor que la competencia y consiguiendo <a href="/blog/link-building-enlaces-de-calidad">enlaces de calidad</a>.
                    </p>
                </section>

                <section id="frente-a-frente">
                    <h2>Frente a frente: velocidad, costo y duración</h2>
                    <ul>
                        <li><strong>Velocidad.</strong> SEM: visitas desde el día que activas la campaña. SEO: meses antes de ver tráfico relevante.</li>
                        <li><strong>Forma de pago.</strong> SEM: pagas cada clic, y el gasto crece con el tráfico. SEO: pagas el trabajo, y el tráfico extra no cuesta más.</li>
                        <li><strong>Duración del resultado.</strong> SEM: se apaga cuando dejas de pagar. SEO: una página bien posicionada puede seguir trayendo visitas por años, si la mantienes.</li>
                        <li><strong>Control.</strong> SEM: decides en qué búsquedas, ciudades, horarios y con qué mensaje apareces, y lo cambias en minutos. SEO: influyes, pero Google decide.</li>
                        <li><strong>Datos.</strong> SEM: te dice muy rápido qué búsquedas convierten en clientes. SEO: te da datos más lentos, pero de búsquedas que no tienes que pagar.</li>
                        <li><strong>Riesgo.</strong> SEM: si sube el costo por clic o entra un competidor con más presupuesto, tu costo por cliente sube. SEO: si Google cambia sus criterios o tu sitio tiene problemas técnicos, puedes perder posiciones.</li>
                    </ul>
                </section>

                <section id="cuando-invertir">
                    <h2>Cuándo conviene invertir en cada uno</h2>

                    <h3>Empieza por SEM si...</h3>
                    <ul>
                        <li><strong>Necesitas ventas este trimestre.</strong> El SEO no te va a salvar el mes; los anuncios sí pueden.</li>
                        <li><strong>Tienes un lanzamiento con fecha.</strong> Una preventa, una apertura, una temporada. Para cuando el SEO madure, la ventana ya pasó.</li>
                        <li><strong>No sabes qué búsquedas te traen clientes.</strong> Cuatro a seis semanas de campañas bien medidas te dicen qué frases convierten. Después construyes páginas de SEO para esas, en lugar de adivinar.</li>
                    </ul>

                    <h3>Empieza por SEO si...</h3>
                    <ul>
                        <li><strong>Tu nicho tiene poco volumen y poca competencia.</strong> Ahí una página buena entra rápido a la primera página, y en anuncios a veces ni hay volumen suficiente para gastar el presupuesto.</li>
                        <li><strong>Tus clics son carísimos.</strong> En búsquedas legales, financieras o médicas, cada clic puede costar mucho. Cada visita orgánica que consigues ahí vale ese mismo dinero.</li>
                        <li><strong>Tu cliente investiga mucho antes de comprar.</strong> Ciclos largos, decisiones grandes. Estar presente con contenido útil en cada etapa de su investigación es trabajo de SEO.</li>
                    </ul>

                    <h3>Cómo repartir el presupuesto</h3>
                    <p>
                        Un punto de partida razonable para un negocio de alto ticket que empieza de cero: la mayor parte en anuncios para generar ventas desde ya, y una parte fija en SEO para construir el canal que con el tiempo baja tu costo por cliente. Conforme las páginas orgánicas empiezan a traer prospectos, mueves presupuesto de los anuncios hacia donde todavía no posicionas.
                    </p>
                    <p>
                        La proporción exacta depende de tus números, no de una regla. Lo que no conviene es poner todo en uno: solo anuncios te deja dependiendo de la subasta para siempre, y solo SEO te deja meses sin ventas.
                    </p>
                </section>

                <section id="juntos">
                    <h2>Por qué funcionan mejor juntos</h2>
                    <p>
                        El argumento más fuerte para combinarlos es que se alimentan. El informe de términos de búsqueda de Google Ads te dice con dinero real qué frases traen clientes; esas son las páginas que conviene construir para SEO. Y el SEO te permite bajar la puja en búsquedas donde ya apareces arriba, para mover ese presupuesto a donde todavía no.
                    </p>
                    <p>
                        También cubren momentos distintos. El anuncio atrapa al que está listo para contratar hoy; el contenido orgánico atrapa al que apenas está investigando y regresa semanas después, cuando ya confía en ti. En negocios de ciclo largo, ese segundo cliente es la mayoría.
                    </p>
                    <p>
                        Y no olvides limpiar la campaña: las búsquedas que solo traen curiosos se bloquean con <a href="/blog/palabras-clave-negativas">palabras clave negativas</a>, y de paso te dicen qué temas informativos le tocan al blog y no a la publicidad. Si además estás evaluando redes sociales, la comparación con el otro gran canal pagado está en <a href="/blog/facebook-ads-vs-google-ads">Facebook Ads vs Google Ads</a>.
                    </p>
                </section>

                <section id="por-industria">
                    <h2>Cómo se ve esto en tu industria</h2>

                    <h3>Desarrolladoras inmobiliarias</h3>
                    <p>
                        La preventa tiene fecha, así que los anuncios llevan el peso del lanzamiento: búsquedas de zona y tipo de propiedad que ya tienen intención de compra, como explicamos en <a href="/blog/google-ads-para-inmobiliarias">Google Ads para inmobiliarias</a>. El SEO trabaja en paralelo para la marca de la desarrolladora y para las zonas donde vas a construir los próximos años, con la estructura que describimos en <a href="/blog/seo-para-desarrollos-inmobiliarios">SEO para desarrollos inmobiliarios</a>.
                    </p>

                    <h3>Empresas de energía solar</h3>
                    <p>
                        La demanda sube con el calor y con los recibos de luz altos. Los anuncios te dejan acelerar en esos meses y frenar en los flojos. El SEO captura todo el año las búsquedas de costo, ahorro y financiamiento, que la gente hace meses antes de decidir.
                    </p>

                    <h3>Despachos jurídicos y contables</h3>
                    <p>
                        Suelen tener de los clics más caros, lo que hace que cada visita orgánica valga mucho. Aquí conviene invertir en SEO desde temprano en las búsquedas de problema ("me despidieron sin liquidación", "multa del SAT") y reservar los anuncios para las búsquedas de contratación inmediata.
                    </p>

                    <h3>Industrial B2B</h3>
                    <p>
                        Volúmenes chicos y búsquedas muy específicas: números de parte, normas, aplicaciones. El SEO suele ganar rápido porque la competencia en contenido es floja, y los anuncios funcionan bien con concordancia muy precisa en esos mismos términos, sin desperdiciar presupuesto en búsquedas genéricas.
                    </p>
                </section>

                <section id="como-medirlo">
                    <h2>Cómo medirlo y qué esperar</h2>
                    <p>
                        La métrica que permite comparar los dos canales es el <strong>costo por cliente</strong>: inversión del mes entre clientes conseguidos por ese canal. Para que funcione necesitas saber de dónde llegó cada prospecto, así que antes de invertir en cualquiera de los dos, configura la medición de formularios, llamadas y WhatsApp.
                    </p>
                    <p>
                        En SEM, la lectura es casi inmediata: en unas semanas sabes cuánto te cuesta cada prospecto. En SEO, compara trimestre contra trimestre: impresiones y posiciones en Search Console primero, prospectos orgánicos después. Los plazos realistas están en <a href="/blog/cuanto-tarda-el-seo-en-dar-resultados">cuánto tarda el SEO en dar resultados</a>.
                    </p>
                    <p>
                        Lo que deberías ver a los seis meses de combinarlos: anuncios estables o con menos gasto en búsquedas donde ya posicionas, y una parte creciente de tus prospectos llegando sin que pagues el clic.
                    </p>
                </section>

