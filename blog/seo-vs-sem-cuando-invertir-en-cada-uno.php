                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Qué es mejor, SEO o SEM?</summary>
                        <p>Ninguno es mejor en abstracto; resuelven problemas distintos. El SEM te da visibilidad inmediata y control total sobre cuánto gastas y en qué búsquedas apareces, pero se apaga el día que dejas de pagar. El SEO tarda meses en despegar, pero el lugar que ganas no depende de tu presupuesto diario y sigue trayendo visitas cuando no estás invirtiendo.</p>
                        <p>La pregunta útil es cuál necesitas primero. Si necesitas ventas este trimestre, empieza por SEM. Si tu negocio ya vende y quieres bajar tu costo por cliente a mediano plazo, invierte en SEO. Para la mayoría de los negocios de alto ticket la respuesta termina siendo los dos, en distinta proporción según la etapa.</p>
                    </details>

                    <details>
                        <summary>¿Pagar Google Ads mejora mi posicionamiento orgánico?</summary>
                        <p>No. Google lo dice de forma explícita: los anunciantes no pueden pagar para aparecer más arriba en los resultados orgánicos, y la publicidad no le da ninguna ventaja a tu sitio en el posicionamiento. Son dos sistemas separados que comparten la misma página de resultados.</p>
                        <p>Lo que sí pasa es indirecto. Las campañas te dan datos de qué búsquedas convierten, y esa información te ayuda a decidir qué páginas crear para SEO. Además, la gente que conoce tu marca por un anuncio puede buscarte después por nombre. Pero ninguna de las dos cosas es un premio de Google por gastar.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto cuesta el SEO comparado con Google Ads?</summary>
                        <p>Se cobran distinto, así que hay que compararlos por costo por cliente, no por factura mensual. En Google Ads pagas por cada clic, y en búsquedas competidas de alto ticket un solo clic puede costar decenas o cientos de pesos. En SEO pagas el trabajo de crear y mejorar páginas y conseguir enlaces, y ese costo no sube con cada visita.</p>
                        <p>Por eso la comparación cambia con el tiempo. Los primeros meses, el SEO sale caro por cliente porque todavía no trae tráfico. Cuando las páginas ya posicionan, cada cliente orgánico cuesta una fracción de lo que costaría por anuncios. La cuenta correcta es inversión entre clientes conseguidos, mes contra mes, en cada canal.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto tarda cada uno en dar resultados?</summary>
                        <p>Una campaña de Google Ads bien armada puede generar clics y prospectos desde el primer día, aunque necesita unas semanas de datos para optimizarse. El SEO normalmente tarda meses: Google tiene que rastrear, indexar y ganar confianza en tus páginas antes de mostrarlas arriba.</p>
                        <p>Los plazos del SEO dependen mucho de la competencia. En búsquedas de nicho, una página buena puede entrar a la primera página en semanas; en búsquedas muy peleadas puede tomar uno o dos años. Lo desglosamos en la guía de cuánto tarda el SEO en dar resultados.</p>
                    </details>

                    <details>
                        <summary>¿Puedo dejar de pagar Google Ads cuando ya posicione con SEO?</summary>
                        <p>En algunas búsquedas sí. Si ya apareces arriba en orgánico para una búsqueda y tus anuncios en esa misma búsqueda casi no suman clientes nuevos, puedes bajar la inversión ahí y moverla a búsquedas donde todavía no posicionas. Esa es justo la forma sana de combinarlos.</p>
                        <p>Apagar todo de golpe suele ser un error. En búsquedas comerciales los anuncios ocupan los primeros lugares de la página, y tu competencia puede quedarse con ese espacio. Haz la prueba por grupos de búsquedas, mide cuántos clientes pierdes o no, y decide con esos datos.</p>
                    </details>
