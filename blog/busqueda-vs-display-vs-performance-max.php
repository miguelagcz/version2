                <section id="campanas-de-busqueda">
                    <h2>Campañas de Búsqueda</h2>
                    <p>
                        Son los anuncios de texto que aparecen dentro de los resultados de Google cuando alguien escribe una búsqueda. Es el formato de mayor intención: la persona ya está buscando activamente algo, no la estás interrumpiendo mientras hace otra cosa. Por eso suele ser el punto de entrada recomendado para casi cualquier negocio que empieza en Google Ads.
                    </p>
                    <p>
                        Un detalle que mucha gente no sabe: puedes habilitar lo que Google llama expansión en Display para tus campañas de Búsqueda, que usa el presupuesto de Búsqueda que no se gastó para conseguir conversiones adicionales en la Red de Display, manteniendo la configuración de tu campaña original. Es una forma de extender tu alcance sin crear una campaña completamente nueva desde cero.
                    </p>
                </section>

                <section id="campanas-de-display">
                    <h2>Campañas de Display</h2>
                    <p>
                        Son anuncios visuales, con imágenes o formatos HTML5, que aparecen en una red de millones de sitios web y aplicaciones (Google la describe en más de 35 millones de sitios y apps en todo el mundo), además de en propiedades propias de Google como YouTube y Gmail.
                    </p>
                    <p>
                        La diferencia de fondo frente a Búsqueda es el momento del ciclo de compra que capturas. Mientras que Búsqueda te conecta con alguien que ya está buscando activamente tu producto o servicio, Display te permite captar la atención de esa persona en una etapa mucho más temprana, antes de que sepa exactamente qué quiere o incluso antes de que sepa que tu negocio existe. Por eso Display suele rendir mejor para generar reconocimiento de marca que para cerrar una venta inmediata.
                    </p>
                </section>

                <section id="performance-max">
                    <h2>Performance Max</h2>
                    <p>
                        Es el tipo de campaña más reciente y el que Google empuja con más fuerza dentro de la plataforma. Performance Max usa inteligencia artificial para distribuir un mismo presupuesto entre todos los canales de Google a la vez (Búsqueda, Display, YouTube, Gmail, Maps y Shopping), a partir de la información que tú le das sobre tu negocio, tus objetivos y qué conversiones te importan medir.
                    </p>
                    <p>
                        Google recomienda esta opción cuando tu negocio ya tiene objetivos de conversión claros (más ventas en línea, más leads) y cuando quieres maximizar resultados sin restringir en qué canales específicos aparecen tus anuncios. La contraparte de esa comodidad es el control: le entregas a la IA de Google buena parte de las decisiones sobre dónde y cómo mostrar tu anuncio, que en Búsqueda o Display manejarías tú mismo de forma más directa.
                    </p>
                </section>

                <section id="tabla-comparativa">
                    <h2>Comparación directa</h2>
                    <ul>
                        <li><strong>Intención del usuario.</strong> Búsqueda: alta, la persona ya busca algo específico. Display: baja a media, la interrumpes mientras hace otra cosa. Performance Max: mixta, según en qué canal termine mostrándose cada anuncio.</li>
                        <li><strong>Mejor para.</strong> Búsqueda: capturar demanda existente. Display: generar reconocimiento de marca. Performance Max: maximizar conversiones a través de todos los canales a la vez.</li>
                        <li><strong>Nivel de control manual.</strong> Búsqueda: alto. Display: alto. Performance Max: bajo, gran parte de las decisiones las toma la IA de Google.</li>
                        <li><strong>Qué tan pronto conviene usarla.</strong> Búsqueda: desde el primer día. Display: cuando ya tienes claro tu mensaje de marca. Performance Max: cuando ya acumulaste suficientes datos de conversión para que el sistema aprenda bien.</li>
                    </ul>
                </section>

                <section id="cual-elegir">
                    <h2>¿Cuál conviene según tu etapa de negocio?</h2>
                    <p>
                        Si apenas estás empezando y todavía no tienes historial de conversiones en tu cuenta, Búsqueda sigue siendo la opción más segura: te permite entender qué palabras clave, anuncios y páginas de destino funcionan mejor, con el mayor control posible sobre cada variable.
                    </p>
                    <p>
                        Si ya tienes una campaña de Búsqueda funcionando de forma estable y quieres ampliar tu alcance sin duplicar el trabajo de configuración desde cero, la expansión en Display dentro de tu campaña actual suele ser un paso intermedio razonable antes de saltar directo a una campaña de Display independiente o a Performance Max. Y si ya llevas meses acumulando datos de conversión sólidos y quieres simplificar la administración de varios canales a la vez, ese es el momento en que Performance Max empieza a tener sentido real, no antes.
                    </p>
                    <p>
                        Un apunte sobre el mercado mexicano: en industrias de alto ticket como desarrollo inmobiliario o energía solar, el costo por clic en Búsqueda suele ser considerablemente más alto que el promedio general, porque hay pocos anunciantes peleando por búsquedas muy valiosas. Eso no la descarta, la hace más rentable de lo que parece cuando el valor de un solo cliente cerrado justifica varios miles de pesos de inversión. En cambio, saltar a Performance Max con un presupuesto mensual bajo y sin historial de conversiones suele traducirse en gasto repartido sin aprendizaje en ninguno de los canales.
                    </p>
                </section>

