                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Puedo tener campañas de Búsqueda y Performance Max al mismo tiempo?</summary>
                        <p>Sí, y muchos negocios que ya tienen tracción lo hacen. Sin embargo, vale la pena tener cuidado con la segmentación de palabras clave y audiencias entre ambas, porque Performance Max puede terminar compitiendo internamente contra tu propia campaña de Búsqueda por las mismas búsquedas, lo que en la práctica significa competir contra ti mismo en la subasta. Antes de correr ambas a la vez, conviene revisar qué tan solapadas están tus configuraciones para evitar ese conflicto.</p>
                    </details>

                    <details>
                        <summary>¿Display sirve para generar ventas directas o solo para reconocimiento de marca?</summary>
                        <p>Puede generar ventas directas, pero no es su punto más fuerte comparado con Búsqueda. Display funciona mejor cuando el objetivo es que más gente conozca tu marca, tu producto o tu desarrollo, o cuando quieres reforzar presencia frente a alguien que ya te conoció por otro canal, como en una estrategia de remarketing. Esperar el mismo tipo de conversión inmediata que obtienes en Búsqueda suele llevar a decepciones, no porque Display esté mal configurado, sino porque está resolviendo un problema distinto.</p>
                    </details>

                    <details>
                        <summary>¿Performance Max reemplaza por completo a las campañas de Búsqueda?</summary>
                        <p>No necesariamente, aunque Google la posiciona como una opción muy completa. Performance Max te da alcance en todos los canales con menos trabajo manual, pero a cambio de menos visibilidad sobre exactamente qué palabra clave o qué canal específico generó cada resultado. Muchos anunciantes con experiencia prefieren mantener una campaña de Búsqueda separada, con control total, mientras usan Performance Max para capturar el resto del potencial que una campaña de Búsqueda sola no alcanzaría a cubrir.</p>
                    </details>

                    <details>
                        <summary>¿Necesito recursos creativos distintos para cada tipo de campaña?</summary>
                        <p>Sí, en distinta medida. Búsqueda solo requiere texto (títulos y descripciones), sin necesidad de imágenes. Display sí requiere recursos visuales, ya sea imágenes que subas tú o anuncios adaptables que Google arma automáticamente a partir de elementos que le proporcionas. Performance Max necesita el conjunto más amplio de recursos, porque puede combinar texto, imágenes y hasta video, y entre más variedad de buena calidad le des, mejor puede optimizar en qué canal usar cada uno.</p>
                    </details>

                    <details>
                        <summary>¿Cuál de los tres tiene el costo por clic más bajo?</summary>
                        <p>No hay una regla fija, porque depende mucho de tu industria y de qué tan bien configurada esté cada campaña. En términos generales, Display suele tener un costo por clic más bajo que Búsqueda, precisamente porque la intención de compra es menor y hay más espacio publicitario disponible. Pero un costo por clic bajo con pocas conversiones puede salir más caro a largo plazo que un costo por clic alto con muchas conversiones, así que comparar solo el costo por clic entre formatos sin ver las conversiones que produce cada uno es una forma común de sacar conclusiones equivocadas.</p>
                    </details>
