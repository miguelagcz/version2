                    </details>

                    <details>
                        <summary>¿Cuánto presupuesto debería destinar a retargeting frente a captación de tráfico frío?</summary>
                        <p>No existe una proporción universal correcta, porque depende de cuánto tráfico frío estás generando y qué tan largo es tu ciclo de decisión, pero una referencia común en la industria es destinar entre el 10% y el 20% del presupuesto total a retargeting cuando el negocio todavía está en fase de crecimiento y necesita generar volumen de tráfico frío nuevo constantemente. Para negocios de alto ticket con ciclos de decisión largos, como una desarrolladora inmobiliaria, esa proporción puede subir considerablemente, incluso hasta el 30% o 40%, porque el valor de recuperar a alguien que ya mostró interés real en una compra de varios millones de pesos suele justificar una inversión mayor que en negocios de ticket más bajo y ciclo de decisión más corto. La forma más confiable de encontrar tu proporción ideal es comparar el ROAS de tus campañas de retargeting contra el de tus campañas de captación, y ajustar el presupuesto hacia donde el retorno sea consistentemente mejor.</p>
                    </details>

                    <details>
                        <summary>¿Puedo hacer retargeting sin tener el Pixel de Meta instalado?</summary>
                        <p>De forma limitada, sí, pero no vas a poder aprovechar todo el potencial de la estrategia. Sin el Pixel instalado en tu sitio web, no puedes crear públicos personalizados basados en visitantes específicos de tu página, que suele ser la forma más efectiva y precisa de hacer retargeting. Sin embargo, sí es posible construir públicos personalizados a partir de otras fuentes que no dependen del Pixel, como personas que interactuaron con tu página de Facebook o cuenta de Instagram, quienes vieron un porcentaje relevante de tus videos, o una lista de clientes que subas directamente desde tu propia base de datos. Estas alternativas funcionan como un punto de partida razonable mientras instalas correctamente el Pixel y la API de Conversiones, pero no sustituyen del todo la precisión que da poder segmentar por comportamiento real dentro de tu sitio web.</p>
                    </details>

                    <details>
                        <summary>¿Cada cuánto debo cambiar el creativo de mis campañas de retargeting?</summary>
                        <p>No existe un calendario fijo que aplique a todas las cuentas, pero una señal más confiable que el simple paso del tiempo es la métrica de frecuencia dentro del Administrador de Anuncios: cuando la frecuencia de un anuncio de retargeting empieza a subir de forma sostenida (por ejemplo, más de tres o cuatro impresiones promedio por persona dentro de la ventana de tu campaña) sin que el CTR se mantenga estable, suele ser el momento de rotar el creativo o el mensaje. Como referencia general, muchas cuentas actualizan sus creativos de retargeting cada dos a cuatro semanas para negocios con ciclos de decisión más cortos, y con menor frecuencia (cada mes o mes y medio) para negocios de alto ticket donde el mismo público permanece en la ventana de retargeting durante más tiempo. Lo importante no es cambiar por cambiar, sino observar cuándo el rendimiento empieza a deteriorarse y actuar en ese momento.</p>
                    </details>

                    <details>
                        <summary>¿El retargeting funciona igual de bien para negocios nuevos sin tráfico todavía?</summary>
                        <p>No, y esta es una de las confusiones más comunes entre negocios que apenas empiezan a anunciarse. El retargeting depende directamente de tener tráfico previo (visitantes del sitio, interacciones con tu contenido, video vistos) para poder construir un público sobre el cual retargetear; sin ese tráfico inicial, simplemente no existe una base de personas a quienes mostrarles el anuncio de seguimiento. Para un negocio completamente nuevo, la secuencia lógica es primero invertir en campañas de captación de tráfico frío durante algunas semanas para empezar a generar visitantes y datos dentro del Pixel, y solo después activar campañas de retargeting sobre ese público que ya empezó a acumularse. Intentar lanzar retargeting antes de tener suficiente volumen de tráfico previo suele resultar en públicos demasiado pequeños para que Meta pueda entregar el anuncio de forma eficiente.</p>
                    </details>
