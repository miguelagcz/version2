                <section id="que-es-retargeting">
                    <h2>Qué es el retargeting (remarketing)</h2>
                    <p>
                        El retargeting, o remarketing, es la práctica de mostrar anuncios específicamente a personas que ya tuvieron algún tipo de contacto con tu negocio: visitaron tu sitio web, vieron un video tuyo, iniciaron un formulario sin terminarlo, o interactuaron con tu página de Facebook o cuenta de Instagram. En lugar de competir por la atención de alguien que nunca ha oído hablar de ti, le hablas a alguien que ya conoce tu marca y que, por alguna razón, todavía no dio el siguiente paso.
                    </p>
                    <p>
                        Dentro de Meta Ads, el retargeting se construye sobre la base de los públicos personalizados que explicamos en nuestro artículo dedicado a <a href="/blog/publicos-personalizados-y-lookalike">públicos personalizados y lookalike</a>: visitantes del sitio web, quienes vieron cierto porcentaje de un video, o quienes iniciaron pero no completaron un formulario instantáneo.
                    </p>
                </section>

                <section id="por-que-importa">
                    <h2>Por qué el retargeting suele ser tu campaña más rentable</h2>
                    <p>
                        Una campaña de retargeting le habla a un público mucho más pequeño y mucho más calificado que una campaña de captación de tráfico frío, lo que casi siempre se traduce en un CTR más alto y un costo por resultado (CPA) más bajo. Estas personas ya superaron la barrera más difícil, que es descubrir que tu negocio existe; lo único que falta es darles la razón, la confianza o el empujón final que necesitan para completar la conversión. Por esta razón, muchas cuentas de Meta Ads reservan una porción fija de su presupuesto exclusivamente para retargeting, incluso cuando el grueso de la inversión sigue destinado a la captación de tráfico nuevo.
                    </p>
                </section>

                <section id="como-configurarlo">
                    <h2>Cómo configurar una campaña de retargeting</h2>
                    <ul>
                        <li>Confirma que el Pixel de Meta y, de preferencia, la API de Conversiones estén correctamente instalados en tu sitio web, ya que sin ellos no existe forma de identificar quién visitó qué página.</li>
                        <li>Crea un público personalizado basado en visitantes del sitio web, ajustando la ventana de tiempo según tu ciclo de decisión (más sobre esto en la siguiente sección).</li>
                        <li>Si tienes suficiente volumen, segmenta ese público por página visitada; alguien que vio una propiedad específica dentro de tu sitio merece un mensaje distinto a alguien que solo vio la página de inicio.</li>
                        <li>Excluye de tu público de retargeting a quienes ya completaron la conversión, para no seguir gastando presupuesto en mostrarles un anuncio de captación que ya no les aplica.</li>
                        <li>Diseña un creativo y un copy específico para retargeting, distinto al anuncio original que vio esa persona la primera vez.</li>
                        <li>Asigna un presupuesto independiente a esta campaña, separado del presupuesto de captación de tráfico frío, para poder medir su rendimiento de forma clara.</li>
                    </ul>
                </section>

                <section id="ventanas-de-tiempo">
                    <h2>Qué ventana de tiempo usar según tu ciclo de decisión</h2>
                    <p>
                        La ventana de tiempo de un público personalizado (7, 14, 30, 60 o hasta 180 días) debería reflejar qué tan largo es el ciclo de decisión real de tu negocio, no un número elegido al azar. Para un negocio de bajo costo con una decisión rápida, una ventana corta de 7 a 14 días suele ser suficiente, porque quien no convirtió en ese periodo probablemente ya perdió el interés. Para un negocio de alto ticket, como una desarrolladora inmobiliaria o una empresa de energía solar, donde el ciclo de decisión puede extenderse varias semanas o incluso meses, ventanas más largas de 60 a 180 días capturan a personas que siguen genuinamente interesadas, aunque todavía no estén listas para dar el siguiente paso.
                    </p>
                </section>

                <section id="segmentar-por-comportamiento">
                    <h2>Segmentar el retargeting por comportamiento, no solo por visita</h2>
                    <p>
                        No toda visita al sitio web representa el mismo nivel de interés, así que tratarlas todas igual dentro de una sola campaña de retargeting desperdicia una oportunidad importante de personalización. Alguien que solo vio la página de inicio durante quince segundos no está en el mismo punto que alguien que revisó varias páginas de propiedades, calculó su crédito hipotecario o inició un formulario sin terminarlo. Crear públicos personalizados separados para cada uno de estos comportamientos, con un mensaje ajustado a su nivel de interés, casi siempre supera en rendimiento a una sola campaña de retargeting genérica dirigida a "cualquiera que visitó el sitio".
                    </p>
                </section>

                <section id="mensaje-distinto">
                    <h2>Por qué el mensaje debe ser distinto al anuncio original</h2>
                    <p>
                        Mostrarle exactamente el mismo anuncio que la persona ya vio e ignoró la primera vez rara vez cambia el resultado; en el mejor de los casos genera indiferencia, y en el peor, fatiga y hasta rechazo activo hacia la marca. Un buen anuncio de retargeting suele incluir información nueva que no estaba en el anuncio original: un testimonio, una actualización de avance de obra, una pregunta frecuente resuelta, o una oferta por tiempo limitado. La idea es continuar la conversación, no repetirla.
                    </p>
                </section>

                <section id="frecuencia-y-fatiga">
                    <h2>Frecuencia y fatiga: el límite del retargeting</h2>
                    <p>
                        Aunque el retargeting le habla a un público más receptivo, sigue existiendo un límite razonable de cuántas veces conviene mostrarle un anuncio a la misma persona. Una frecuencia demasiado alta dentro de una ventana corta de tiempo puede pasar de sentirse como un recordatorio útil a sentirse invasivo, lo que eventualmente se traduce en comentarios negativos, ocultamientos del anuncio o simplemente una caída en el CTR. Revisar la métrica de frecuencia dentro del Administrador de Anuncios y rotar el creativo cuando empieza a subir de forma sostenida ayuda a mantener el retargeting efectivo sin cruzar esa línea.
                    </p>
                </section>

                <section id="retargeting-por-industria">
                    <h2>Retargeting aplicado a inmobiliaria y energía solar</h2>
                    <p>
                        Para una desarrolladora inmobiliaria, un retargeting efectivo suele mostrar, unos días después de la primera visita, un testimonio en video de un comprador reciente, seguido más adelante por una actualización del avance de obra si el prospecto sigue sin convertir después de varias semanas. Para una empresa de energía solar, un retargeting bien pensado puede empezar con contenido educativo adicional (por ejemplo, resolviendo la objeción más común sobre el mantenimiento de los paneles) y avanzar, con el tiempo, hacia una oferta de evaluación gratuita del techo o el consumo eléctrico, siempre respetando que el ciclo de decisión en ambos sectores suele ser más largo que en la mayoría de las industrias.
                    </p>
                </section>

