                        <summary>¿Cuánto tiempo tarda un lead de energía solar en convertirse en una instalación cerrada?</summary>
                        <p>El ciclo de decisión en energía solar suele extenderse desde varias semanas hasta unos cuantos meses, porque implica una inversión considerable y, en muchos casos, la comparación de varias cotizaciones antes de decidir. Este ciclo tiende a ser más corto cuando la empresa ofrece financiamiento accesible y responde con rapidez a cada duda del prospecto, y más largo cuando la decisión involucra a varias personas dentro de una familia o un negocio, o cuando existe una remodelación o construcción pendiente que debe resolverse antes de instalar el sistema. Por esta razón, medir el éxito de una campaña únicamente por el volumen de leads generados en el primer mes puede dar una imagen incompleta; es más confiable dar seguimiento a las cohortes de leads durante varios meses para entender la verdadera tasa de conversión y el tiempo real que toma cerrar una venta en tu mercado específico.</p>
                    </details>

                    <details>
                        <summary>¿Qué es la medición neta y por qué debería mencionarla en mis anuncios?</summary>
                        <p>La medición neta (net metering) es el mecanismo mediante el cual la Comisión Federal de Electricidad absorbe, durante el día, la energía que produce tu sistema fotovoltaico y no consumes de inmediato, y te permite usar ese excedente como créditos para cubrir tu consumo durante la noche, cuando los paneles no generan electricidad. Explicar este concepto de forma simple es importante en tus anuncios y landing pages porque resuelve una de las dudas más comunes de quien nunca ha tenido paneles solares: qué pasa cuando no hay sol. Un prospecto que entiende que no necesita baterías costosas ni se queda sin electricidad por las noches, gracias a este mecanismo, avanza con mucha más confianza hacia la siguiente etapa del embudo que alguien a quien nunca se le explicó cómo funciona este proceso.</p>
                    </details>

                    <details>
                        <summary>¿Debo usar Facebook Ads o Google Ads para mi empresa de energía solar?</summary>
                        <p>Al igual que en otras industrias de alto ticket, la combinación de ambos suele funcionar mejor que elegir uno solo, como explicamos con más detalle en <a href="/blog/facebook-ads-vs-google-ads">Facebook Ads vs Google Ads</a>. Facebook Ads suele ser especialmente útil en las etapas tempranas, porque la mayoría de las personas todavía no está buscando activamente "instalación de paneles solares" en Google, sino que necesita primero descubrir que la energía solar es una opción viable para su situación específica, algo que un anuncio educativo en redes sociales logra mejor que esperar a que la búsqueda ya exista. Google Ads se vuelve cada vez más valioso conforme el prospecto avanza en su proceso de decisión y empieza a comparar activamente proveedores, momento en el que capturar esa búsqueda directa suele generar leads más calificados y cerca del cierre.</p>
                    </details>

                    <details>
                        <summary>¿Cómo distingo un lead de energía solar residencial de uno comercial o industrial en mis campañas?</summary>
                        <p>La forma más práctica es separar tus campañas y tus formularios desde el inicio, preguntando directamente en la calculadora o el formulario de contacto si la persona busca una solución para su hogar o para su negocio, ya que el perfil de consumo, el ticket promedio y el proceso de decisión son bastante distintos entre ambos casos. Un lead residencial suele tener un ciclo de decisión más corto y un ticket más bajo que un lead comercial o industrial, donde la instalación puede ser considerablemente más grande y la decisión suele involucrar a más de una persona dentro de la empresa, además de un análisis financiero más formal. Separar estos dos públicos desde la segmentación de tus campañas, con mensajes y ofertas adaptadas a cada uno, generalmente produce mejores resultados que un anuncio genérico que intenta hablarle a ambos perfiles al mismo tiempo.</p>
                    </details>
