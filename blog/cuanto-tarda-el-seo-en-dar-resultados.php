                <section id="respuesta-corta">
                    <h2>La respuesta corta: entre cuatro meses y un año</h2>
                    <p>
                        Google lo dice en su propia documentación sobre contratar a un especialista en SEO: los
                        resultados tardan, y por lo general los beneficios de los cambios que haces empiezan a
                        notarse en un rango que va de cuatro meses a un año. No es una estimación de agencia. Es la
                        cifra que publica el buscador para el que estás optimizando.
                    </p>
                    <p>
                        En la guía para principiantes lo matiza todavía más: algunos cambios pueden reflejarse en
                        unas horas, otros pueden tardar meses, y lo razonable es esperar varias semanas antes de
                        juzgar si una modificación tuvo efecto positivo. Google incluso advierte que no todos los
                        cambios que hagas van a mover la aguja, y sugiere repetir el experimento si el resultado no
                        convence.
                    </p>
                    <p>
                        Traducido a lenguaje de negocio: si tu horizonte de decisión es un trimestre, el SEO
                        difícilmente va a caber ahí como canal principal. Si tu horizonte es un año, es de las
                        inversiones con mejor retorno que existen, porque el tráfico que construyes no se apaga
                        cuando dejas de pagar.
                    </p>
                </section>

                <section id="por-que-tarda">
                    <h2>Por qué tarda tanto</h2>
                    <p>
                        No es burocracia ni mala voluntad del buscador. Son cuatro procesos encadenados, y ninguno se
                        puede saltar.
                    </p>
                    <h3>Primero hay que ser encontrado</h3>
                    <p>
                        Google descubre páginas principalmente siguiendo enlaces desde otras páginas que ya rastreó.
                        Una URL nueva en un sitio con poca autoridad puede tardar días o semanas en ser visitada por
                        el rastreador. Un sitemap ayuda, y solicitar el rastreo desde Search Console también, pero
                        ninguno de los dos garantiza indexación inmediata.
                    </p>
                    <h3>Después hay que ser entendido</h3>
                    <p>
                        Rastrear no es indexar. El buscador tiene que procesar la página, decidir si aporta algo que
                        no exista ya en su índice y ubicarla temáticamente. Si tu página está mal construida, si
                        bloquea recursos que el rastreador necesita o si duplica contenido de otra URL tuya, ese paso
                        se complica. Aquí es donde el trabajo de
                        <a href="/blog/seo-on-page-checklist">SEO on-page</a> y el de
                        <a href="/blog/seo-tecnico-velocidad-indexacion-errores">SEO técnico</a> se cobran solos.
                    </p>
                    <h3>Luego hay que competir</h3>
                    <p>
                        Aunque tu página sea excelente, entra a una subasta de relevancia contra páginas que llevan
                        años acumulando enlaces, tráfico y señales. Escalar posiciones es un proceso gradual: primero
                        apareces en la página cinco, luego en la tres, luego peleas por el top diez. Cada escalón
                        depende de que el buscador junte evidencia suficiente.
                    </p>
                    <h3>Y por último hay que acumular</h3>
                    <p>
                        El SEO compone. Cada artículo publicado enlaza a los anteriores, cada enlace externo que
                        llega reparte autoridad hacia adentro, cada mes de historial le da al buscador más datos
                        sobre tu sitio. Por eso los resultados no son lineales: los primeros meses parece que no pasa
                        nada y después la curva se acelera. Ese efecto acumulado es también la razón por la que el
                        <a href="/blog/link-building-enlaces-de-calidad">link building</a> tarda más que cualquier
                        otra parte del trabajo.
                    </p>
                </section>

                <section id="linea-de-tiempo">
                    <h2>Qué pasa mes a mes en un proyecto real</h2>
                    <p>
                        Esta es la secuencia que vemos en proyectos de alto ticket, con un sitio que ya existe y un
                        equipo publicando de forma constante. No es una promesa: es el orden en que suelen aparecer
                        las señales.
                    </p>
                    <ul>
                        <li><strong>Mes 1.</strong> Auditoría, corrección de errores técnicos, definición del mapa de contenidos y de la palabra clave de cada página. Casi nada visible hacia afuera. Es el mes que más determina todo lo demás.</li>
                        <li><strong>Mes 2.</strong> Optimización on-page de las páginas comerciales y publicación del primer contenido. Empiezan a aparecer impresiones nuevas en Search Console para términos que antes no registrabas.</li>
                        <li><strong>Mes 3.</strong> Movimiento en posición promedio. Términos de cola larga y muy específicos empiezan a rankear, normalmente los primeros. Todavía hay poco clic.</li>
                        <li><strong>Meses 4 a 6.</strong> Aquí entra el rango que marca Google. Aparecen los primeros clics con intención real y, en negocios de ticket alto, las primeras solicitudes de contacto atribuibles al canal orgánico.</li>
                        <li><strong>Meses 6 a 12.</strong> Los términos de más volumen y competencia empiezan a moverse. El tráfico deja de depender de cada publicación nueva y el histórico empieza a sostenerlo solo.</li>
                    </ul>
                    <p>
                        Un matiz importante para negocios con ticket alto: el orgánico casi nunca convierte en la
                        primera visita. Alguien que va a contratar un despacho, comprar maquinaria industrial o
                        firmar la compra de una propiedad investiga durante semanas o meses antes de contactar. Eso
                        significa que al plazo de posicionamiento hay que sumarle el ciclo de decisión del cliente, y
                        por eso la métrica honesta nunca es el tráfico: es el contacto calificado.
                    </p>
                </section>

                <section id="factores">
                    <h2>Qué alarga o acorta el plazo</h2>
                    <p>
                        Dos negocios que arrancan el mismo día pueden ver resultados con seis meses de diferencia.
                        Estos son los factores que explican la brecha.
                    </p>
                    <h3>La edad y el historial del dominio</h3>
                    <p>
                        Un sitio con años de contenido publicado y enlaces acumulados reacciona mucho más rápido a
                        cualquier optimización que un dominio recién registrado. Si acabas de lanzar, tu primer
                        trimestre se va casi entero en existir para el buscador.
                    </p>
                    <h3>La competencia del término</h3>
                    <p>
                        Rankear para "abogado corporativo Ciudad de México" y para "cómo se disuelve una sociedad
                        anónima en México" son proyectos de dificultad completamente distinta. Por eso el trabajo de
                        <a href="/blog/como-hacer-investigacion-de-palabras-clave">investigación de palabras
                        clave</a> importa tanto: empezar por lo específico da resultados visibles antes y construye
                        la base para atacar lo competido después.
                    </p>
                    <h3>El estado técnico del sitio</h3>
                    <p>
                        Un sitio lento, con errores de indexación o que carga el contenido de forma que el rastreador
                        no lo alcanza a leer, arranca en negativo. Antes de sumar contenido nuevo hay que dejar de
                        perder lo que ya tienes. Ahí entran las métricas de experiencia en la página que vemos en
                        <a href="/blog/core-web-vitals">Core Web Vitals</a>.
                    </p>
                    <h3>El ritmo de publicación</h3>
                    <p>
                        Cuatro artículos al mes de forma sostenida rinden muchísimo más que veinte en enero y cero el
                        resto del año. La constancia le da al buscador un patrón, y a tu sitio una biblioteca que se
                        enlaza entre sí.
                    </p>
                    <h3>Si el negocio es local o nacional</h3>
                    <p>
                        Una clínica que compite por búsquedas de su colonia y su ciudad puede ver movimiento mucho
                        antes que un fabricante que compite a nivel nacional. El SEO local juega con reglas parcialmente
                        distintas, y lo desarrollamos en
                        <a href="/blog/seo-local-para-inmobiliarias">SEO local</a>.
                    </p>
                </section>

                <section id="que-medir">
                    <h2>Qué medir mientras todavía no hay clientes</h2>
                    <p>
                        El error más caro de los primeros meses es medir solo la variable final. Si en el mes dos la
                        única pregunta en la junta es cuántos clientes llegaron por orgánico, el proyecto se cancela
                        antes de tener oportunidad. Hay indicadores tempranos que se mueven mucho antes que el
                        ingreso, y todos están en Search Console, que es gratuito.
                    </p>
                    <ul>
                        <li><strong>Impresiones.</strong> Cuántas veces apareciste en resultados. Es lo primero que sube y la señal más temprana de que el buscador ya te ubica en un tema.</li>
                        <li><strong>Consultas nuevas.</strong> Términos por los que antes no aparecías. Indica que estás ganando cobertura temática, aunque todavía no ganes clics.</li>
                        <li><strong>Posición promedio.</strong> Pasar de la posición 40 a la 18 no genera tráfico, pero es la mitad del camino hacia el top diez.</li>
                        <li><strong>Páginas indexadas.</strong> Si publicas y no se indexan, el problema no es el plazo: es técnico y hay que atenderlo ya.</li>
                        <li><strong>Relación impresiones contra clics.</strong> Muchas impresiones con pocos clics apunta a un problema de título o de meta descripción, no de contenido, y es de las correcciones más rápidas que existen.</li>
                    </ul>
                    <p>
                        Search Console conserva el histórico de los últimos meses, lo que permite comparar periodos y
                        detectar estacionalidad. Para un negocio de alto ticket con demanda estacional, comparar
                        contra el mismo mes del año anterior dice más que comparar contra el mes pasado.
                    </p>
                </section>

                <section id="mientras-tanto">
                    <h2>Qué hacer durante los meses de espera</h2>
                    <p>
                        La respuesta que damos siempre en la sesión de diagnóstico: no esperes con los brazos
                        cruzados. El SEO y la pauta no compiten, se financian mutuamente.
                    </p>
                    <p>
                        Mientras el orgánico madura, la publicidad paga sostiene el flujo de oportunidades. Con
                        <a href="/blog/que-es-google-ads-y-como-funciona">Google Ads</a> capturas hoy la misma
                        intención de búsqueda que el SEO capturará gratis en unos meses, y de paso te dice qué
