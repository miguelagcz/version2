                <section id="minimo-tecnico-vs-real">
                    <h2>El mínimo técnico y el mínimo real</h2>
                    <p>
                        El <strong>mínimo técnico</strong> es lo que Meta te permite gastar. Es bajo, el equivalente a unos cuantos dólares al día según cómo te cobren, y el Administrador de Anuncios te avisa la cifra exacta en pesos cuando configuras el conjunto de anuncios. Sirve para probar un anuncio, no para sostener una campaña.
                    </p>
                    <p>
                        El <strong>mínimo real</strong> es otra cosa. Cada conjunto de anuncios nuevo, o que tuvo un cambio importante, pasa por una fase de aprendizaje en la que Meta prueba a quién mostrarle tus anuncios. Para salir de ahí necesita juntar suficientes resultados, y la referencia que Meta suele dar es de alrededor de 50 en los siete días posteriores al último cambio importante. Si no llega, el conjunto se queda en aprendizaje limitado.
                    </p>
                    <p>
                        Piénsalo como la gasolina para llegar a otra ciudad. La gasolinera te vende un litro si quieres; eso es el mínimo técnico. Pero con un litro no llegas a ningún lado, y concluir que el coche no sirve sería injusto con el coche.
                    </p>
                </section>

                <section id="como-calcularlo">
                    <h2>Cómo calcular tu presupuesto</h2>

                    <h3>La fórmula rápida: lo que necesita Meta para aprender</h3>
                    <p>
                        Multiplica tu costo por resultado por 50. Eso es, aproximadamente, lo que necesita cada conjunto de anuncios por semana para trabajar con datos suficientes. Si cada lead te cuesta 200 pesos, un conjunto necesita unos 10,000 pesos a la semana, algo más de 40,000 al mes.
                    </p>
                    <p>
                        Ese número asusta a muchos, y está bien que asuste, porque explica dos cosas. La primera: por qué no conviene dividir un presupuesto chico en cinco conjuntos de anuncios. La segunda: por qué casi nunca conviene optimizar por la cita o la venta al principio; si cada cita cuesta 1,500 pesos, juntar 50 por semana es inalcanzable para la mayoría.
                    </p>

                    <h3>La fórmula completa: desde tu meta de ventas</h3>
                    <p>
                        La segunda cuenta va hacia atrás desde lo que quieres vender. Supongamos que quieres cerrar dos ventas al mes, que una de cada diez citas termina en venta y que uno de cada cuatro leads llega a cita:
                    </p>
                    <ul>
                        <li>2 ventas necesitan <strong>20 citas</strong>.</li>
                        <li>20 citas necesitan <strong>80 leads</strong>.</li>
                        <li>80 leads a 250 pesos cada uno son <strong>20,000 pesos al mes</strong>.</li>
                    </ul>
                    <p>
                        Ahora cruza las dos cuentas. Con 20,000 pesos al mes llegas a unos 18 leads por semana, lejos de los 50. Eso no significa que no funcione; significa que debes concentrar todo en una sola campaña y un solo conjunto, aceptar que el aprendizaje será más lento y medir con paciencia. Los números de este ejemplo son ilustrativos: los tuyos salen de tu cuenta y de tu equipo de ventas.
                    </p>
                    <p>
                        Como referencia, la estructura que describimos en <a href="/blog/como-estructurar-cuenta-meta-ads">cómo estructurar una cuenta de Meta Ads</a> está pensada para cuentas desde unos 15,000 pesos al mes. Por debajo de eso, lo más sano es una sola campaña con un solo conjunto de anuncios.
                    </p>
                </section>

                <section id="que-mueve-el-numero">
                    <h2>Qué hace que tu número suba o baje</h2>
                    <ul>
                        <li><strong>La oferta.</strong> Es lo que más mueve el costo por lead. "Agenda una visita" cuesta más que "descarga la lista de precios", y a veces trae mejores prospectos. El detalle está en <a href="/blog/como-bajar-costo-por-lead-facebook-ads">cómo bajar el costo por lead</a>.</li>
                        <li><strong>El destino.</strong> Formulario instantáneo, landing page o WhatsApp tienen costos y calidades distintas. Lo comparamos en <a href="/blog/campanas-de-leads-vs-trafico-landing-page">campañas de leads vs tráfico a landing page</a>.</li>
                        <li><strong>El tamaño del público.</strong> Una ciudad mediana con un nicho muy específico da menos volumen y suele costar más por resultado que una zona metropolitana.</li>
                        <li><strong>La temporada.</strong> En fin de año sube la competencia por la atención y con ella el costo. En tu temporada alta conviene tener presupuesto listo.</li>
                        <li><strong>El creativo.</strong> Un anuncio que detiene el scroll baja el costo de todo lo demás. Uno cansado lo sube semana a semana.</li>
                    </ul>
                </section>

                <section id="por-industria">
                    <h2>Cómo cambia según tu industria</h2>

                    <h3>Desarrolladoras inmobiliarias</h3>
                    <p>
                        El presupuesto no es plano: un lanzamiento necesita concentrar inversión al principio para armar la lista de espera de la preventa, y después sostener la captación durante la venta activa. Con presupuesto total por fase en lugar de uno diario fijo, controlas mejor esos picos. Las tres fases están en <a href="/blog/facebook-ads-lanzamiento-desarrollo-inmobiliario">Facebook Ads para el lanzamiento de un desarrollo inmobiliario</a>.
                    </p>

                    <h3>Empresas de energía solar</h3>
                    <p>
                        Con instalaciones que valen decenas o cientos de miles de pesos, un lead caro puede ser perfectamente rentable si llega a la visita técnica. La demanda sube con el calor y los recibos altos, así que conviene reservar más presupuesto para esos meses. Lo complementa <a href="/blog/facebook-ads-para-energia-solar">Facebook Ads para energía solar</a>.
                    </p>

                    <h3>Clínicas y consultorios</h3>
                    <p>
                        Los tratamientos estéticos suelen tener más volumen y leads más baratos; las especialidades, menos volumen y más valor por paciente. En las dos, el evento que más conviene optimizar al principio es el lead o la conversación, y medir la cita en tu agenda.
                    </p>

                    <h3>Despachos y servicios B2B</h3>
                    <p>
                        Volúmenes chicos y ciclos largos. Si tu presupuesto no alcanza para que Meta aprenda en frío, muchas veces rinde más usarlo en remarketing a quien ya visitó tu sitio y poner la captación en frío en los buscadores. La comparación está en <a href="/blog/facebook-ads-vs-google-ads">Facebook Ads vs Google Ads</a>.
                    </p>
                </section>

                <section id="cuando-no-invertir">
                    <h2>Cuándo no deberías invertir todavía</h2>
                    <p>
                        Hay momentos en los que el mejor consejo es esperar, y vale la pena decirlo:
                    </p>
                    <ul>
                        <li><strong>Cuando nadie puede contestar los leads el mismo día.</strong> Un prospecto de alto ticket que espera 48 horas una respuesta ya habló con tu competencia. Pagar por leads que nadie atiende es tirar el dinero.</li>
                        <li><strong>Cuando la oferta no está clara.</strong> Si no puedes explicar en una frase por qué alguien debería escribirte a ti, el anuncio tampoco va a poder.</li>
                        <li><strong>Cuando el presupuesto solo alcanza para unos días.</strong> Mejor juntar para sostener cuatro a seis semanas que gastarlo en una y concluir que no funciona.</li>
                    </ul>
                </section>

                <section id="errores-comunes">
                    <h2>Errores comunes</h2>
                    <p>
                        Ordenados por lo que más cuestan:
                    </p>
                    <ol>
                        <li><strong>Repartir un presupuesto chico en muchos conjuntos.</strong> Cinco conjuntos con poco dinero aprenden peor que uno con todo.</li>
                        <li><strong>Optimizar por clics porque salen baratos.</strong> Meta te va a traer exactamente lo que pediste: gente que da clic, no gente que compra.</li>
                        <li><strong>Juzgar a los tres días.</strong> En plena fase de aprendizaje los resultados brincan; decidir con eso es decidir con ruido.</li>
                        <li><strong>Hacer cambios grandes y seguidos.</strong> Las ediciones importantes regresan el conjunto a la fase de aprendizaje. Cuando algo funciona, súbele en pasos moderados, como explicamos en <a href="/blog/como-escalar-campana-meta-ads">cómo escalar una campaña de Meta Ads</a>.</li>
                        <li><strong>Copiar el presupuesto de la competencia.</strong> No sabes su costo por lead, su margen ni su tasa de cierre. Tus números son los únicos que sirven.</li>
                    </ol>
                </section>

                <section id="como-medirlo">
                    <h2>Cómo medirlo y qué esperar</h2>
                    <p>
                        Mide en tres niveles: costo por lead en el Administrador de Anuncios, costo por cita con tu agenda o tu CRM, y costo por venta cuando tu ciclo lo permita. El último, comparado contra tu margen por venta, es el que te dice si tu presupuesto es rentable. Para leer el primero sin perderte, revisa <a href="/blog/como-leer-ads-manager">cómo leer el Ads Manager</a>.
                    </p>
                    <p>
                        Cuando ya tengas suficientes datos, puedes pedirle a Meta que optimice por la calidad del lead y no solo por la cantidad, mandándole de regreso qué prospectos avanzaron en tu venta. Cómo conectarlo está en <a href="/blog/meta-ads-api-de-conversiones-capi">la API de Conversiones de Meta</a>.
                    </p>
                    <p>
                        Lo que deberías ver: la primera semana, costos inestables; entre la segunda y la cuarta, un costo por lead que se asienta; y a partir del segundo mes, suficientes citas y ventas para saber si el presupuesto se paga solo y si conviene subirlo.
                    </p>
                </section>

