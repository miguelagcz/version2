                        <p>El número que importa es otro: el que le permite a Meta juntar suficientes resultados para aprender, que suele rondar los 50 por semana por conjunto de anuncios. Multiplica tu costo por resultado por 50 y tendrás una idea del presupuesto semanal que necesita cada conjunto para trabajar con datos suficientes.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto debo invertir al mes en Facebook Ads para generar leads?</summary>
                        <p>Lo que salga de tu meta de ventas, calculada hacia atrás. Cuántas ventas quieres, qué porcentaje de tus citas cierra, qué porcentaje de tus leads llega a cita y cuánto te cuesta cada lead. Con esos cuatro datos el presupuesto deja de ser una corazonada y se vuelve una cuenta.</p>
                        <p>Si todavía no conoces tu costo por lead, empieza con un presupuesto de prueba de cuatro a seis semanas concentrado en una sola campaña y un solo conjunto de anuncios. Al final tendrás tu costo real, que vale más que cualquier promedio de internet, y podrás hacer la cuenta completa con tus propios números.</p>
                    </details>

                    <details>
                        <summary>¿Qué pasa si mi presupuesto no alcanza para salir de la fase de aprendizaje?</summary>
                        <p>El conjunto de anuncios se queda en aprendizaje limitado: sigue funcionando, pero Meta tiene menos datos para optimizar y los resultados suelen ser menos estables. No es una catástrofe, pero sí una señal de que tu estructura está pidiendo más de lo que tu presupuesto puede dar.</p>
                        <p>Tienes tres salidas. Juntar todo en menos conjuntos de anuncios para que cada uno reciba más resultados, optimizar por un evento más frecuente, por ejemplo el lead en lugar de la cita, o subir el presupuesto. Lo que no conviene es dividir todavía más con la esperanza de que algún conjunto despegue.</p>
                    </details>

                    <details>
                        <summary>¿Conviene usar presupuesto diario o presupuesto total?</summary>
                        <p>El presupuesto diario sirve para campañas que corren todo el tiempo, como la captación de prospectos de un negocio que vende todo el año. El presupuesto total, que se gasta en un periodo con fecha de inicio y fin, sirve para lo que tiene fecha: un lanzamiento, una preventa, un evento.</p>
                        <p>Con cualquiera de los dos, evita los cambios bruscos. Las ediciones importantes pueden regresar el conjunto de anuncios a la fase de aprendizaje, así que es mejor ajustar en pasos moderados y dejar correr unos días entre un cambio y otro. Cómo subir presupuesto sin romper una campaña que funciona está en nuestra guía de cómo escalar campañas.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto tiempo dejo correr una campaña antes de decidir si funciona?</summary>
                        <p>Al menos una semana, o hasta que el conjunto de anuncios salga de la fase de aprendizaje, lo que pase después. Los primeros días los resultados brincan mucho mientras Meta prueba a quién mostrarle tus anuncios, y decidir con esos datos es decidir con ruido.</p>
                        <p>En negocios de alto ticket hay un segundo plazo: el de tu ciclo de venta. Una campaña puede traer leads caros que cierran en seis semanas y otra leads baratos que nunca cierran. Juzga el costo por lead en la primera semana, pero el costo por cita y por venta cuando tu ciclo lo permita.</p>
