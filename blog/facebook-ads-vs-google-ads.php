                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Qué es más barato, Facebook Ads o Google Ads?</summary>
                        <p>Depende completamente de tu industria y de tu objetivo. En términos de CPM, Facebook Ads suele ser más barato para generar alcance masivo, con un CPM promedio en México de entre 2 y 5 dólares. En Google Ads, el CPC de la Red de Búsqueda puede ser bastante más caro en sectores muy competidos, como bienes raíces, seguros o servicios legales, precisamente porque estás compitiendo por capturar una intención de compra que ya existe y que todos tus competidores también quieren. Sin embargo, un CPC más alto en Google Ads muchas veces se traduce en un lead más calificado, porque esa persona ya estaba buscando activamente, mientras que un clic barato en Facebook Ads puede venir de alguien que todavía está en una etapa de descubrimiento y no de decisión de compra. Comparar el precio sin comparar la calidad del lead que genera cada canal es el error más común al elegir entre las dos plataformas.</p>
                    </details>

                    <details>
                        <summary>¿Puedo usar Facebook Ads y Google Ads al mismo tiempo con un presupuesto pequeño?</summary>
                        <p>Sí, aunque con un presupuesto muy limitado suele ser más eficiente concentrar el gasto en un solo canal hasta encontrar una estructura de campaña rentable, y después expandirte al segundo. Dividir un presupuesto de 5 o 10 dólares diarios entre dos plataformas distintas normalmente significa que ninguna de las dos junta suficientes datos para salir de su fase de aprendizaje de forma eficiente, lo que se traduce en un costo por resultado más alto en ambos lados. Una secuencia común para negocios que están arrancando es empezar en Facebook Ads, validar la oferta y el mensaje con ese tráfico más económico, y una vez que el negocio genera ingresos suficientes, sumar Google Ads para capturar la demanda de búsqueda que ya existe alrededor de su categoría de producto o servicio.</p>
                    </details>

                    <details>
                        <summary>¿Cuál de las dos plataformas es mejor para un negocio inmobiliario?</summary>
                        <p>Para el sector inmobiliario, lo ideal casi siempre es una combinación de ambas, aunque con pesos distintos según la etapa del desarrollo. Durante el lanzamiento de un desarrollo nuevo, donde la marca y el proyecto todavía no son conocidos, Facebook Ads suele generar más volumen de leads a un costo más bajo, porque puede llegar a personas que ni siquiera sabían que estaban interesadas en comprar una propiedad en esa zona hasta que vieron el anuncio. Conforme el proyecto avanza y empieza a generar búsquedas directas ("nombre del desarrollo" o "departamentos en [zona]"), Google Ads se vuelve cada vez más rentable, porque esas búsquedas representan a personas mucho más cerca de tomar una decisión de compra. La estrategia más común entre desarrolladoras que ya tienen experiencia es mantener ambos canales activos de forma permanente, ajustando el presupuesto de cada uno según el momento del proyecto.</p>
                    </details>

                    <details>
                        <summary>¿Qué plataforma da mejores resultados para energía solar?</summary>
                        <p>El sector de energía solar suele beneficiarse mucho de un enfoque en dos etapas. Facebook Ads funciona particularmente bien al inicio del recorrido del cliente porque el concepto de ahorro con paneles solares, el retorno de la inversión y el proceso de instalación todavía requieren educación para la mayoría del público, algo que se logra mejor con contenido de valor (como una calculadora de ahorro) mostrado a tráfico frío. Google Ads, por su parte, captura a las personas que ya decidieron investigar activamente opciones de energía solar y están comparando proveedores, lo que las hace leads mucho más calificados y cerca del cierre. Empresas de energía solar que solo usan Google Ads suelen dejar fuera a un porcentaje enorme del mercado potencial que todavía no sabe que la energía solar es una opción viable para su hogar o negocio.</p>
                    </details>

                    <details>
                        <summary>¿Necesito un sitio web distinto para Facebook Ads y para Google Ads?</summary>
                        <p>No necesariamente un sitio distinto, pero sí es recomendable adaptar la landing page según de dónde viene el tráfico. Alguien que llega desde Google Ads ya sabe lo que está buscando, así que su página de destino puede ser más directa y enfocada en la conversión inmediata. Alguien que llega desde Facebook Ads todavía está descubriendo tu oferta, así que su landing page normalmente necesita más contexto, más prueba social y una explicación más completa de por qué debería confiar en tu negocio antes de dejar sus datos o hacer una compra.</p>
                    </details>
