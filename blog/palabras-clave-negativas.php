                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Cuántas palabras clave negativas debería tener desde el inicio de una campaña?</summary>
                        <p>No existe un número ideal universal, pero sí conviene empezar con una lista base de exclusiones obvias para tu industria (como vimos en los ejemplos por sector) antes de lanzar tu primera campaña, en lugar de esperar a ver qué pasa. Después de eso, la lista debería crecer de forma orgánica conforme revises tu reporte de términos de búsqueda cada semana o cada dos semanas durante el primer mes. Es mucho más fácil prevenir gasto desperdiciado desde el inicio que recuperarlo después de que ya se fue en clics irrelevantes.</p>
                    </details>

                    <details>
                        <summary>¿Puedo usar la misma palabra como positiva en una campaña y negativa en otra?</summary>
                        <p>Sí, y de hecho es una técnica avanzada bastante efectiva conocida como negativas cruzadas. Por ejemplo, si tienes una campaña específica para "departamentos en preventa" y otra para "departamentos en entrega inmediata", puedes usar "preventa" como negativa en la segunda campaña y "entrega inmediata" como negativa en la primera. Esto asegura que cada búsqueda active exactamente la campaña que le corresponde, sin que ambas compitan entre sí por la misma persona.</p>
                    </details>

                    <details>
                        <summary>¿Las palabras clave negativas funcionan igual en Búsqueda que en Display?</summary>
                        <p>No. En campañas de Búsqueda, las negativas son bastante precisas y respetan los tipos de concordancia que elijas. En campañas de Display y de Video, todas las palabras clave negativas se consideran de concordancia amplia, y su funcionamiento es menos exacto: es posible que ocasionalmente tu anuncio siga apareciendo en páginas que contienen ese término, porque ahí Google evalúa el tema general del contenido, no una coincidencia literal palabra por palabra.</p>
                    </details>

                    <details>
                        <summary>¿Es mejor usar palabras clave negativas de concordancia amplia o exacta?</summary>
                        <p>Depende de qué tan seguro estés de que ese término nunca te interesa en ninguna forma. La concordancia amplia bloquea más variaciones con menos esfuerzo, pero corre el riesgo de bloquear también búsquedas que sí querías capturar si no la revisas con cuidado. La concordancia exacta es más segura pero requiere que agregues manualmente cada variante (singular, plural, con y sin errores ortográficos comunes) para lograr una cobertura similar. En la práctica, muchas cuentas terminan usando una combinación de ambas según qué tan crítico sea cada término.</p>
                    </details>

                    <details>
                        <summary>¿Agregar demasiadas palabras clave negativas puede perjudicar mi campaña?</summary>
                        <p>Sí, si se hace sin cuidado. El riesgo real no es tener muchas negativas, sino agregar una negativa demasiado amplia sin revisar qué búsquedas legítimas podría estar bloqueando de paso. Por ejemplo, excluir "barato" para evitar cazadores de ofertas también podría bloquear a alguien buscando "el más barato de los planes premium", una búsqueda que en realidad sí te convendría capturar. Por eso conviene revisar el reporte de términos de búsqueda después de agregar negativas nuevas, para confirmar que el efecto fue el esperado.</p>
                    </details>
