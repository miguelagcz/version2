                <section id="que-es-una-palabra-clave-negativa">
                    <h2>¿Qué es una palabra clave negativa?</h2>
                    <p>
                        Es justo lo contrario a una palabra clave normal: en lugar de decirle a Google cuándo sí quieres que aparezca tu anuncio, le dices cuándo definitivamente no quieres que aparezca. Google lo explica con un ejemplo simple: si agregas "gratis" como palabra clave negativa, tu anuncio deja de mostrarse en cualquier búsqueda que contenga esa palabra, sin importar qué tan bien coincidan el resto de los términos.
                    </p>
                    <p>
                        Esto también se conoce como concordancia negativa, y es una de las herramientas más subestimadas de <a href="/blog/que-es-google-ads-y-como-funciona">Google Ads</a>. La mayoría de la gente que empieza se enfoca solo en qué palabras clave agregar, y se olvida por completo de qué palabras clave excluir, aunque ambas decisiones afectan igual de directo cuánto terminas gastando.
                    </p>
                </section>

                <section id="tipos-de-concordancia">
                    <h2>Cómo funcionan sus tipos de concordancia</h2>
                    <p>
                        Igual que las palabras clave normales, las negativas también tienen tipos de concordancia: amplia, de frase y exacta. Pero aquí viene el detalle que sorprende a mucha gente, incluso a quien ya tiene experiencia con las positivas: las negativas no funcionan exactamente igual que su contraparte positiva.
                    </p>
                    <p>
                        Google pone un ejemplo muy claro de esto: si excluyes la palabra clave negativa de concordancia amplia "flores", tu anuncio no se va a mostrar cuando alguien busque "flores rojas", pero sí se puede seguir mostrando si alguien busca "flor roja", en singular. Las palabras clave negativas no incluyen automáticamente variantes cercanas, sinónimos, ni formas en singular o plural, algo que sí ocurre con las palabras clave positivas normales. Esto significa que si quieres bloquear un concepto completo, tienes que anticipar y agregar tú mismo esas variantes, en lugar de asumir que Google las va a cubrir por ti.
                    </p>
                </section>

                <section id="donde-se-aplican">
                    <h2>¿A qué nivel se pueden aplicar?</h2>
                    <p>
                        Las palabras clave negativas se pueden agregar en distintos niveles, y elegir el nivel correcto importa tanto como elegir las palabras correctas:
                    </p>
                    <ul>
                        <li><strong>A nivel de grupo de anuncios.</strong> Para excluir términos que solo tienen sentido bloquear en ese grupo específico.</li>
                        <li><strong>A nivel de campaña.</strong> Para exclusiones que aplican a toda esa campaña, sin importar el grupo de anuncios.</li>
                        <li><strong>A nivel de cuenta.</strong> Google permite crear una sola lista que aplica automáticamente a todo tu inventario relevante de Búsqueda y Shopping en todas tus campañas, útil para exclusiones que nunca cambian sin importar qué estés promocionando.</li>
                        <li><strong>Listas compartidas.</strong> Puedes crear hasta 20 listas de palabras clave negativas por cuenta, con hasta 5,000 términos cada una, y aplicar la misma lista a varias campañas a la vez en lugar de repetir el trabajo campaña por campaña.</li>
                    </ul>
                    <p>
                        Un error común es no usar listas compartidas cuando se manejan varias campañas al mismo tiempo. Sin ellas, es fácil terminar duplicando esfuerzo, olvidando actualizar una campaña cuando actualizas otra, y perdiendo consistencia en lo que excluyes de un lado a otro de tu cuenta.
                    </p>
                </section>

                <section id="como-encontrarlas">
                    <h2>Cómo encontrar tus propias palabras clave negativas</h2>
                    <p>
                        No hace falta adivinar. Dentro de tu cuenta de Google Ads existe un reporte de términos de búsqueda que te muestra, de forma literal, qué escribió la gente antes de que le apareciera tu anuncio. Revisar este reporte de forma regular es, probablemente, el hábito más rentable que puedes adoptar una vez que tu campaña lleva unos días corriendo.
                    </p>
                    <p>
                        Ahí es donde vas a encontrar patrones que nunca hubieras anticipado solo pensando en tu negocio: términos relacionados con empleo cuando tú vendes un producto, búsquedas de tutoriales gratuitos cuando tú vendes un servicio de paga, o nombres de competidores cuando en realidad no quieres ese tipo de comparación directa. Cada uno de esos patrones es candidato a convertirse en una palabra clave negativa.
                    </p>
                </section>

                <section id="ejemplos-por-industria">
                    <h2>Ejemplos aplicados por tipo de negocio</h2>
                    <p>
                        Los términos que conviene excluir cambian mucho según tu industria. Una inmobiliaria que solo vende, como vimos en nuestra guía de <a href="/blog/google-ads-para-inmobiliarias">Google Ads para inmobiliarias</a>, suele necesitar excluir "renta", "alquiler" y "empleo" desde el primer día. Una empresa de energía solar probablemente quiera excluir búsquedas relacionadas con "empleo en energía solar" o "curso de instalación de paneles", que atraen a gente buscando trabajo o capacitación, no a gente buscando comprar un sistema.
                    </p>
                    <p>
                        Una agencia de marketing digital, por su parte, suele beneficiarse de excluir términos como "gratis", "curso" o "tutorial", que atraen a gente buscando aprender a hacerlo ellos mismos en lugar de contratar el servicio. El patrón de fondo es siempre el mismo: identificar la intención que no quieres capturar, y ser lo suficientemente específico al excluirla para no bloquear, sin querer, búsquedas que sí te interesan.
                    </p>
                </section>

