                <!-- FAQ -->
                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Necesito un sitio web para anunciarme en Google Ads?</summary>
                        <p>Sí, necesitas algún lugar al que enviar a la persona después de que le da clic a tu anuncio, ya sea tu sitio web, una landing page dedicada o, en algunos casos, tu ficha de Perfil de Negocio en Google. Sin un destino claro y relevante, el anuncio puede aparecer, pero es muy probable que no convierta en ventas.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto tiempo tardan en verse resultados en Google Ads?</summary>
                        <p>A diferencia del SEO, aquí la visibilidad es prácticamente inmediata: en cuanto tu campaña se aprueba, tu anuncio puede empezar a mostrarse el mismo día. Lo que sí toma tiempo es la optimización: entender qué palabras clave, anuncios y páginas de destino funcionan mejor suele requerir varias semanas de ajustes basados en datos reales.</p>
                    </details>

                    <details>
                        <summary>¿Puedo manejar Google Ads yo mismo o necesito una agencia?</summary>
                        <p>Técnicamente cualquiera puede crear una cuenta y lanzar una campaña. El reto está en que la plataforma tiene suficientes variables (pujas, calidad del anuncio, segmentación, exclusiones) como para que sea fácil gastar presupuesto sin ver resultados si no se configura bien desde el inicio. Muchos negocios empiezan solos para entender lo básico y después contratan una agencia de Google Ads cuando quieren escalar con seriedad.</p>
                    </details>

                    <details>
                        <summary>¿Qué diferencia hay entre Google Ads y Google AdWords?</summary>
                        <p>Son la misma plataforma. Google le cambió el nombre de AdWords a Google Ads en 2018 para reflejar que ya no solo eran anuncios de texto basados en palabras clave, sino un conjunto mucho más amplio de formatos como Display, Video y Shopping. Si ves el término "AdWords" en algún lado, se refiere a la misma herramienta.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto debería invertir al mes si apenas estoy empezando?</summary>
                        <p>No hay una cifra universal, porque depende del costo por clic de tu industria y de cuántas conversiones necesitas para que el negocio sea rentable. Lo que sí es un buen hábito es empezar con un presupuesto que puedas sostener durante varias semanas seguidas sin sentir presión, revisar los resultados con datos reales, y ajustar a partir de ahí. Le dedicaremos una guía completa a este cálculo más adelante.</p>
                    </details>

                    <details>
                        <summary>¿Qué son las palabras clave negativas?</summary>
                        <p>Son términos que le indicas a Google que excluya, para que tu anuncio no se muestre en búsquedas que no tienen que ver con tu negocio. Por ejemplo, si vendes departamentos en venta, probablemente quieras excluir búsquedas relacionadas con "renta" o "empleo" para no pagar clics de gente que busca algo distinto a lo que ofreces. Es una de las formas más simples y efectivas de dejar de desperdiciar presupuesto.</p>
                    </details>
                </section>

