                <section id="que-es">
                    <h2>Qué es el schema markup</h2>
                    <p>
                        El schema markup, también llamado <strong>datos estructurados</strong>, es una forma estandarizada de etiquetar el contenido de una página para que los buscadores lo entiendan sin ambigüedad. El vocabulario se llama Schema.org y lo comparten Google y los demás buscadores; define tipos como negocio local, artículo, producto, evento o pregunta frecuente, cada uno con sus propiedades.
                    </p>
                    <p>
                        Piénsalo como la diferencia entre una nota de remisión y una factura. La información puede ser la misma, pero la factura pone cada dato en la casilla que el SAT espera: RFC aquí, monto allá, fecha en su lugar. Nadie tiene que interpretar nada. Los datos estructurados son la factura de tu página.
                    </p>
                    <p>
                        Es parte del trabajo técnico del sitio, junto con la velocidad y la indexación que cubrimos en <a href="/blog/seo-tecnico-velocidad-indexacion-errores">SEO técnico: velocidad, indexación y errores</a>. No reemplaza al contenido: si tu página no responde lo que la gente busca, etiquetarla mejor no la va a salvar. La parte de contenido está en la <a href="/blog/seo-on-page-checklist">checklist de SEO on-page</a>.
                    </p>
                </section>

                <section id="para-que-sirve">
                    <h2>Para qué sirve y qué no hace</h2>
                    <p>
                        Sirve para dos cosas. La primera, que Google entienda con precisión quién eres: tu nombre, tu dirección, tu horario, tus servicios, quién escribió un artículo y cuándo. La segunda, volver tu página elegible para <strong>resultados enriquecidos</strong>: estrellas, precios, fechas de eventos, rutas de navegación y otros elementos que hacen tu resultado más visible.
                    </p>
                    <p>
                        Ese segundo efecto se nota en los clics. Google publica casos de sitios que lo midieron: Rotten Tomatoes midió una tasa de clics 25% mayor en las páginas con datos estructurados, y Nestlé una 82% mayor en las páginas que aparecían como resultado enriquecido. No es una promesa para todos, pero muestra por qué vale la pena hacerlo bien.
                    </p>
                    <p>
                        Lo que no hace es igual de importante. No te sube de posición por sí solo, no garantiza que Google muestre el resultado enriquecido y no compensa un contenido flojo. Además, Google ha ido retirando varios tipos de resultados enriquecidos con los años, así que perseguir un efecto visual concreto es mala apuesta. La apuesta buena es describir con precisión lo que ya es cierto de tu negocio.
                    </p>
                </section>

                <section id="tipos-que-convienen">
                    <h2>Los tipos que le convienen a un negocio</h2>
                    <p>
                        Schema.org tiene cientos de tipos. Un negocio de servicios de alto ticket necesita pocos, y en este orden:
                    </p>
                    <ul>
                        <li><strong>Organization o LocalBusiness.</strong> Quién eres, tu logo, tu dirección, teléfono, horario y redes. Si atiendes en un lugar físico, usa el subtipo más específico que exista para tu giro, por ejemplo clínica médica, servicio legal o servicio contable.</li>
                        <li><strong>BreadcrumbList.</strong> La ruta de navegación de cada página (Inicio, Blog, Artículo). Ayuda a Google a entender la estructura del sitio y puede mostrarse en el resultado en lugar de la URL.</li>
                        <li><strong>Article o BlogPosting.</strong> Para cada artículo: título, fecha de publicación y de actualización, autor e imagen.</li>
                        <li><strong>Service y Offer.</strong> Para describir tus servicios y, si los publicas, sus precios o rangos.</li>
                        <li><strong>Event.</strong> Si organizas eventos reales con fecha y lugar: un lanzamiento, una plática, un open house.</li>
                        <li><strong>FAQPage.</strong> Para las preguntas frecuentes que ya están visibles en tu página. Ya casi nunca genera un resultado enriquecido, pero sigue ayudando a que se entienda qué respondes.</li>
                        <li><strong>Product.</strong> Solo si vendes productos con precio, por ejemplo un catálogo industrial o una tienda en línea.</li>
                    </ul>
                </section>

                <section id="como-implementarlo">
                    <h2>Cómo se implementa</h2>
                    <p>
                        Google acepta tres formatos y recomienda <strong>JSON-LD</strong>: un bloque de código en el encabezado de la página, separado del texto visible, fácil de mantener y de generar de forma automática. Los otros dos, Microdata y RDFa, se escriben dentro del HTML del contenido y se rompen con más facilidad cuando alguien edita la página.
                    </p>
                    <p>
                        Lo sano es que la plantilla del sitio genere el código a partir de los datos de cada página, no que alguien lo pegue a mano en cada una. En nuestro propio blog, el encabezado de cada artículo arma el JSON-LD solo: artículo, organización, ruta de navegación y preguntas frecuentes, tomando los datos del propio texto.
                    </p>
                    <p>
                        Tres reglas que no se negocian:
                    </p>
                    <ol>
                        <li><strong>Marca solo lo que se ve.</strong> Los datos estructurados deben describir contenido que el visitante puede ver en esa misma página. Inventar reseñas, precios u horarios que no aparecen es la forma más rápida de que Google ignore todo tu código.</li>
                        <li><strong>Llena las propiedades obligatorias.</strong> Cada tipo de resultado enriquecido pide ciertos datos mínimos; si faltan, la página no califica.</li>
                        <li><strong>Que coincida con tu ficha de Google.</strong> Nombre, dirección y teléfono idénticos en tu sitio, tu código y tu <a href="/blog/como-optimizar-google-business-profile">ficha de Google Business Profile</a>.</li>
                    </ol>
                </section>

                <section id="errores-comunes">
                    <h2>Errores comunes</h2>
                    <p>
                        Ordenados por lo que más cuestan:
                    </p>
                    <ol>
                        <li><strong>Marcar reseñas propias para conseguir estrellas.</strong> Google no muestra estrellas para reseñas que un negocio marca sobre sí mismo en su propio sitio. En el mejor caso no pasa nada; en el peor, se considera marcado engañoso.</li>
                        <li><strong>Dos plugins generando datos que se contradicen.</strong> Uno dice que eres una organización en CDMX y otro que eres un negocio local en Guadalajara. Google no sabe a cuál creerle.</li>
                        <li><strong>Usar el tipo equivocado.</strong> Marcar un servicio como producto o un artículo como página de producto confunde más de lo que ayuda.</li>
                        <li><strong>Dejar datos viejos.</strong> El horario cambió, el teléfono cambió, el precio cambió, pero el código sigue diciendo lo de hace dos años.</li>
                        <li><strong>Esperar un milagro.</strong> Comprar "schema" como solución de posicionamiento y decepcionarse a los tres meses. Es una mejora técnica que suma, no un atajo.</li>
                    </ol>
                </section>

                <section id="por-industria">
                    <h2>Cómo se ve esto en tu industria</h2>

                    <h3>Clínicas y consultorios</h3>
                    <p>
                        Usa el subtipo de clínica o consultorio médico con tus horarios, dirección y especialidades, y marca a cada médico con su nombre y especialidad cuando tenga su propia página. En salud, Google cuida mucho la confianza, así que todo lo que marques debe coincidir exactamente con lo que dice tu sitio y tu ficha.
                    </p>

                    <h3>Despachos jurídicos y contables</h3>
                    <p>
                        Existen subtipos específicos para servicios legales y contables. Combínalos con una página por área de práctica descrita como servicio, y con los artículos de tu blog marcados con autor y fecha, porque en temas legales y fiscales la fecha de actualización le importa tanto a Google como a tu cliente.
                    </p>

                    <h3>Desarrolladoras inmobiliarias</h3>
                    <p>
                        La desarrolladora va como organización; cada proyecto, como lugar con su dirección. Si haces lanzamientos o recorridos con fecha, márcalos como evento. Y cuando un proyecto se vende, actualiza o retira su información para que Google no siga mostrando unidades que ya no existen, algo que explicamos en <a href="/blog/seo-para-desarrollos-inmobiliarios">SEO para desarrollos inmobiliarios</a>.
                    </p>

                    <h3>Industrial B2B</h3>
                    <p>
                        Si publicas un catálogo, marcar cada producto con su modelo, especificaciones y fabricante ayuda a que aparezcas cuando alguien busca un número de parte exacto. Es de los pocos casos donde el tipo de producto tiene mucho sentido para una empresa que no vende en línea.
                    </p>
                </section>

                <section id="como-medirlo">
                    <h2>Cómo medirlo y qué esperar</h2>
                    <p>
                        Antes de publicar, pasa cada tipo de página por la <strong>Prueba de resultados enriquecidos</strong> de Google: te dice si el código es válido y para qué resultados califica. Después de publicar, la herramienta de inspección de URLs de Search Console confirma que Google encontró los datos, y los informes de mejoras te avisan si algo se rompe en todo el sitio.
                    </p>
                    <p>
                        Para ver el efecto, abre el informe de Rendimiento y usa el filtro de aparición en búsquedas: ahí aparecen los clics e impresiones que vinieron de resultados enriquecidos. Si sale vacío, como pasa en muchos sitios nuevos, todavía no estás obteniendo ninguno, y eso también es información útil.
                    </p>
                    <p>
                        Sobre los tiempos: Google tiene que volver a rastrear cada página para leer el código nuevo, así que los cambios tardan desde días hasta algunas semanas en reflejarse. Si quieres acelerar las páginas más importantes, solicita su indexación desde Search Console.
                    </p>
                </section>

