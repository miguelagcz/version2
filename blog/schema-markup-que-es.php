                    <details>
                        <summary>¿Qué es JSON-LD?</summary>
                        <p>Es el formato que Google recomienda para escribir datos estructurados. Es un bloque de código que va en el encabezado de la página, separado del texto que ve el visitante, donde describes en un formato estándar quién eres, qué ofreces y cómo contactarte.</p>
                        <p>Su ventaja es práctica: como no se mezcla con el diseño, se puede generar de forma automática desde la plantilla del sitio y mantener sin tocar el contenido visible. Existen otros dos formatos, Microdata y RDFa, que se escriben dentro del HTML del texto, pero son más fáciles de romper cuando alguien edita la página.</p>
                    </details>

                    <details>
                        <summary>¿Por qué no me salen las estrellas de reseñas en Google?</summary>
                        <p>Por varias razones posibles. La más común es que Google no muestra estrellas cuando un negocio marca en su propio sitio las reseñas sobre sí mismo usando los tipos de negocio local u organización. Esas reseñas "autoservidas" no califican, aunque estén bien escritas en el código.</p>
                        <p>Además, tener el código correcto no obliga a Google a mostrar el resultado enriquecido; solo te vuelve elegible. Para un negocio de servicios, el lugar donde las estrellas sí aparecen es tu ficha de Google Business Profile, que se alimenta de reseñas que dejan tus clientes directamente en Google.</p>
                    </details>

                    <details>
                        <summary>¿Sigue sirviendo el schema de preguntas frecuentes?</summary>
                        <p>Para mostrar el acordeón de preguntas en los resultados, casi nunca. Desde agosto de 2023, Google limitó esos resultados enriquecidos a sitios de gobierno y de salud con mucha autoridad, y también retiró los de instrucciones paso a paso. Un negocio normal ya no los va a ver aparecer.</p>
                        <p>Eso no vuelve inútil el código. Dejarlo no causa ningún problema, ayuda a que Google entienda qué preguntas responde tu página y les da material ordenado a los buscadores y asistentes que arman respuestas con inteligencia artificial. Lo que no conviene es venderlo, ni comprarlo, como si fuera a cambiar tu resultado en Google.</p>
                    </details>

                    <details>
                        <summary>¿Necesito un programador para agregar schema markup?</summary>
                        <p>Depende de cómo está hecho tu sitio. Muchas plataformas y plugins generan los tipos básicos de forma automática, y para una página suelta puedes escribir el bloque a mano y pegarlo en el encabezado. Para un sitio con decenas de páginas, lo sano es que la plantilla lo genere sola a partir de los datos de cada página.</p>
                        <p>Lo que sí necesitas es que alguien lo revise. Un plugin que genera un tipo equivocado, o dos plugins que generan datos contradictorios, hacen más daño que no tener nada. Pasa cada tipo de página por la Prueba de resultados enriquecidos de Google antes de darlo por terminado.</p>
                    </details>
