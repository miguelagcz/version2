                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Qué Nivel de Calidad se considera bueno?</summary>
                        <p>No existe un número mágico universal, pero en términos generales, un Nivel de Calidad de 7 en adelante suele considerarse sólido, mientras que por debajo de 5 suele ser señal de que algo necesita atención real. Más importante que el número en sí es mirar los tres componentes por separado: puedes tener un Nivel de Calidad de 6 con los tres componentes en un punto razonable, o un 6 con dos componentes excelentes y uno muy débil arrastrando el promedio hacia abajo. El segundo caso suele ser más fácil de arreglar, porque ya sabes exactamente dónde enfocar el esfuerzo.</p>
                    </details>

                    <details>
                        <summary>¿Puedo tener un Nivel de Calidad distinto para la misma palabra clave en diferentes grupos de anuncios?</summary>
                        <p>Sí, y de hecho es bastante común. El Nivel de Calidad se evalúa en el contexto de cómo esa palabra clave, el anuncio asociado a ella y la página de destino trabajan juntos dentro de un grupo de anuncios específico. Si usas la misma palabra clave en dos grupos de anuncios distintos, con textos de anuncio y páginas de destino diferentes, es perfectamente posible obtener resultados distintos en cada uno, porque en realidad estás evaluando combinaciones distintas, no la palabra clave de forma aislada.</p>
                    </details>

                    <details>
                        <summary>¿Bajar mi Nivel de Calidad significa que Google va a dejar de mostrar mi anuncio?</summary>
                        <p>No necesariamente de forma inmediata, pero sí afecta tus probabilidades. Un Nivel de Calidad bajo generalmente significa que necesitas pujar más alto para compensar esa debilidad y seguir siendo competitivo en la subasta, lo cual eleva tu costo por clic. En casos donde la calidad es consistentemente muy baja, es posible que tu anuncio deje de ser apto para ciertas búsquedas porque no logra superar el umbral mínimo del Ranking del Anuncio, sin importar cuánto estés dispuesto a pagar.</p>
                    </details>

                    <details>
                        <summary>¿La velocidad de mi sitio afecta mi experiencia de página de destino?</summary>
                        <p>Sí, es uno de los factores que se toman en cuenta dentro de ese componente. Una página que tarda mucho en cargar, sin importar qué tan bien escrito esté el contenido, perjudica la experiencia de quien llegó ahí después de hacer clic, y eso se refleja en la evaluación de ese componente. Vale la pena revisar la velocidad de carga de tus páginas de destino con la misma seriedad con la que revisas el copy de tus anuncios, porque ambos elementos pesan en el mismo resultado final.</p>
                    </details>

                    <details>
                        <summary>¿Vale la pena pausar palabras clave con Nivel de Calidad muy bajo?</summary>
                        <p>Depende de qué tan bajo y de cuánto volumen te traiga esa palabra clave. Una palabra clave con un Nivel de Calidad de 2 o 3 casi siempre te está costando más de lo que debería por cada clic, así que antes de pausarla del todo vale la pena intentar un ajuste específico (un anuncio nuevo más alineado, una página de destino dedicada) y medir si mejora. Si después de ese intento sigue igual de baja y no representa un volumen importante para tu negocio, pausarla suele liberar presupuesto que rinde mejor en otras palabras clave con mejor calidad.</p>
                    </details>
