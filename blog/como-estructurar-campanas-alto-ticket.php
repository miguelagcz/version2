                <section id="que-es-una-estructura-de-campanas-para-alto-ticket-y-en-que-se-diferencia-de-una-de-e-commerce">
                    <h2>Qué es una estructura de campañas para alto ticket y en qué se diferencia de una de e-commerce</h2>
                    <p>
                        Estructurar una cuenta de Google Ads significa decidir cómo se dividen el presupuesto, las palabras clave y los anuncios entre campañas y grupos de anuncios, de modo que cada búsqueda reciba un anuncio y una página de destino que le hablen directamente a esa intención.
                    </p>
                    <p>
                        En e-commerce, esa estructura suele organizarse alrededor del catálogo: una campaña por categoría de producto, alimentada por un feed con cientos o miles de artículos, optimizada para volumen de conversiones. En un negocio de alto ticket, el volumen de búsquedas es bajo, cada conversión vale mucho y el ciclo de decisión puede tomar semanas. Por eso la estructura no se organiza por catálogo, sino por intención de búsqueda y por etapa de decisión del comprador, algo que se nota incluso en la elección entre <a href="/blog/busqueda-vs-display-vs-performance-max">campañas de Búsqueda, Display o Performance Max</a> para cada objetivo.
                    </p>
                </section>

                <section id="los-tres-niveles-que-tienes-que-ordenar-antes-de-subir-presupuesto">
                    <h2>Los tres niveles que tienes que ordenar antes de subir presupuesto</h2>
                    <p>
                        Google Ads organiza toda cuenta en tres capas: la cuenta, la campaña y el grupo de anuncios. Cada una cumple un trabajo distinto, y mezclarlas es la causa más común de campañas caras que no convierten.
                    </p>
                    <h3>La cuenta</h3>
                    <p>
                        La cuenta es el contenedor de todo: presupuesto total, facturación, conversiones registradas y acceso de usuarios. Un negocio debería tener una sola cuenta de Google Ads por marca, no una cuenta distinta por cada campaña o por cada persona del equipo que la administra. Cuando hay varias cuentas para la misma marca, Google pierde el historial de conversiones que necesita para optimizar, y el negocio pierde visibilidad de cuánto está gastando en total.
                    </p>
                    <h3>La campaña</h3>
                    <p>
                        La campaña es donde se define el presupuesto diario, la ubicación geográfica, el tipo de campaña y, en la mayoría de los casos, el objetivo de negocio. Aquí es donde de verdad se nota la diferencia entre un negocio de alto ticket y uno transaccional:
                    </p>
                    <ul>
                        <li><strong>Una campaña por línea de negocio, no por palabra clave.</strong> Si un despacho legal ofrece derecho corporativo y derecho familiar, cada línea necesita su propia campaña, con su propio presupuesto y sus propias métricas, porque el valor de un cliente y el costo por lead son distintos entre ambas.</li>
                        <li><strong>Presupuesto dedicado, nunca compartido entre campañas que compiten por el mismo cliente.</strong> Cuando dos campañas persiguen al mismo tipo de prospecto, terminan pujando una contra la otra y subiendo el costo por clic sin necesidad.</li>
                        <li><strong>Segmentación geográfica separada cuando el área de cobertura cambia.</strong> Un desarrollo en Zapopan y otro en la Riviera de Chapala no deberían compartir campaña aunque los venda la misma constructora, porque el radio de búsqueda relevante es distinto para cada uno.</li>
                    </ul>
                    <h3>El grupo de anuncios</h3>
                    <p>
                        El grupo de anuncios es el nivel más fino: agrupa las palabras clave que comparten la misma intención exacta y los anuncios que responden a esa intención. La regla práctica que usamos en Flova Media es simple: si dentro de un grupo hay palabras clave que necesitarían un anuncio distinto para sonar naturales, ese grupo está mal armado y hay que dividirlo. En la práctica, esto casi siempre significa grupos de entre 10 y 20 palabras clave, nunca los 80 que mencionábamos al inicio.
                    </p>
                </section>

                <section id="los-errores-mas-comunes-al-estructurar-campanas-de-alto-ticket">
                    <h2>Los errores más comunes al estructurar campañas de alto ticket</h2>
                    <p>
                        Ordenados por qué tan seguido los vemos en cuentas nuevas que llegan a auditoría, no por orden alfabético.
                    </p>
                    <ul>
                        <li><strong>Un solo grupo de anuncios genérico para todo el negocio.</strong> Es el error de origen del ejemplo de la inmobiliaria: mezclar preventa, renta y terrenos en el mismo grupo produce anuncios que no le hablan bien a nadie.</li>
                        <li><strong>No separar por etapa de consciencia del comprador.</strong> Alguien que busca "qué es un crédito hipotecario" no está en el mismo punto de decisión que alguien que busca el nombre exacto de un desarrollo. Tratarlos en la misma campaña, con el mismo anuncio y la misma página de destino, baja la tasa de conversión de ambos.</li>
                        <li><strong>Usar concordancia amplia sin una lista de <a href="/blog/palabras-clave-negativas">palabras clave negativas</a> desde el primer día.</strong> En alto ticket, cada clic desperdiciado en una búsqueda de empleo o de información gratuita pesa más, porque el presupuesto mensual suele ser más bajo en volumen absoluto que el de un e-commerce.</li>
                        <li><strong>Medir la campaña solo por clics o por costo por clic.</strong> Un costo por clic alto puede ser perfectamente rentable si esa palabra clave trae compradores reales; lo que hay que vigilar es el costo por lead calificado y, más adelante, el costo por venta.</li>
                        <li><strong>Duplicar presupuesto en campañas que en realidad compiten entre sí.</strong> Sucede seguido cuando una agencia hereda una cuenta armada por prueba y error: hay dos o tres campañas apuntando al mismo público, cada una con su propio presupuesto, subiendo artificialmente el costo por clic de ambas.</li>
                    </ul>
                </section>

                <section id="ejemplos">
                    <h2>Cómo se ve esta estructura por industria</h2>
                    <p>
                        Los negocios de alto ticket comparten dos cosas: el ticket promedio es alto y el comprador investiga antes de contactar. Pero la forma de aplicar la estructura cambia según la industria.
                    </p>
                    <h3>Inmobiliaria</h3>
                    <p>
                        Aquí conviene una campaña por desarrollo o por tipo de producto (preventa, entrega inmediata, terrenos), nunca una sola campaña para toda la constructora. El grupo de anuncios se separa además por etapa: búsquedas de marca del desarrollo van en un grupo, búsquedas genéricas de la zona van en otro, porque el costo por clic y la tasa de conversión de ambos son muy distintos.
                    </p>
                    <h3>Energía solar</h3>
                    <p>
                        El reto particular es que mucha gente busca información antes de estar lista para cotizar. Conviene separar la campaña informativa (paneles solares, ahorro en luz) de la campaña de cotización directa, y dirigir cada una a una página distinta: la primera a contenido educativo, la segunda a un formulario o simulador de ahorro.
                    </p>
                    <h3>Despachos legales o contables</h3>
                    <p>
                        Cada área de práctica es, en los hechos, un negocio distinto con su propio comprador y su propio valor de cliente. Derecho corporativo, derecho familiar y contabilidad fiscal deberían vivir en campañas separadas, con anuncios que usen el vocabulario exacto de cada especialidad en vez de un mensaje genérico de "asesoría legal".
                    </p>
                    <h3>Industrial B2B</h3>
                    <p>
                        Las búsquedas suelen ser muy específicas (una pieza, un proceso, una certificación) y de bajo volumen, lo que hace tentador meterlas todas juntas para acumular datos más rápido. El problema es que esa mezcla diluye la relevancia del anuncio. Aquí ayuda organizar por línea de producto o por proceso industrial, aunque cada grupo tenga solo unas cuantas palabras clave.
                    </p>
                </section>

                <section id="como-medir-si-la-estructura-esta-funcionando">
                    <h2>Cómo medir si la estructura está funcionando</h2>
                    <p>
                        La señal más clara de que la estructura funciona no es el costo por clic, sino el <a href="/blog/quality-score-que-es-y-como-bajar-tu-costo-por-clic">Nivel de Calidad</a> de cada grupo de anuncios: cuando las palabras clave, el anuncio y la página de destino coinciden en intención, ese nivel sube y el costo por clic baja de forma natural, sin necesidad de pelear la puja.
                    </p>
                    <p>
                        Otra señal práctica: revisa el reporte de términos de búsqueda de cada campaña una vez por semana durante el primer mes. Si encuentras búsquedas que no tienen nada que ver con lo que esa campaña vende, no es un problema de presupuesto, es un síntoma de que la estructura o la lista de negativas necesita ajuste.
                    </p>
                </section>

