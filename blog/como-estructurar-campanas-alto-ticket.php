                            Toma más tiempo de configuración inicial, eso es cierto. Pero el costo de no separar suele ser mayor: presupuesto gastado en clics de baja intención, anuncios genéricos con tasas de conversión bajas y un equipo de ventas que no sabe de qué campaña vino cada lead.
                        </p>
                        <p>
                            En la práctica, una vez que la estructura está armada, administrar varias campañas bien definidas toma menos tiempo semanal que perseguir los problemas de una campaña mezclada, porque los reportes ya vienen separados por línea de negocio y es más fácil ver qué está funcionando y qué no.
                        </p>
                    </details>

                    <details>
                        <summary>¿Debo usar concordancia exacta en todas mis palabras clave de alto ticket?</summary>
                        <p>
                            No necesariamente. La concordancia exacta da más control, pero también limita el volumen de búsquedas que capturas, algo que ya es escaso en nichos de alto ticket. Un punto de partida razonable es usar concordancia de frase para las palabras clave centrales del negocio y reservar la concordancia exacta para los términos donde el costo por clic es más alto y el margen de error más caro.
                        </p>
                        <p>
                            Lo que sí es prácticamente obligatorio en cualquier concordancia es mantener una lista de palabras clave negativas activa y revisarla seguido, porque incluso la concordancia de frase puede traer búsquedas que no tienen relación con lo que vendes.
                        </p>
                    </details>

                    <details>
                        <summary>¿Qué hago si ya tengo una cuenta desordenada con meses de historial?</summary>
                        <p>
                            No la borres ni la vuelvas a crear desde cero: perderías el historial de conversiones que Google usa para optimizar la puja. Lo recomendable es reestructurar por fases, campaña por campaña, empezando por la que más presupuesto consume.
                        </p>
                        <p>
                            Primero separa los grupos de anuncios mezclados dentro de esa campaña, revisa el reporte de términos de búsqueda de las últimas semanas para armar la lista de negativas, y solo después crea campañas nuevas para las líneas de negocio que todavía comparten espacio con otras.
                        </p>
                    </details>

                    <details>
                        <summary>¿La estructura de la cuenta afecta el Nivel de Calidad o solo el orden interno?</summary>
                        <p>
                            Sí lo afecta, y de forma directa. El Nivel de Calidad se calcula, entre otras cosas, a partir de qué tan relevante es tu anuncio para la palabra clave que lo activó y qué tan relevante es tu página de destino para ese anuncio. Una estructura donde cada grupo de anuncios tiene pocas palabras clave con la misma intención hace que esa relevancia sea alta casi por diseño.
                        </p>
                        <p>
                            Por eso arreglar la estructura suele bajar el costo por clic sin tocar el presupuesto ni la puja: no es magia, es que el sistema deja de tener que adivinar qué tan bien encajan tu anuncio y tu palabra clave.
                        </p>
                    </details>
