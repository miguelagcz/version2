                <section id="por-que-escalar-es-dificil">
                    <h2>Por qué escalar es más difícil que encontrar la campaña rentable</h2>
                    <p>
                        Una campaña rentable con un presupuesto pequeño está aprovechando la parte más receptiva y accesible de tu público objetivo, la que menos esfuerzo le cuesta a Meta encontrar dentro de la subasta. Cuando aumentas el presupuesto de forma agresiva, el sistema de entrega tiene que empezar a competir por porciones de público cada vez menos obvias, lo que naturalmente sube el costo por resultado. Escalar bien no significa evitar por completo que el costo suba un poco; significa gestionar ese aumento de forma que el ROAS se mantenga dentro de un rango aceptable mientras el volumen de resultados crece.
                    </p>
                </section>

                <section id="escalado-vertical">
                    <h2>Escalado vertical: más presupuesto al mismo público</h2>
                    <p>
                        El escalado vertical consiste en aumentar el presupuesto de un conjunto de anuncios que ya está funcionando, manteniendo el mismo público y el mismo creativo. Es la forma más directa de escalar, pero también la que más rápido puede reiniciar tu fase de aprendizaje si el incremento es demasiado agresivo. La práctica recomendada es aumentar el presupuesto en incrementos de 15% a 20% cada 3 a 4 días, en lugar de saltos grandes de un día para otro, lo que le da al sistema de entrega tiempo suficiente para ajustarse a la nueva escala sin perder por completo la eficiencia ya encontrada.
                    </p>
                </section>

                <section id="escalado-horizontal">
                    <h2>Escalado horizontal: más públicos, más creativos</h2>
                    <p>
                        El escalado horizontal consiste en crecer el volumen total de la cuenta sin depender únicamente de subir el presupuesto de un solo conjunto de anuncios: se agregan nuevos conjuntos con públicos similares adicionales, nuevas variantes de creativo, o incluso nuevas campañas dirigidas a segmentos ligeramente distintos del mismo público objetivo. Esta forma de escalar tiende a ser más estable que el escalado vertical puro, porque distribuye el crecimiento entre varias fuentes de tráfico en lugar de forzar a un solo conjunto de anuncios a absorber todo el incremento de presupuesto.
                    </p>
                </section>

                <section id="cuando-usar-cada-uno">
                    <h2>Cuándo usar cada tipo de escalado</h2>
                    <p>
                        El escalado vertical suele ser la primera opción cuando el conjunto de anuncios todavía tiene margen dentro de un público que no ha mostrado señales de saturación, porque es más simple de ejecutar y de medir. El escalado horizontal se vuelve necesario cuando el escalado vertical empieza a mostrar rendimientos decrecientes, es decir, cuando cada incremento de presupuesto genera cada vez menos resultados adicionales de los que generaba el incremento anterior. Muchas cuentas maduras terminan usando una combinación de ambos: escalado vertical moderado dentro de cada conjunto que sigue funcionando bien, y escalado horizontal constante para seguir alimentando la cuenta con públicos y creativos frescos.
                    </p>
                </section>

                <section id="senales-de-saturacion">
                    <h2>Señales de que tu público se está saturando</h2>
                    <ul>
                        <li><strong>La frecuencia sube de forma sostenida.</strong> Si la misma persona está viendo tu anuncio cada vez más veces sin que eso se traduzca en más conversiones, el público disponible se está agotando.</li>
                        <li><strong>El CPM sube sin que cambie la competencia externa.</strong> Si otras variables se mantienen estables pero el CPM sigue subiendo, es señal de que estás compitiendo cada vez más contigo mismo por el mismo grupo reducido de personas.</li>
                        <li><strong>El costo por resultado crece más rápido que el volumen de resultados.</strong> Cuando cada incremento de presupuesto genera proporcionalmente menos resultados que el anterior, el público ya no tiene la misma capacidad de absorber más inversión de forma eficiente.</li>
                    </ul>
                    <p>
                        Cuando aparecen estas señales, suele ser el momento de pausar el escalado vertical en ese conjunto específico y mover el crecimiento hacia el escalado horizontal, ya sea ampliando el público, sumando un público similar adicional, o refrescando el creativo.
                    </p>
                </section>

                <section id="kpis-durante-el-escalado">
                    <h2>Qué KPIs vigilar durante el proceso</h2>
                    <p>
                        Durante cualquier proceso de escalado, el ROAS y el costo por resultado son los indicadores que deberían guiar cada decisión, más que el volumen absoluto de resultados. Es tentador celebrar que una campaña genera el doble de leads después de duplicar el presupuesto, pero si el costo por lead también se duplicó, el negocio no necesariamente está mejor que antes. La meta de un buen escalado es crecer el volumen de resultados mientras el ROAS se mantiene dentro de un rango que tu negocio pueda sostener de forma rentable, no simplemente generar más actividad en la cuenta.
                    </p>
                </section>

                <section id="escalar-en-alto-ticket">
                    <h2>Escalar en negocios de alto ticket</h2>
                    <p>
                        Para negocios de alto ticket, como una desarrolladora inmobiliaria o una empresa de energía solar, el escalado suele ser más lento por naturaleza, porque el público calificado para una decisión de compra grande es, casi por definición, más reducido que el de un negocio de consumo masivo. Esto hace que el escalado horizontal (sumar públicos similares adicionales, explorar zonas geográficas nuevas, ampliar a públicos de inversión o expansión internacional) sea especialmente relevante en este tipo de negocios, ya que el escalado vertical puro dentro de un mismo público reducido tiende a agotarse mucho más rápido que en industrias de consumo masivo con audiencias potenciales mucho más grandes.
                    </p>
                </section>

