                    </details>

                    <details>
                        <summary>¿El escalado funciona igual en todas las industrias o varía mucho?</summary>
                        <p>Los principios generales de escalado (incrementos graduales, vigilar el ROAS, distinguir entre escalado vertical y horizontal) aplican de forma similar en cualquier industria, pero la velocidad y el techo real de escalado sí varían considerablemente según qué tan grande sea el público potencial disponible. Un negocio de consumo masivo con un público objetivo de millones de personas tiene, en teoría, mucho más margen de escalado vertical antes de saturar su audiencia que un negocio de alto ticket con un público objetivo naturalmente más reducido, como suele ser el caso en bienes raíces o energía solar. Esto no significa que los negocios de alto ticket no puedan escalar de forma significativa, solo que el camino más realista para ellos suele apoyarse más en el escalado horizontal (nuevas zonas geográficas, nuevos ángulos de público, nuevos formatos de creativo) que en simplemente seguir subiendo el presupuesto de un mismo conjunto de anuncios de forma indefinida.</p>
                    </details>
