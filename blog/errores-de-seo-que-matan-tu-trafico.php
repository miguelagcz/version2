                <section id="por-que-cae-el-trafico">
                    <h2>Por qué cae el tráfico y cómo saber si es tu culpa</h2>
                    <p>
                        Antes de arreglar nada, hay que saber qué se rompió. La documentación oficial de Google agrupa las caídas de tráfico orgánico en cinco causas: problemas técnicos, problemas de seguridad, acciones manuales por incumplir sus políticas, cambios de algoritmo y cambios en el interés de la gente por lo que vendes. Las dos últimas no son errores tuyos. Las tres primeras sí.
                    </p>
                    <p>
                        La forma de la caída te dice mucho. Un desplome vertical de un día a otro apunta a algo técnico o a una sanción: el sitio se cayó, alguien bloqueó a los rastreadores, se venció el certificado. Una pendiente suave de varias semanas apunta a contenido que se quedó atrás o a un ajuste de algoritmo. Y una caída que se repite cada año en las mismas fechas no es una caída, es tu temporada baja.
                    </p>
                    <p>
                        Hay un cuarto escenario que confunde a medio mundo: las impresiones se mantienen o suben, pero los clics bajan. Ahí tu posición está bien. Lo que cambió fue la página de resultados alrededor tuyo, con más anuncios, más bloques de respuesta o un competidor con un título mejor escrito.
                    </p>
                    <p>
                        <strong>Regla práctica:</strong> si Search Console está estable y tu analítica se hundió, el problema es de medición, no de posicionamiento web orgánico. Revisa primero que la etiqueta de analítica siga instalada después del último cambio en el sitio.
                    </p>
                </section>

                <section id="errores-tecnicos-seo">
                    <h2>Errores técnicos que te sacan del índice</h2>
                    <p>
                        Los errores técnicos de SEO son los más caros porque son binarios: o Google puede leer tu página o no puede. No hay término medio. Google pide tres cosas mínimas para mostrar una página: que sus rastreadores no estén bloqueados, que la URL responda correctamente y que el contenido no viole sus políticas. Suena elemental, y aun así la mitad de las auditorías que hacemos encuentran algo roto en ese nivel.
                    </p>
                    <p>Los problemas de SEO técnico que más se repiten:</p>
                    <ul>
                        <li><strong>La etiqueta noindex olvidada.</strong> Se pone mientras el sitio está en desarrollo para que Google no vea la versión a medias, y nadie la quita el día del lanzamiento. Es el error más caro y el más fácil de arreglar.</li>
                        <li><strong>El robots.txt que bloquea de más.</strong> Una línea mal puesta puede cerrarle la puerta al rastreador en un directorio completo, por ejemplo el de tus páginas de servicio.</li>
                        <li><strong>Migraciones sin redirecciones.</strong> Cambiaste de sitio y las URLs viejas ahora dan error. Todo el historial que esas páginas habían acumulado se queda huérfano en el camino.</li>
                        <li><strong>Etiquetas canónicas apuntando al lugar equivocado.</strong> Le estás diciendo a Google que la versión buena de tu página es otra, y a veces esa otra es el sitio de pruebas.</li>
                        <li><strong>Contenido que solo existe si corre JavaScript.</strong> Si el texto no está en el HTML que llega, el rastreador puede no verlo nunca.</li>
                        <li><strong>Velocidad y estabilidad visual.</strong> No sacan tu página del índice, pero sí te cuestan posiciones y conversiones cuando compites contra alguien que carga en la mitad de tiempo. Lo desglosamos en la guía de <a href="/blog/core-web-vitals">Core Web Vitals</a>.</li>
                    </ul>
                    <p>
                        Si quieres el detalle completo de cómo funciona esta capa, está en la guía de <a href="/blog/seo-tecnico-velocidad-indexacion-errores">qué es el SEO técnico</a>. Para efectos de una auditoría de SEO técnico rápida, con revisar indexación, redirecciones y velocidad cubres el noventa por ciento de lo que rompe un sitio.
                    </p>
                </section>

                <section id="errores-de-contenido">
                    <h2>Errores de contenido: canibalización y relleno</h2>
                    <p>
                        Aquí es donde se pierden los negocios de alto ticket. No porque escriban poco, sino porque escriben mucho de lo mismo sin darse cuenta.
                    </p>
                    <h3>Canibalización: tus propias páginas compitiendo entre ellas</h3>
                    <p>
                        Una clínica de ortodoncia publicó en dos años once artículos sobre brackets. Once. Google tenía que elegir cuál mostrar para "ortodoncia en Guadalajara" y terminó rotando entre tres, sin posicionar bien ninguno. La autoridad que debía concentrarse en una página se repartió en once pedacitos.
                    </p>
                    <p>
                        La solución rara vez es escribir más. Es fusionar: tomas el artículo con mejor desempeño, le pasas lo bueno de los demás, y rediriges los sobrantes hacia él. Una página fuerte vale más que cinco tibias. Para evitar caer en esto desde el principio, cada tema necesita una sola página objetivo asignada antes de escribir, algo que explicamos en la guía de <a href="/blog/como-hacer-investigacion-de-palabras-clave">investigación de palabras clave</a>.
                    </p>
                    <h3>Contenido escrito para el buscador, no para el cliente</h3>
                    <p>
                        Las políticas de spam de Google nombran de forma explícita el contenido creado sobre todo para posicionar en vez de para ayudar a alguien. El relleno de palabras clave, los textos generados en masa y las páginas que repiten lo mismo cambiando la ciudad entran ahí. Y no hablamos de una zona gris: es una de las conductas que pueden hacer que una página o el sitio entero baje o desaparezca de los resultados.
                    </p>
                    <p>
                        El síntoma clásico en un sitio de alto ticket es la página de servicio de 300 palabras que repite "despacho jurídico corporativo CDMX" seis veces y no responde ni una duda real del prospecto. Posiciona un tiempo, luego se cae, y el dueño concluye que el SEO no sirve.
                    </p>
                    <h3>Contenido que envejeció sin que nadie lo notara</h3>
                    <p>
                        Precios de 2023, un programa de incentivos que ya no existe, un catálogo con desarrollos entregados hace dos años. El contenido desactualizado pierde posiciones despacio, sin señal de alarma. Si tienes más de treinta páginas, necesitas un calendario de revisión, no buena memoria.
                    </p>
                    <h3>Descuidar el on page SEO</h3>
                    <p>
                        Títulos duplicados en veinte páginas, descripciones vacías, imágenes sin texto alternativo, encabezados usados como decoración en lugar de estructura. Ninguno de estos errores comunes tumba un sitio por sí solo, pero juntos le quitan al buscador las señales que necesita para entender de qué trata cada página. La lista completa está en el <a href="/blog/seo-on-page-checklist">checklist de SEO on page</a>, y los <a href="/blog/schema-markup-que-es">datos estructurados</a> son la capa que le termina de explicar a Google qué es cada cosa.
                    </p>
                </section>

                <section id="errores-de-enlaces">
                    <h2>Errores de enlaces y autoridad</h2>
                    <p>
                        Dos negocios con el mismo contenido y la misma velocidad no posicionan igual si uno tiene diez sitios serios recomendándolo y el otro tiene cero. Los enlaces siguen pesando. El problema es cómo los consigue la gente.
                    </p>
                    <p>
                        Comprar paquetes de enlaces es la forma más rápida de meterse en problemas. Google clasifica como spam los esquemas de enlaces, incluido comprarlos y venderlos para manipular posiciones. El paquete de "500 backlinks por 2,000 pesos" no es una ganga con riesgo: es exactamente la conducta que sus sistemas buscan detectar.
                    </p>
                    <p>
                        El error contrario es igual de común: no hacer nada. Una desarrolladora inmobiliaria con seis proyectos entregados, prensa local y alianzas con notarías tiene material de sobra para ganar enlaces legítimos y no pide uno solo. Cómo se construye eso está en la guía de <a href="/blog/link-building-enlaces-de-calidad">link building con enlaces de calidad</a>.
                    </p>
                    <p>
                        Y luego está el enlazado interno, que es gratis y casi nadie usa. Páginas nuevas que no reciben un solo enlace desde el resto del sitio quedan aisladas, y tanto el usuario como el rastreador tardan en llegar a ellas. Cada artículo nuevo debería enlazar hacia arriba, hacia su página principal de tema, y hacia los lados, hacia sus hermanos.
                    </p>
                </section>

                <section id="errores-por-industria">
                    <h2>Cómo se ve esto por industria</h2>
                    <p>
                        El mismo error se disfraza distinto según el negocio. Estos son los patrones que más vemos en las verticales de alto ticket.
                    </p>
                    <ul>
                        <li><strong>Clínicas y consultorios.</strong> Sedes múltiples con la misma página duplicada cambiando solo el nombre de la colonia, y la ficha de Google sin actualizar tras una mudanza. El tráfico local se va completo. El caso análogo en bienes raíces lo tratamos en <a href="/blog/seo-local-para-inmobiliarias">SEO local para inmobiliarias</a>.</li>
                        <li><strong>Despachos jurídicos y contables.</strong> Blogs escritos en lenguaje de circular fiscal que nadie busca así. El prospecto teclea "cuánto me cobra el SAT por vender mi casa", no el nombre técnico del artículo de la ley.</li>
                        <li><strong>Industrial B2B.</strong> Catálogos en PDF y fichas de producto cargadas por JavaScript que el rastreador no alcanza a leer. Miles de referencias invisibles para el buscador.</li>
                        <li><strong>Energía solar.</strong> Páginas que hablan de la tecnología del panel y no del recibo de luz. Además, contenido de cobertura nacional cuando la venta es por zona.</li>
                        <li><strong>Desarrolladoras inmobiliarias.</strong> Micrositios por proyecto que se apagan al vender la última unidad, tirando a la basura todo el historial acumulado. La alternativa la vemos en <a href="/blog/seo-para-desarrollos-inmobiliarios">SEO para desarrollos inmobiliarios</a>.</li>
                    </ul>
                </section>

                <section id="como-diagnosticar">
                    <h2>Cómo diagnosticar tu caída en una tarde</h2>
                    <p>
                        No necesitas contratar a nadie para saber qué pasó. Necesitas Search Console y una hora sin interrupciones. El orden importa, porque cada paso descarta una causa.
                    </p>
                    <ul>
                        <li><strong>Encuentra la fecha exacta.</strong> Abre el informe de rendimiento a dieciséis meses y localiza dónde se quiebra la línea. Esa fecha es tu mejor pista: todo lo que sigue consiste en averiguar qué cambió ese día.</li>
                        <li><strong>Separa clics de impresiones.</strong> Si cayeron juntos, perdiste posiciones. Si las impresiones aguantan y los clics no, el problema está en tus títulos o en cómo cambió la página de resultados.</li>
                        <li><strong>Revisa si es todo el sitio o unas páginas.</strong> Filtra por página y por consulta. Una caída concentrada en una sección apunta a algo técnico en esa sección; una caída pareja apunta a algo general.</li>
                        <li><strong>Descarta lo grave.</strong> Entra a acciones manuales y a problemas de seguridad en Search Console. Si hay algo, sale ahí y se atiende primero.</li>
                        <li><strong>Compara contra el año pasado.</strong> Si la misma caída ocurrió en las mismas fechas el año anterior, es estacionalidad. Deja de buscar culpables.</li>
                        <li><strong>Pregunta qué se tocó.</strong> La causa más común que encontramos es un cambio en el sitio que nadie relacionó con el SEO: un rediseño, un plugin nuevo, una migración de servidor.</li>
                    </ul>
                    <p>
                        La métrica que importa al final no son las visitas. Son los clics de las consultas que traen prospectos con dinero. Un sitio puede perder cuarenta por ciento del tráfico web y no perder una sola venta si lo que se fue era tráfico informativo. Por eso conviene mirar el desempeño por grupo de páginas, no el total. Si el diagnóstico apunta a que vas a tardar en recuperarte, ahí es donde tiene sentido evaluar <a href="/blog/seo-vs-sem-cuando-invertir-en-cada-uno">cuándo conviene invertir en SEO y cuándo en anuncios</a> mientras tanto.
                    </p>
                </section>

