                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Cuáles son los errores técnicos de SEO más graves?</summary>
                        <p>Los que impiden que Google lea o muestre tu página: una etiqueta noindex activa en producción, un robots.txt que bloquea directorios importantes, páginas que responden con error, redirecciones rotas después de una migración y etiquetas canónicas mal apuntadas. Son los más graves porque no te bajan de posición, te sacan del índice por completo. Y son silenciosos: el sitio se ve normal en el navegador mientras el buscador no lo ve.</p>
                        <p>Después de esos vienen los que te cuestan posiciones sin borrarte, como la velocidad de carga, la inestabilidad visual y el contenido que depende de JavaScript para existir. Para un negocio de alto ticket estos pesan más de lo que parece, porque tu prospecto compara tres o cuatro proveedores antes de llamar y el que carga lento pierde la comparación antes de decir nada.</p>
                    </details>

                    <details>
                        <summary>Mi tráfico web bajó pero no cambiamos nada en el sitio, ¿qué pasó?</summary>
                        <p>En nuestra experiencia, casi siempre sí se cambió algo, solo que quien lo hizo no lo asoció con el SEO: un rediseño, una actualización de plugin, un cambio de servidor, una limpieza de páginas viejas. Empieza preguntando qué se tocó en la semana de la caída, incluso cosas que parezcan menores. Si de verdad no se movió nada, revisa acciones manuales y problemas de seguridad en Search Console, y compara la fecha con las actualizaciones de algoritmo publicadas por Google.</p>
                        <p>Si nada de eso encaja, quedan dos explicaciones. Una es estacional: compara contra el mismo periodo del año pasado antes de entrar en pánico. La otra es competitiva, y es la más incómoda, porque significa que alguien publicó algo mejor que lo tuyo para tus consultas principales. Ahí el camino es el <a href="/blog/como-hacer-analisis-seo-de-la-competencia">análisis SEO de la competencia</a>, no tocar el sitio al azar.</p>
                    </details>

                    <details>
                        <summary>¿Google puede penalizar mi sitio y cómo me entero?</summary>
                        <p>Sí. Cuando un revisor humano determina que un sitio incumple las políticas de spam, se aplica una acción manual y el aviso aparece en la sección de acciones manuales de Search Console, con el motivo y el alcance. Si no tienes nada ahí, no tienes una penalización manual, por más que el tráfico haya caído. Eso descarta una causa en dos minutos.</p>
                        <p>Lo que sí ocurre sin aviso son los ajustes algorítmicos: nadie te notifica y no hay nada que "levantar". Las causas más comunes en negocios de alto ticket son los enlaces comprados y el contenido producido en masa para posicionar. Si compraste paquetes de enlaces, ese es el primer lugar donde mirar, y limpiar es más rápido que esperar a la siguiente actualización.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto tiempo tarda el SEO orgánico en recuperarse de una caída?</summary>
                        <p>Depende enteramente de la causa, y quien te dé un número sin haber diagnosticado está adivinando. Un error técnico corregido puede revertirse en días o pocas semanas, en cuanto Google vuelve a rastrear las páginas afectadas. Un problema de contenido o de autoridad toma meses, porque implica publicar, consolidar y ganar señales nuevas.</p>
                        <p>Una caída por actualización de algoritmo es la más lenta: la recuperación suele llegar con una actualización posterior, y esas se publican cada varios meses. Por eso el orden correcto es diagnosticar primero y actuar después. Equivocarse de causa cuesta un trimestre completo mejorando lo que no estaba roto. Lo desarrollamos en la guía sobre <a href="/blog/cuanto-tarda-el-seo-en-dar-resultados">cuánto tarda el SEO en dar resultados</a>.</p>
                    </details>

                    <details>
                        <summary>¿Vale la pena una auditoría de SEO técnico si mi sitio es chico?</summary>
                        <p>Sí, y en un sitio chico es más barata y más rentable, porque hay menos páginas que revisar y cada una pesa más en el total. Un sitio de quince páginas donde tres están mal indexadas tiene el veinte por ciento de su negocio digital apagado. Esa revisión se hace en unas horas y no requiere herramientas caras: Search Console, la prueba de resultados enriquecidos y una hoja de cálculo bastan para el primer diagnóstico.</p>
                        <p>Donde sí conviene apoyarse en alguien con experiencia es en la interpretación. Encontrar veinte alertas es fácil; saber cuáles mueven ventas y cuáles son ruido es lo que separa una auditoría útil de un reporte de cien páginas que nadie aplica. Si trabajas con una agencia, pide que cada hallazgo venga con un impacto estimado y un responsable, no solo con una etiqueta de color.</p>
                    </details>
