                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Cuál es un buen costo por lead en Facebook Ads?</summary>
                        <p>No existe un número universal, porque depende completamente de tu industria, tu ticket promedio y tu margen de ganancia. Un costo por lead de 50 pesos puede ser excelente para una tienda en línea de productos de bajo costo y, al mismo tiempo, ser irrelevante para una desarrolladora inmobiliaria que vende propiedades de varios millones de pesos, donde incluso un costo por lead de 500 o 1,000 pesos puede ser perfectamente rentable si la tasa de cierre es sólida. La pregunta correcta no es "cuánto debería costar un lead", sino "cuánto puedo pagar por un lead y seguir siendo rentable", y esa respuesta se calcula dividiendo tu margen de ganancia entre tu tasa de conversión de lead a cliente. Una vez que tienes ese número como referencia, cualquier campaña que se mantenga por debajo de él es, por definición, una campaña rentable, sin importar si el costo por lead parece alto o bajo en términos absolutos comparado con otras industrias.</p>
                    </details>

                    <details>
                        <summary>¿Por qué mi costo por lead sube después de unas semanas?</summary>
                        <p>Esto se conoce como fatiga de audiencia o fatiga del creativo, y es uno de los motivos más comunes por los que una campaña que funcionaba bien empieza a deteriorarse con el tiempo. Cuando le muestras el mismo anuncio al mismo público durante demasiado tiempo, la frecuencia (el número de veces que una misma persona ve tu anuncio) empieza a subir, y las personas que todavía no convirtieron se vuelven cada vez menos receptivas al mensaje, mientras que las que sí eran clientes potenciales ya convirtieron y salieron del público disponible. La solución no siempre es aumentar el presupuesto: muchas veces basta con refrescar el creativo (nuevas imágenes, nuevo copy), ampliar ligeramente el público o rotar entre dos o tres variantes de anuncio dentro del mismo conjunto para que el sistema tenga opciones frescas que ofrecer en cada subasta.</p>
                    </details>

                    <details>
                        <summary>¿Debo pausar una campaña si el costo por lead sube un solo día?</summary>
                        <p>No. Los costos dentro de la subasta de Meta fluctúan de un día a otro según la competencia de otros anunciantes por el mismo público, el día de la semana y hasta la hora del día, así que un solo día malo casi nunca es representativo del rendimiento real de la campaña. La recomendación general es evaluar el rendimiento en ventanas de al menos 7 días o después de que la campaña acumule alrededor de 50 conversiones, que es aproximadamente el tiempo que necesita la fase de aprendizaje para estabilizarse. Pausar o editar la campaña de forma reactiva cada vez que el costo por lead sube un día suele ser contraproducente, porque cada edición significativa reinicia el aprendizaje del algoritmo y prolonga el periodo de inestabilidad en lugar de acortarlo.</p>
                    </details>

                    <details>
                        <summary>¿Los formularios instantáneos de Facebook generan leads más baratos que enviar tráfico a una landing page?</summary>
                        <p>En la mayoría de los casos, sí, porque los formularios instantáneos se abren dentro de la misma app sin necesidad de cargar una página externa, lo que reduce la fricción y elimina el tiempo de carga como posible punto de abandono. Sin embargo, esa facilidad tiene una contraparte: los leads que llegan por formulario instantáneo suelen estar, en promedio, menos calificados que los que llegan después de visitar una landing page completa, precisamente porque el esfuerzo para completarlos es mucho menor. La decisión entre uno u otro depende de qué es más valioso para tu negocio en ese momento: volumen de leads más baratos con formularios instantáneos, o menos leads pero más calificados a través de una landing page bien diseñada. Muchas cuentas maduras terminan corriendo ambos formatos en paralelo para comparar el costo por lead contra la tasa de cierre real de cada uno.</p>
                    </details>

                    <details>
                        <summary>¿Aumentar el presupuesto siempre baja el costo por lead?</summary>
                        <p>No, y de hecho puede tener el efecto contrario si el aumento es demasiado agresivo. Subir el presupuesto de golpe (por ejemplo, duplicarlo de un día a otro) se considera un cambio significativo dentro del sistema de Meta y puede reiniciar la fase de aprendizaje del conjunto de anuncios, lo que temporalmente vuelve a subir el costo por resultado mientras el algoritmo se reajusta. La recomendación generalizada en la industria es incrementar el presupuesto de forma gradual, en pasos de no más del 15% al 20% cada pocos días, para que el sistema pueda escalar sin perder la eficiencia que ya había encontrado. Un presupuesto más alto sí amplía tu alcance potencial y puede mejorar los resultados absolutos, pero solo si se introduce de forma progresiva y con una oferta y una segmentación que ya demostraron funcionar a menor escala.</p>
                    </details>
