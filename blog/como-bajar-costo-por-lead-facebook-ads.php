                <section id="la-oferta-primero">
                    <h2>1. Empieza por la oferta, no por el diseño</h2>
                    <p>
                        El factor que más determina si una campaña de clientes potenciales es rentable no es el diseño del anuncio ni la calidad de la foto: es la oferta. Una oferta que resuelve un problema real y específico de tu público genera leads baratos casi sin importar qué tan bien redactado esté el texto; una oferta débil genera leads caros incluso con el mejor copywriting del mundo. Antes de gastar tiempo puliendo el diseño de tu anuncio, pregúntate si lo que estás ofreciendo (una guía, una calculadora, una cotización, una sesión gratuita) realmente le importa a la persona que la va a recibir.
                    </p>
                    <p>
                        Para una desarrolladora inmobiliaria, una oferta débil es "conoce nuestro desarrollo"; una oferta fuerte es una guía descargable como "7 errores que te cuestan dinero al comprar tu primer departamento en Zapopan", porque resuelve una duda específica y genera curiosidad inmediata. Para una empresa de energía solar, cambiar "cotiza tus paneles solares" por "calcula en 2 minutos cuánto puedes ahorrar en tu recibo de luz" suele bajar el costo por lead de forma notable, porque convierte una decisión grande en un primer paso pequeño y de bajo compromiso.
                    </p>
                </section>

                <section id="conoce-a-tu-cliente">
                    <h2>2. Conoce a tu cliente antes de segmentar</h2>
                    <p>
                        Muchos negocios saltan directo a la segmentación de audiencia sin haber hecho antes un estudio de mercado real sobre quién es su cliente ideal y qué lo detiene de comprar. Sin esa investigación de mercado, hasta la segmentación más sofisticada del Administrador de Anuncios va a estar apuntando, con mucha precisión, al público equivocado. Dedica tiempo a entender el comportamiento de compra de tu cliente ideal antes de tocar un solo parámetro de público objetivo.
                    </p>
                </section>

                <section id="segmentacion-y-publicos">
                    <h2>3 a 5. Segmentación, públicos personalizados y públicos similares (lookalike)</h2>
                    <p>
                        Dentro del Administrador de Anuncios existen tres formas principales de construir un público, y cada una cumple un rol distinto en bajar tu costo por lead:
                    </p>
                    <ul>
                        <li><strong>Segmentación detallada.</strong> Acota tu público por datos demográficos, intereses y comportamientos. Es tu punto de partida cuando todavía no tienes suficientes datos propios.</li>
                        <li><strong>Públicos personalizados.</strong> Se construyen con tus propios datos (el Pixel de Meta, tu lista de clientes o quienes ya interactuaron con tu página) y casi siempre generan el costo por lead más bajo, porque ya tienen una relación previa con tu marca.</li>
                        <li><strong>Públicos similares (lookalike).</strong> Meta busca personas parecidas a tus mejores clientes actuales. Entre más pequeño el porcentaje de similitud que elijas (más cerca del 1%), más preciso pero más limitado será el alcance; entre más cerca del 10%, mayor alcance pero menor precisión.</li>
                    </ul>
                    <p>
                        Profundizamos en cómo construir cada uno de estos públicos, paso a paso, en nuestro artículo dedicado a <a href="/blog/publicos-personalizados-y-lookalike">públicos personalizados y lookalike</a>.
                    </p>
                </section>

                <section id="presupuesto-y-fase-de-aprendizaje">
                    <h2>6 y 7. Presupuesto diario y la fase de aprendizaje</h2>
                    <p>
                        Uno de los errores más comunes que dispara el costo por lead es interrumpir la fase de aprendizaje. Cada vez que creas un conjunto de anuncios nuevo o haces un cambio importante en uno existente, el sistema de entrega de Meta necesita entre 7 días o 50 conversiones (lo que ocurra primero) para identificar qué público, horario y contenido funcionan mejor. Pausar, editar o reiniciar la campaña antes de completar esta fase reinicia el aprendizaje desde cero, y eso casi siempre se traduce en un costo por lead más alto durante más tiempo del necesario.
                    </p>
                    <p>
                        Sobre el presupuesto, puedes elegir entre un presupuesto diario (el importe promedio que estás dispuesto a gastar por día, con la posibilidad de que Meta gaste hasta 25% más en los días con mejores oportunidades) o un presupuesto total para todo el periodo de la campaña. Un presupuesto total tiende a maximizar resultados y minimizar el costo general porque le da al sistema más flexibilidad para explorar oportunidades a lo largo de toda la campaña, mientras que un presupuesto diario fijo restringe esa exploración. Si además usas el presupuesto de la campaña Advantage+, evita pausar o reiniciar conjuntos de anuncios de forma manual, porque ese presupuesto se reserva y se asigna automáticamente solo entre los conjuntos que siguen activos.
                    </p>
                </section>

                <section id="copywriting-y-creativo">
                    <h2>8 y 9. Copywriting consistente e imagen de calidad</h2>
                    <p>
                        El copywriting de tu anuncio, tu formulario y tu página de destino debe contar la misma historia de principio a fin. Cuando el titular del anuncio promete una cosa y el formulario o la landing page hablan de algo distinto, se genera una fricción mental en la persona que reduce drásticamente la tasa de conversión, incluso si el CPC de ese anuncio es barato. Mantener el mismo mensaje central en cada etapa del embudo de ventas en Facebook es una de las formas más baratas de bajar el costo por lead, porque no requiere presupuesto adicional, solo consistencia.
                    </p>
                    <p>
                        La imagen o el video que acompaña tu anuncio también pesa muchísimo: buena parte de la capacidad de un anuncio para captar atención en el feed depende del elemento visual, más que del texto. Contenido que muestra personas reales en contextos reconocibles tiende a generar más interacción que fotografías genéricas de stock, y eso se traduce directamente en un CTR más alto y, por lo tanto, en un costo por resultado más bajo.
                    </p>
                </section>

                <section id="pixel-y-optimizacion">
                    <h2>10 y 11. Pixel, API de Conversiones y ubicaciones Advantage+</h2>
                    <p>
