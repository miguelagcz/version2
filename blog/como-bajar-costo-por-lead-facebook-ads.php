                <section id="que-es-el-costo-por-lead">
                    <h2>Qué es el costo por lead y cómo se calcula</h2>
                    <p>
                        El costo por lead (también llamado costo por resultado cuando el objetivo de tu campaña es clientes potenciales) es el importe total que gastaste dividido entre el número de leads que generaste. Si gastaste 3,000 pesos en una semana y obtuviste 30 formularios llenados, tu costo por lead fue de 100 pesos. Esta métrica aparece directamente como columna dentro del Administrador de Anuncios y es, junto con el ROAS, uno de los indicadores que más rápido te dice si una campaña está funcionando o si necesita ajustes.
                    </p>
                    <p>
                        Es importante no confundir el costo por lead con el CPC o el CPM. Puedes tener un CPC barato y aun así un costo por lead alto, si el tráfico que estás atrayendo hace clic pero no completa el formulario. Por eso bajar el costo por lead casi nunca es un solo cambio: es la suma de mejorar la calidad del tráfico (con mejor segmentación y estudio de mercado), mejorar la oferta y el copywriting, y darle al algoritmo el tiempo y los datos que necesita para optimizar.
                    </p>
                </section>

                <section id="objetivo-de-clientes-potenciales">
                    <h2>El objetivo de clientes potenciales en el Administrador de Anuncios</h2>
                    <p>
                        Antes de tocar cualquier otra variable, confirma que tu campaña esté configurada con el objetivo correcto. Dentro del Administrador de Anuncios, el objetivo de clientes potenciales está diseñado específicamente para recopilar información de personas interesadas en tu producto o servicio, ya sea a través de formularios instantáneos dentro de la misma plataforma, mensajes directos, llamadas o registros en tu sitio web. Elegir el objetivo equivocado (por ejemplo, tráfico en lugar de clientes potenciales) hace que el sistema de entrega optimice para una acción distinta a la que realmente te interesa, y eso por sí solo puede inflar tu costo por lead sin que el resto de tu campaña tenga nada de malo.
                    </p>
                    <p>
                        También existen dos formas de comprar anuncios dentro de Meta: subasta y reserva. La inmensa mayoría de las campañas de generación de leads en Facebook usan el modelo de subasta, donde compites por impresiones o acciones con otros anunciantes, y donde la calidad y relevancia de tu anuncio pesa tanto como tu presupuesto. El modelo de reserva, con precio fijo y compromiso de varios meses, casi nunca aplica para negocios que están optimizando su costo por lead activamente.
                    </p>
