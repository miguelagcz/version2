                <section id="que-es-link-building">
                    <h2>Qué es el link building</h2>
                    <p>
                        El link building es el trabajo de conseguir que otros sitios web enlacen al tuyo. A esos enlaces que llegan desde fuera se les llama <strong>backlinks</strong> o enlaces entrantes, y son la parte del posicionamiento que no depende de lo que haces dentro de tu página, sino de lo que otros dicen de ti. Por eso también se le conoce como <strong>SEO off page</strong>.
                    </p>
                    <p>
                        Piénsalo como cartas de recomendación. Si buscas un notario y tres conocidos te recomiendan al mismo, le crees. Si la recomendación viene de alguien que reparte volantes en el semáforo, no tanto. Google lee los enlaces de forma parecida: cada uno es un sitio diciendo "esta página vale la pena", y pesa según quién lo dice.
                    </p>
                    <p>
                        No lo confundas con los enlaces internos, los que tú pones entre tus propias páginas. Esos también cuentan y los controlas al cien por ciento; los repasamos en la <a href="/blog/seo-on-page-checklist">checklist de SEO on-page</a>. Y no es lo primero que hay que arreglar: si Google no puede rastrear o cargar tu sitio, ningún enlace lo va a rescatar. Eso se revisa antes, en <a href="/blog/seo-tecnico-velocidad-indexacion-errores">SEO técnico: velocidad, indexación y errores</a>.
                    </p>
                </section>

                <section id="por-que-importan">
                    <h2>Por qué Google se fija en quién te enlaza</h2>
                    <p>
                        Por dos razones muy concretas. La primera es que así encuentra tus páginas. Google descubre la mayoría de las páginas nuevas siguiendo enlaces desde sitios que ya conoce, así que una página a la que nadie enlaza es, en la práctica, una página difícil de encontrar.
                    </p>
                    <p>
                        La segunda es la confianza. PageRank, uno de los algoritmos más antiguos de Google, usa los enlaces para estimar qué tan importante es una página. Google mismo aclara que es una señal entre muchas, y eso es lo que más se olvida: los enlaces ayudan, pero no compensan un contenido que no responde lo que la gente busca.
                    </p>
                    <p>
                        Funciona como el comité que revisa un crédito. Tus enlaces son tus referencias. Unas buenas referencias no te aprueban si tus números están mal, pero entre dos solicitudes con números parecidos, la que trae mejores referencias se lleva la tasa.
                    </p>
                    <p>
                        Para un negocio de alto ticket esto tiene una consecuencia práctica. En búsquedas competidas, como "despacho fiscal en Santa Fe" o "departamentos en preventa en Mérida", suele haber dos o tres sitios con contenido igual de bueno. Muchas veces lo que los separa es quién habla de ellos.
                    </p>
                </section>

                <section id="que-hace-valioso-un-enlace">
                    <h2>Qué hace que un enlace valga más que otro</h2>
                    <p>
                        No todos los enlaces pesan lo mismo, y aquí está la diferencia entre un trabajo serio y uno que solo infla un número. Estos son los criterios que importan, en orden:
                    </p>
                    <ul>
                        <li><strong>Relevancia.</strong> Un enlace desde el sitio de la cámara de vivienda le dice más a Google sobre una desarrolladora que diez enlaces desde blogs de recetas. Google entiende de qué trata el sitio que te enlaza.</li>
                        <li><strong>Que sea editorial.</strong> El enlace vale cuando alguien decidió ponerlo porque tu contenido o tu empresa lo merecían, no porque lo pagaste o lo dejaste tú mismo en un foro.</li>
                        <li><strong>La reputación de quien enlaza.</strong> Un medio, una universidad o una asociación con años de historia transmiten más confianza que un sitio creado el mes pasado.</li>
                        <li><strong>El contexto y el texto ancla.</strong> Un enlace dentro de un párrafo que habla de tu tema, con un texto que describe a dónde lleva, le dice mucho más a Google que uno perdido en un pie de página.</li>
                        <li><strong>Que mande visitas reales.</strong> El mejor filtro de todos: si ese enlace te traería prospectos aunque Google no existiera, casi seguro es un buen enlace.</li>
                    </ul>
                    <p>
                        Un dato que te va a ahorrar dinero: la famosa <strong>autoridad de dominio</strong> que muestran las herramientas de SEO la inventaron esas mismas herramientas. Sirve como referencia, pero Google no la usa. Un proveedor que te vende enlaces por su puntaje de autoridad te está vendiendo la calificación de otra empresa.
                    </p>

                    <h3>Dofollow, nofollow y los otros atributos</h3>
                    <p>
                        Quien enlaza puede marcar el enlace con un atributo que le dice a Google cómo tratarlo. <strong>nofollow</strong> indica que el sitio no quiere respaldar esa página, <strong>sponsored</strong> se usa en enlaces pagados o de publicidad, y <strong>ugc</strong> en los que dejan los usuarios en comentarios y foros. Un enlace sin ninguno de estos atributos es lo que en la industria se llama "dofollow".
                    </p>
                    <p>
                        Google trata estos atributos como sugerencias, no como órdenes. Un enlace nofollow normalmente no transmite reputación, pero te puede mandar visitas y ayudar a que Google encuentre tu página. No los desprecies: un nofollow desde un periódico que te manda prospectos vale más que un dofollow desde un sitio que nadie visita.
                    </p>
                </section>

                <section id="spam-de-enlaces">
                    <h2>Lo que Google considera spam de enlaces</h2>
                    <p>
                        Google publica una lista de prácticas que considera manipulación de enlaces. Vale la pena conocerla porque varias se venden en México como servicio normal:
                    </p>
                    <ul>
                        <li><strong>Comprar o vender enlaces para posicionar</strong>, ya sea con dinero, con producto o con servicios a cambio.</li>
                        <li><strong>Intercambios excesivos</strong>, el clásico "tú me enlazas y yo te enlazo" entre sitios que no tienen nada que ver.</li>
                        <li><strong>Programas automáticos</strong> que generan enlaces hacia tu sitio en masa.</li>
                        <li><strong>Artículos invitados, comunicados de prensa o publirreportajes</strong> con enlaces optimizados con palabras clave y sin marcar como patrocinados.</li>
                        <li><strong>Directorios y sitios de marcadores de baja calidad</strong>, de esos que aceptan a cualquiera.</li>
                        <li><strong>Comentarios en foros y blogs</strong> con enlaces optimizados en el texto o en la firma.</li>
                        <li><strong>Enlaces repetidos en pies de página o plantillas</strong> de muchos sitios distintos.</li>
                    </ul>
                    <p>
                        Si un proveedor te ofrece "paquetes de backlinks", "enlaces en sitios de alta autoridad" o "redes de blogs", te está ofreciendo algo de esta lista. En el mejor de los casos Google ignora esos enlaces y tiraste el dinero. En el peor, tu sitio recibe una acción manual y pierde posiciones que te costaron meses ganar.
                    </p>
                    <p>
                        Ojo: anunciarte en un medio no está prohibido. Lo que Google pide es que esos enlaces vayan marcados como sponsored o nofollow, para que quede claro que son publicidad y no una recomendación.
                    </p>
                </section>

                <section id="como-conseguir-enlaces">
                    <h2>Cómo conseguir enlaces de calidad</h2>
                    <p>
                        La buena noticia para un negocio de alto ticket: no necesitas cientos de enlaces, necesitas pocos y buenos. Y muchos ya los tienes a medio camino, porque salen de relaciones que existen fuera de internet. Van de lo más fácil a lo más laborioso.
                    </p>

                    <h3>1. Las relaciones que ya tienes</h3>
                    <p>
                        Proveedores, socios, clientes, marcas que distribuyes. Muchos tienen en su sitio una sección de distribuidores, instaladores certificados, aliados o casos de éxito. Si trabajas con ellos y no apareces ahí con un enlace a tu sitio, es el enlace más fácil que vas a conseguir: basta con pedirlo.
                    </p>
                    <p>
                        Haz la lista con calma. Una empresa solar que instala paneles de una marca reconocida, una clínica que trabaja con un laboratorio, un despacho aliado de una firma internacional: casi todos tienen dos o tres de estos enlaces esperando.
                    </p>

                    <h3>2. Cámaras, asociaciones y colegios</h3>
                    <p>
                        Las cámaras empresariales y los colegios profesionales suelen tener directorio de socios, y son justo el tipo de sitio que Google relaciona con tu industria: CANADEVI para vivienda, ASOLMEX para energía solar, el IMCP para contadores, CANACINTRA para la industria. Si ya pagas la membresía, confirma que tu ficha incluya el enlace a tu sitio.
                    </p>
                    <p>
                        Además del directorio, dar una plática en sus eventos o escribir para su boletín te consigue menciones en páginas que tus prospectos sí leen.
                    </p>

                    <h3>3. Contenido que otros quieran citar</h3>
                    <p>
                        Los sitios enlazan a lo que les sirve para explicar algo. Un estudio con datos propios ("cuánto cuesta el metro cuadrado en preventa en Mérida este año"), una calculadora o una guía que resuelve una duda mejor que nadie se vuelven fuentes. Es el tipo de enlace que llega solo, sin pedirlo, durante años.
                    </p>
                    <p>
                        Tú tienes datos que nadie más tiene: tus cotizaciones, tus tiempos de entrega, las preguntas que te hacen en cada junta. Para elegir cuál convertir en página, cruza esas preguntas con una <a href="/blog/como-hacer-investigacion-de-palabras-clave">investigación de palabras clave</a> y quédate con la que más gente busca.
                    </p>

                    <h3>4. Prensa y medios del sector</h3>
                    <p>
                        Los periodistas necesitan fuentes. Si diriges una desarrolladora, una clínica o una empresa solar, tienes opiniones con datos sobre tu mercado. Ofrecerte como fuente a medios locales y revistas especializadas te da menciones con enlace en sitios de mucha reputación y, de paso, más gente buscando tu marca.
                    </p>
                    <p>
                        Lo que no funciona es el comunicado de prensa repartido en cien portales: está en la lista de Google y la mayoría de esos enlaces no cuentan.
                    </p>

                    <h3>5. Menciones que no tienen enlace</h3>
                    <p>
                        Busca en Google el nombre de tu empresa entre comillas y excluye tu propio sitio, por ejemplo <strong>"Nombre de tu empresa" -site:tusitio.com</strong>. Vas a encontrar notas, listas o publicaciones de aliados que te mencionan sin enlazarte. Un correo amable pidiendo agregar el enlace funciona mucho mejor que pedirle un enlace a un desconocido, porque ya hablaron bien de ti.
                    </p>

                    <h3>6. Directorios que sí valen</h3>
                    <p>
                        No todos los directorios son spam. Tu <a href="/blog/como-optimizar-google-business-profile">ficha de Google Business Profile</a>, los directorios de tu cámara y los especializados de tu industria, donde tus prospectos sí buscan proveedores, aportan. Lo explicamos aplicado a un caso en <a href="/blog/seo-local-para-inmobiliarias">SEO local para inmobiliarias</a>. Lo que sobra son los directorios genéricos que aceptan a cualquiera a cambio de un enlace recíproco.
                    </p>
                    <p>
                        Para saber qué enlaces tiene tu competencia y tú no, haz un <a href="/blog/como-hacer-analisis-seo-de-la-competencia">análisis SEO de tu competencia</a>: te da la lista concreta de por dónde empezar.
                    </p>
                </section>

                <section id="errores-comunes">
                    <h2>Errores comunes</h2>
                    <p>
                        Ordenados por lo que más cuestan, no por lo que más se ven:
                    </p>
                    <ol>
                        <li><strong>Comprar paquetes de enlaces.</strong> Es el error más caro porque se paga dos veces: lo que cuesta el paquete y lo que tardas en recuperarte si Google te sanciona.</li>
                        <li><strong>Empezar por los enlaces cuando el sitio no está listo.</strong> Mandar reputación a una página lenta, mal indexada o que no convierte es llenar una cubeta con agujeros. Primero corrige los <a href="/blog/errores-de-seo-que-matan-tu-trafico">errores de SEO que matan tu tráfico</a>.</li>
                        <li><strong>Medir el trabajo por cantidad.</strong> "Conseguimos 80 enlaces este mes" no dice nada si 78 vienen de sitios que nadie lee. Pide la lista y revísala tú.</li>
                        <li><strong>Repetir siempre la misma palabra clave en el texto ancla.</strong> Un perfil natural mezcla tu marca, tu dirección web y frases variadas. Cien enlaces que dicen exactamente "inmobiliaria en Querétaro" se ven fabricados, porque lo son.</li>
                        <li><strong>Mandar todos los enlaces a la página principal.</strong> Tus páginas de servicio y tus mejores artículos también necesitan reputación. Cuando un enlace llega a tu home, repártela con enlaces internos hacia lo que vendes.</li>
                    </ol>
                </section>

                <section id="por-industria">
                    <h2>Cómo se ve esto en tu industria</h2>

                    <h3>Desarrolladoras inmobiliarias</h3>
                    <p>
                        El activo más enlazable es el proyecto mismo: los medios y portales inmobiliarios publican lanzamientos, los brokers con los que trabajas pueden listarte y la cámara de vivienda tiene directorio. Cuida un detalle que vemos seguido: cuando un proyecto se vende, sus enlaces deben apuntar a una página que siga viva, no a una que vas a borrar. Lo explicamos en <a href="/blog/seo-para-desarrollos-inmobiliarios">SEO para desarrollos inmobiliarios</a>.
                    </p>

                    <h3>Clínicas y consultorios</h3>
                    <p>
                        Los mejores enlaces vienen de los hospitales donde atienden tus médicos, de los colegios de especialidad, de las universidades donde dan clase y de los medios de salud que buscan especialistas para entrevistar. En temas de salud Google es especialmente exigente con la reputación, así que un enlace de una institución médica pesa mucho más que cualquier directorio genérico de doctores.
                    </p>

                    <h3>Despachos jurídicos y contables</h3>
                    <p>
                        Colegios y barras, universidades, cámaras donde dan conferencias y, sobre todo, columnas en medios de negocios. Un contador que explica una reforma fiscal en un medio con buen tráfico consigue en una semana lo que un directorio de abogados no le da en un año.
                    </p>

                    <h3>Industrial B2B</h3>
                    <p>
                        Las fichas de proveedor en los sitios de los fabricantes que distribuyes, los parques industriales donde operan tus clientes, las asociaciones del sector y los directorios de expositores de las ferias comerciales. Son pocos enlaces, pero muy relevantes. En búsquedas tan específicas como las industriales, pocos enlaces buenos alcanzan para destacar.
                    </p>
                </section>

                <section id="como-medirlo">
                    <h2>Cómo medirlo y qué esperar</h2>
                    <p>
                        La fuente más confiable es gratuita. En Search Console, el informe de <strong>Enlaces</strong> te muestra qué sitios te enlazan, a qué páginas y con qué texto. No es una lista completa, pero son datos de Google sobre tu sitio, no estimaciones de una herramienta externa.
                    </p>
                    <p>
                        Lo que importa, en orden: cuántos <strong>sitios distintos</strong> te enlazan (no cuántos enlaces, porque un sitio puede enlazarte mil veces desde su pie de página), qué tan relacionados están con tu industria, y si las páginas que reciben enlaces empiezan a ganar impresiones y posiciones en el informe de rendimiento.
                    </p>
                    <p>
                        Sobre los tiempos, sin humo: es la parte más lenta del SEO. Un enlace nuevo puede tardar semanas en ser descubierto y meses en reflejarse en posiciones; el panorama completo está en <a href="/blog/cuanto-tarda-el-seo-en-dar-resultados">cuánto tarda el SEO en dar resultados</a>. Lo que sí puedes revisar cada mes es el avance: para un negocio local, una meta razonable es sumar uno o dos sitios relevantes nuevos al mes. Si después de seis meses tu informe de enlaces sigue igual, la estrategia no está funcionando.
                    </p>
                </section>

