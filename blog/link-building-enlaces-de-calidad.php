                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Es malo comprar backlinks?</summary>
                        <p>Sí, si lo que compras es un enlace para posicionar. Google lo clasifica como spam de enlaces y lo combate de dos formas: con sistemas automáticos que detectan esos enlaces y los dejan de contar, y con acciones manuales, en las que un revisor de Google sanciona al sitio. En el primer caso pierdes el dinero. En el segundo, además, pierdes posiciones que te costaron meses.</p>
                        <p>Lo que sí puedes hacer es pagar publicidad en un medio o patrocinar un evento, siempre que el enlace vaya marcado como sponsored o nofollow. Ese enlace no te va a subir en Google, pero sí puede traerte prospectos, que al final es lo que importa. Para un negocio de alto ticket, una nota patrocinada en el medio que lee tu cliente ideal vale por las visitas que manda, no por el enlace.</p>
                    </details>

                    <details>
                        <summary>¿Cuántos backlinks necesito para posicionar en Google?</summary>
                        <p>No hay un número, y conviene desconfiar de quien te dé uno. Depende de qué tan competida está la búsqueda y de qué enlaces tienen los sitios que hoy aparecen arriba. Para "abogado laboral en Monterrey" pueden bastar unos cuantos enlaces locales y relevantes. Para "crédito hipotecario" compites contra bancos que acumulan miles.</p>
                        <p>La forma práctica de saberlo es mirar a tus competidores directos: cuántos sitios distintos los enlazan y de qué tipo son. Esa es tu referencia, no un promedio sacado de internet. Y en negocios de nicho, con poco volumen de búsqueda, la competencia suele ser tan floja que un buen contenido con pocos enlaces de calidad ya alcanza para entrar a la primera página.</p>
                    </details>

                    <details>
                        <summary>¿Sirven los directorios de empresas para el SEO?</summary>
                        <p>Algunos sí y la mayoría no. Sirven los que tus clientes de verdad usan para buscar proveedores, los de tu cámara o asociación y los especializados de tu industria. No sirven, y pueden perjudicarte, los directorios genéricos que aceptan cualquier sitio, cobran por publicar un enlace o te piden un enlace de regreso.</p>
                        <p>Para un negocio local, los directorios buenos ayudan además en otra cosa: que tu nombre, dirección y teléfono aparezcan igual en todos lados, algo que refuerza tu presencia en búsquedas locales y en Google Maps. Antes de darte de alta en uno, revisa que esos datos coincidan exactamente con tu ficha de Google Business Profile.</p>
                    </details>

                    <details>
                        <summary>¿Qué es la autoridad de dominio y la usa Google?</summary>
                        <p>Es una calificación que crearon herramientas de SEO como Moz, Ahrefs o Semrush para estimar qué tan fuerte es el perfil de enlaces de un sitio, cada una con su propio nombre y su propia fórmula. Google no la usa. Tiene sus propias señales y no publica ninguna calificación equivalente.</p>
                        <p>Eso no la vuelve inútil. Sirve para comparar tu sitio contra tu competencia con la misma regla, o para descartar rápido sitios sin reputación. El problema empieza cuando se convierte en la meta. Un proveedor que te reporta "subimos tu autoridad de 12 a 20" sin mostrarte más visitas ni más prospectos te está reportando el número equivocado.</p>
                    </details>

                    <details>
                        <summary>¿Cuánto tarda en notarse el link building?</summary>
                        <p>Meses, no semanas. Google tiene que descubrir el enlace, rastrear la página donde está y recalcular cómo cambia la reputación de tu sitio, y nada de eso pasa de un día para otro. Lo normal es empezar a ver efecto en posiciones después de varios meses de trabajo constante, y más tarde todavía en búsquedas muy competidas.</p>
                        <p>Por eso conviene medir el avance con indicadores intermedios: sitios nuevos en el informe de enlaces de Search Console, más impresiones en las páginas que recibieron enlaces y visitas que llegan directo desde esos sitios. Si alguien te promete resultados en 30 días a punta de enlaces, ya sabes de qué lista salieron.</p>
                    </details>
                </section>

