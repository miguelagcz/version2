                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Qué es el SEO on-page y qué es el SEO off-page?</summary>
                        <p>
                            El SEO on-page es todo lo que optimizas dentro de tu propia página: la etiqueta title, la
                            meta descripción, la URL, los encabezados, el texto, las imágenes con su texto alternativo
                            y los enlaces internos. Es la parte del posicionamiento que vive en tu servidor y que puedes
                            modificar sin depender de nadie. El SEO off-page son las señales que se generan fuera de tu
                            sitio, sobre todo los enlaces que otras páginas dirigen hacia la tuya, las menciones de tu
                            marca y las reseñas. Google descubre la mayoría de las páginas nuevas siguiendo enlaces de
                            sitios que ya rastreó, así que esas señales pesan, pero dependen de terceros y tardan más en
                            construirse.
                        </p>
                        <p>
                            En un proyecto nuevo el orden lógico es empezar por el on-page, porque es lo barato, lo
                            rápido y lo que está bajo tu control. No tiene sentido perseguir enlaces hacia una página
                            que ni siquiera tiene un title decente. Cuando la base on-page está limpia, el trabajo
                            off-page rinde mucho más, porque cada enlace que consigas llega a una página que el buscador
                            ya entiende bien.
                        </p>
                    </details>

                    <details>
                        <summary>¿Cuántas veces debo repetir la palabra clave en el artículo?</summary>
                        <p>
                            No hay un número correcto y perseguir un porcentaje de densidad es una pérdida de tiempo.
                            Google ha sido claro en que repetir las mismas palabras una y otra vez resulta cansado para
                            el lector, y que el exceso de palabras clave va en contra de sus políticas de spam. Es decir,
                            la práctica no solo no ayuda: puede perjudicarte.
                        </p>
                        <p>
                            Lo razonable es que la palabra clave principal aparezca en el title, en el H1, en la URL y de
                            forma natural dentro de los primeros párrafos, porque ahí es donde se define de qué trata la
                            página. De ahí en adelante escribe como hablarías. Usa sinónimos, variantes y formas
                            relacionadas del término. Los sistemas de coincidencia de idioma de Google son capaces de
                            entender que tu página responde a muchas consultas distintas aunque no uses las palabras
                            exactas, así que la variedad te ayuda más que la repetición.
                        </p>
                    </details>

                    <details>
                        <summary>¿La meta descripción sirve para posicionar?</summary>
                        <p>
                            Para posicionar directamente, no. Google no la usa como factor de ranking. Lo que hace es
                            tomarla, cuando le parece un buen resumen, para armar el fragmento que aparece debajo del
                            título en los resultados de búsqueda. Muchas veces ni siquiera la usa y prefiere extraer un
                            trozo del contenido real de la página que le parezca más pertinente para esa consulta
                            específica.
                        </p>
                        <p>
                            Aun así vale la pena escribirla bien, y la razón es el clic. Dos resultados en la misma
                            posición pueden tener rendimientos muy distintos según lo atractivo que sea su fragmento.
                            Una meta descripción breve, única para esa página, que mencione el beneficio concreto y
                            hable el idioma del lector, es publicidad gratuita en la página de resultados. La forma más
                            rápida de encontrar dónde aplicarla es revisar en Search Console qué páginas tienen muchas
                            impresiones y pocos clics.
                        </p>
                    </details>

                    <details>
                        <summary>¿Cuántas palabras debe tener un artículo para posicionar?</summary>
                        <p>
                            Google ha dicho que la longitud por sí sola no es un factor de posicionamiento y que no
                            existe un objetivo mágico de cantidad de palabras, ni mínimo ni máximo. Lo que ocurre en la
                            práctica es que los temas competitivos rara vez se cubren bien en pocos párrafos, y por eso
                            los artículos que ganan suelen ser largos. La extensión es consecuencia de tratar el tema
                            completo, no la causa del posicionamiento.
                        </p>
                        <p>
                            El criterio útil es otro: mira los diez primeros resultados para tu palabra clave y fíjate
                            qué subtemas cubren todos. Esos son obligatorios. Si además puedes aportar algo que ninguno
                            tiene, un ejemplo real, un dato propio, una tabla comparativa, ahí está tu ventaja. Escribe
                            hasta que la pregunta quede respondida y detente. Alargar con relleno solo hace que el
                            lector se vaya antes.
                        </p>
                    </details>

                    <details>
                        <summary>¿Puedo hacer SEO on-page sin saber programar?</summary>
                        <p>
                            La mayor parte sí. Si usas un gestor de contenidos como WordPress, Shopify o similar, el
                            propio sistema te deja editar el title, la meta descripción, el slug de la URL, los
                            encabezados y el texto alternativo de las imágenes desde el panel, sin tocar una línea de
                            código. De hecho, la mayoría de los CMS convierten automáticamente el título que escribes en
                            la etiqueta title del HTML.
                        </p>
                        <p>
                            Donde sí necesitas ayuda técnica es en la otra mitad: velocidad de carga, corrección de
                            errores de indexación, implementación de datos estructurados, configuración de redirecciones
                            y etiquetas canónicas. Nuestra recomendación práctica es que la persona que escribe se haga
                            responsable de los puntos 1 al 9 de la checklist, y que los tres últimos entren en la lista
                            de pendientes del desarrollador. Separar así el trabajo evita que todo se detenga esperando
                            a alguien.
                        </p>
                    </details>
                </section>

