                <section id="que-es">
                    <h2>Qué es el SEO on-page y en qué se diferencia del off-page</h2>
                    <p>
                        El SEO on-page se refiere a todas las optimizaciones que ocurren dentro de una página:
                        el título, el texto, los encabezados, las imágenes, la URL, los enlaces internos y la
                        forma en que todo eso está organizado. Es la mitad del trabajo que vive en tu servidor
                        y que puedes cambiar cuando quieras.
                    </p>
                    <p>
                        El SEO off-page es lo contrario: señales que se generan fuera de tu sitio. Principalmente
                        enlaces de otras páginas hacia la tuya, menciones de marca y reseñas. Google encuentra la
                        mayoría de las páginas nuevas siguiendo enlaces, así que esas señales importan, pero no
                        las controlas directamente. Ese tema lo tratamos aparte en
                        <a href="/blog/link-building-enlaces-de-calidad">link building</a>.
                    </p>
                    <p>
                        Y luego está el SEO técnico, que a veces se cuenta como una tercera categoría y a veces se
                        mete dentro del on-page. Ahí entran la velocidad de carga, la indexación, los errores de
                        rastreo y la estructura del sitio. La frontera es difusa y no vale la pena discutirla: lo
                        práctico es saber que hay cosas de código y servidor que un redactor no puede tocar, y para
                        eso está la guía de
                        <a href="/blog/seo-tecnico-velocidad-indexacion-errores">SEO técnico</a>.
                    </p>
                    <p>
                        Una forma simple de recordar la diferencia entre on-page y off-page: el on-page le dice a
                        Google de qué trata tu página, el off-page le dice qué tan confiable es. Necesitas los dos,
                        pero solo uno arranca hoy.
                    </p>
                </section>

                <section id="palabra-clave">
                    <h2>Antes de optimizar: una palabra clave principal por página</h2>
                    <p>
                        Este es el error que vemos con más frecuencia y el que más caro sale. Un negocio decide que
                        quiere posicionar "casas en Zapopan" y termina con cuatro páginas distintas peleando por el
                        mismo término. Google elige una, normalmente la que menos te conviene, y las otras tres se
                        quedan sin tráfico. A eso se le llama canibalización.
                    </p>
                    <p>
                        La regla es una palabra clave principal por página, más dos o cuatro variantes o sinónimos
                        que aparezcan de forma natural. Si dos páginas responden a la misma intención de búsqueda,
                        no tienes dos páginas: tienes una página y un duplicado que hay que fusionar o redirigir.
                    </p>
                    <p>
                        Elegir esa palabra clave no es adivinar. Es un proceso con herramientas y criterios que
                        cubrimos completo en
                        <a href="/blog/como-hacer-investigacion-de-palabras-clave">cómo hacer investigación de
                        palabras clave</a>. Lo mínimo antes de seguir con esta checklist: que el término tenga
                        volumen de búsqueda mayor a cero, que la intención coincida con lo que tu página ofrece,
                        y que hayas visto los diez primeros resultados de Google para entender qué formato está
                        premiando el buscador.
                    </p>
                </section>

                <section id="checklist">
                    <h2>La checklist de SEO on-page: 12 puntos</h2>
                    <p>
                        Revísalos en este orden. Los primeros seis son los que mueven la aguja en la mayoría de los
                        sitios; los últimos seis son los que separan una página decente de una página bien hecha.
                    </p>

                    <h3>1. Etiqueta title descriptiva y única</h3>
                    <p>
                        Cada página necesita su propia etiqueta <em>title</em>, y debe describir con precisión lo que
                        hay dentro. Google usa varias fuentes para armar el enlace de título que ves en los resultados,
                        incluida esa etiqueta, el encabezado principal visible y hasta el texto de los enlaces que
                        apuntan a la página. Si tu título es vago, genérico o está repetido en medio sitio, el buscador
                        puede reemplazarlo por otro texto que le parezca más útil.
                    </p>
                    <p>
                        Google no publica un límite exacto de caracteres, pero sí trunca el título en pantalla según el
                        ancho del dispositivo. En la práctica, mantenerlo entre 55 y 70 caracteres evita sorpresas.
                        Incluye la palabra clave principal, de preferencia al inicio, y agrega el nombre de tu marca al
                        final separado por una pleca o un guion. Evita repetir la misma palabra varias veces: eso se
                        interpreta como exceso de palabras clave y va en contra de las políticas de spam.
                    </p>

                    <h3>2. Meta descripción escrita para el clic</h3>
                    <p>
                        La meta descripción no es un factor de posicionamiento. Es un factor de clic, que en la práctica
                        es igual de valioso. Google arma el fragmento que aparece debajo del título tomando texto real
                        de la página, y a veces usa la meta descripción cuando le parece un buen resumen. Escribirla
                        bien te da la oportunidad de controlar ese mensaje.
                    </p>
                    <p>
                        Una buena meta descripción es breve, única para esa página y menciona los puntos más relevantes
                        de lo que el lector va a encontrar. Entre 70 y 160 caracteres funciona bien. Piénsala como el
                        anuncio gratuito de tu página en los resultados de búsqueda, porque eso es exactamente lo que es.
                    </p>

                    <h3>3. URL corta, descriptiva y permanente</h3>
                    <p>
                        Partes de la URL aparecen en los resultados como ruta de exploración, así que ayuda que contenga
                        palabras que el usuario reconozca. Una dirección con identificadores aleatorios no le dice nada
                        a nadie.
                    </p>
                    <ul>
                        <li><strong>Usa el slug para la palabra clave principal</strong>, separada por guiones medios.</li>
                        <li><strong>Solo minúsculas, números y guiones.</strong> Sin acentos, sin eñes, sin caracteres especiales.</li>
                        <li><strong>Sin fechas ni años.</strong> Si pones 2026 en la URL, en enero el artículo se ve viejo aunque lo actualices.</li>
                        <li><strong>Agrupa por carpetas temáticas.</strong> Ayuda a Google a entender con qué frecuencia cambia cada sección del sitio.</li>
                    </ul>
                    <p>
                        Y una advertencia: las palabras clave que solo viven en el dominio o en la ruta tienen un efecto
                        mínimo en el posicionamiento. La URL descriptiva se hace por claridad y por la ruta de exploración,
                        no porque meter el término en la dirección te vaya a subir posiciones.
                    </p>

                    <h3>4. Un H1 claro y una jerarquía de encabezados que se entienda</h3>
                    <p>
                        Un solo H1 por página, con la palabra clave principal integrada de forma natural. Debajo, los H2
                        dividen el artículo en secciones grandes y los H3 desglosan cada una. Cada encabezado responde a
                        una sola idea.
                    </p>
                    <p>
                        Aquí conviene aclarar algo que se repite mucho y no es exacto. Google ha dicho que el número y el
                        orden de los encabezados no es determinante para la búsqueda; los lectores de pantalla sí agradecen
                        el orden semántico, y esa ya es razón suficiente para hacerlo bien. Lo que sí importa mucho es que
                        quede claro cuál es el título principal. Si tienes tres encabezados del mismo tamaño y peso visual
                        compitiendo arriba, el buscador puede confundirse y tomar el equivocado para el enlace de título.
                    </p>

                    <h3>5. Contenido original, útil y escrito para personas</h3>
                    <p>
                        Este punto pesa más que todos los demás juntos. Contenido original quiere decir escrito por ti,
                        no reescrito de otros. Contenido útil quiere decir que responde de verdad la pregunta con la que
                        el lector llegó. Y contenido actualizado quiere decir que revisas lo publicado y lo corriges o lo
                        retiras cuando deja de ser cierto.
                    </p>
                    <p>
                        Sobre la longitud: no existe un mínimo mágico de palabras. Google lo ha dicho de forma explícita.
                        Lo que sí ocurre es que un tema competitivo rara vez se agota en 400 palabras, así que la extensión
                        termina siendo consecuencia de tratar el tema completo, no un objetivo en sí mismo. Escribe hasta
                        responder la pregunta y detente ahí.
                    </p>
                    <p>
                        Formato que ayuda a que se lea: párrafos de tres o cuatro líneas, negritas en los conceptos clave,
                        listas para la información densa y un índice con anclas en artículos largos. Ese índice, además de
                        mejorar la lectura en móvil, puede generar enlaces de sitio en los resultados de Google.
                    </p>

                    <h3>6. Anticiparte a las palabras que usa tu lector</h3>
                    <p>
                        Alguien que conoce el tema busca distinto a alguien que apenas empieza. Un comprador primerizo
                        escribe "cuánto cuesta una casa en Guadalajara"; un inversionista escribe "plusvalía Zapopan
                        2026". Son la misma industria y son dos páginas diferentes.
                    </p>
                    <p>
                        No necesitas adivinar todas las variantes. Los sistemas de coincidencia de idioma de Google son
                        lo bastante buenos para relacionar tu página con consultas que ni siquiera usaste textualmente.
                        Lo que sí necesitas es escribir con naturalidad y variar el vocabulario en lugar de repetir la
                        misma frase exacta veinte veces.
                    </p>

                    <h3>7. Imágenes optimizadas con texto alternativo real</h3>
                    <p>
                        Mucha gente busca de forma visual, y una imagen puede ser el primer contacto con tu sitio. Tres
                        cosas por imagen:
                    </p>
                    <ul>
                        <li><strong>Nombre de archivo descriptivo</strong> antes de subirla, con guiones medios en vez de espacios.</li>
                        <li><strong>Texto alternativo que describa la imagen</strong> y su relación con el contenido. Sirve para accesibilidad y para que el buscador entienda qué muestra la foto. No es un espacio para amontonar palabras clave.</li>
                        <li><strong>Peso comprimido.</strong> Una imagen de cuatro megas mata la velocidad de carga en móvil y con ella la experiencia de página.</li>
                    </ul>
                    <p>
                        Un detalle que casi nadie aplica: coloca cada imagen cerca del texto que habla de ella. El
                        contenido que rodea a la foto le da contexto al buscador sobre qué significa esa imagen dentro
                        de la página.
                    </p>

                    <h3>8. Enlaces internos con texto de ancla honesto</h3>
                    <p>
                        Los enlaces internos reparten autoridad entre tus páginas y mantienen al lector dentro del sitio.
                        Cada vez que menciones un concepto que ya tiene su propio artículo, enlázalo ahí en lugar de
                        volver a explicarlo. Así evitas canibalización y construyes autoridad temática real.
                    </p>
                    <p>
                        El texto de enlace, o texto ancla, es la parte visible del vínculo, y le dice tanto al usuario
                        como al buscador qué va a encontrar del otro lado. "Haz clic aquí" no comunica nada. "Cómo hacer
                        investigación de palabras clave" comunica todo. Una densidad razonable es un enlace interno cada
                        150 a 200 palabras, para que no se sienta forzado.
                    </p>

                    <h3>9. Enlaces externos a fuentes confiables</h3>
                    <p>
                        Dos o tres enlaces salientes hacia fuentes de autoridad que respalden tus datos le dan contexto
                        a tu contenido y demuestran que sabes de dónde viene la información. La condición es que confíes
                        en el recurso al que enlazas. Si vas a enlazar algo que no controlas ni respaldas, márcalo con
                        el atributo nofollow para no asociar tu sitio con él.
                    </p>
                    <p>
                        Lo mismo aplica a los comentarios y al contenido que suben usuarios: conviene que el CMS agregue
                        nofollow automáticamente a esos enlaces. Es una defensa barata contra el spam.
                    </p>

                    <h3>10. Sin contenido duplicado, con canónica definida</h3>
                    <p>
                        Si el mismo contenido vive en varias URLs, el buscador elige una para mostrar y gasta recursos
                        de rastreo en el resto. Tener duplicados no es una infracción de las políticas de spam ni
                        implica una penalización, pero sí es ineficiente y confunde al usuario.
                    </p>
                    <p>
                        La solución es asegurarte de que cada contenido sea accesible por una sola dirección. Si tienes
                        versiones repetidas, redirige las que no quieres hacia la buena. Si no puedes redirigir, usa la
                        etiqueta rel canonical para señalar cuál es la versión principal. Copiar contenido de otros sitios
                        es harina de otro costal y ahí sí hay consecuencias.
                    </p>

                    <h3>11. Experiencia en móvil y velocidad de carga</h3>
                    <p>
                        Google necesita ver tu página igual que la ve un usuario. Si bloqueas el acceso a archivos CSS o
                        JavaScript, es posible que no entienda la página y que no la posicione bien para los términos que
                        te interesan. La herramienta de inspección de URLs de Search Console te muestra exactamente cómo
                        la está viendo.
                    </p>
                    <p>
                        Súmale las métricas de experiencia en la página, que miden velocidad de carga, estabilidad visual
                        e interactividad. Ese tema tiene su propia guía en
                        <a href="/blog/core-web-vitals">Core Web Vitals</a>. Y evita los intersticiales agresivos: un
                        pop-up que tapa el contenido apenas entras es la forma más rápida de perder al visitante que
                        tanto te costó traer.
                    </p>

                    <h3>12. Datos estructurados donde aporten</h3>
                    <p>
                        Los datos estructurados son un formato estandarizado para decirle al buscador qué es cada cosa
                        dentro de tu página: un artículo, una empresa local, una pregunta frecuente, un producto. No
                        garantizan mejores posiciones, pero habilitan resultados enriquecidos como estrellas de reseña,
                        carruseles o rutas de exploración, y eso cambia mucho cómo se ve tu resultado.
                    </p>
                    <p>
                        Para un negocio local, el marcado de empresa local y el de preguntas frecuentes suelen ser los
                        primeros que valen la pena. El detalle de implementación lo vemos en
                        <a href="/blog/schema-markup-que-es">schema markup</a>.
                    </p>
                </section>

                <section id="ejemplos">
                    <h2>Ejemplos de SEO on-page aplicados</h2>
                    <p>
                        La checklist en abstracto se olvida. Así se ve aplicada en cuatro tipos de negocio muy
                        distintos entre sí, con algo en común: el ticket es alto, el ciclo de decisión es largo y
                        el cliente investiga mucho antes de levantar el teléfono. Cuando eso pasa, la página no
                        vende sola, pero sí decide si te consideran o no.
                    </p>

                    <h3>Clínica especializada o consultorio de alta especialidad</h3>
                    <p>
                        La palabra clave principal es el procedimiento más la ciudad. El title lleva el nombre del
                        tratamiento, la zona y la marca. El H1 lo repite y los H2 responden lo que la gente pregunta
                        antes de agendar: en qué consiste, quién es candidato, cuánto dura la recuperación, cuánto
                        cuesta y qué incluye.
                    </p>
                    <p>
                        Aquí el punto que más pesa es la confianza. La ficha del especialista, con cédula y
                        trayectoria, no es un adorno: es lo que hace que el contenido se sienta escrito por alguien
                        que sabe. Las fotos deben ser de las instalaciones reales con texto alternativo descriptivo,
                        nunca de banco de imágenes. Y el marcado de empresa local con dirección, teléfono y horario,
                        porque casi toda la búsqueda es local.
                    </p>

                    <h3>Despacho jurídico o firma contable</h3>
                    <p>
                        El error clásico es una sola página de servicios que enlista quince áreas de práctica. Eso
                        no posiciona para ninguna. Cada área necesita su propia página, con su propia palabra clave
                        y su propia intención: derecho corporativo, fiscal, laboral y migratorio son cuatro
                        búsquedas distintas hechas por cuatro personas distintas.
                    </p>
                    <p>
                        El contenido tiene que explicar el proceso en lenguaje llano, sin tecnicismos innecesarios,
                        porque quien busca está asustado y sin información. Los enlaces internos llevan de cada área
                        de práctica al artículo de blog que la explica a fondo y de regreso. Y el marcado de
                        preguntas frecuentes rinde muchísimo en este sector, donde las consultas suelen entrar
                        redactadas como preguntas completas.
                    </p>

                    <h3>Equipo industrial, maquinaria o servicios B2B</h3>
                    <p>
                        Aquí las búsquedas son de bajo volumen y altísima intención. Nadie escribe "compresor
                        industrial" por curiosidad. La página tiene que hablar el idioma técnico del comprador:
                        capacidades, especificaciones, compatibilidades, tiempos de entrega y refacciones.
                    </p>
                    <p>
                        Cada línea de producto o modelo va en su propia URL, agrupada en carpetas temáticas para que
                        el buscador entienda la estructura del catálogo. Las fichas técnicas se publican en HTML, no
                        solo en PDF descargable, porque el texto dentro de la página es lo que se indexa y lo que
                        genera el fragmento. Y los enlaces internos van del producto a los casos de aplicación y a
                        la página de cotización.
                    </p>

                    <h3>Desarrollo inmobiliario o proyecto de energía solar</h3>
                    <p>
                        En inmobiliaria la palabra clave principal es el nombre del desarrollo más su zona. Los H2
                        se organizan por lo que realmente se pregunta: ubicación, modelos y precios, amenidades,
                        avance de obra y formas de pago. Los renders llevan nombre de archivo descriptivo y texto
                        alternativo que dice qué modelo y qué zona se ve. El detalle completo está en
                        <a href="/blog/seo-local-para-inmobiliarias">SEO local para inmobiliarias</a> y en
                        <a href="/blog/seo-para-desarrollos-inmobiliarios">SEO para páginas de desarrollos</a>.
                    </p>
                    <p>
                        En solar la intención es mitad informativa y mitad transaccional: la gente quiere saber
                        cuánto ahorra y en cuánto recupera la inversión antes de pedir cotización. Una página que
                        solo dice "instalamos paneles solares" no responde nada de eso. El contenido debe cubrir
                        ahorro estimado, retorno de inversión, tipos de sistema y proceso de instalación, cada
                        bloque con su H2, y los enlaces internos deben llevar a la calculadora de ahorro, que es
                        donde ocurre la conversión.
                    </p>
                </section>

                <section id="mitos">
                    <h2>Lo que no vale la pena que te quite el sueño</h2>
                    <p>
                        Buena parte de lo que circula como técnicas de SEO dejó de ser cierto hace años. Google publicó
                        una lista de temas en los que, según ellos, la gente se enfoca de más. Vale la pena repasarla
                        porque ahorra horas.
                    </p>
                    <ul>
                        <li><strong>La meta etiqueta de keywords.</strong> La Búsqueda de Google no la usa. Llenarla no hace nada.</li>
                        <li><strong>La densidad de palabra clave.</strong> Repetir el término una y otra vez cansa al lector y el exceso de palabras clave va contra las políticas de spam. Escribe natural.</li>
                        <li><strong>La longitud mínima o máxima.</strong> No hay número mágico. La extensión sale del tema, no de una meta.</li>
                        <li><strong>Palabras clave en el dominio.</strong> Tienen un efecto mínimo. Elige el nombre que le sirva a tu marca.</li>
                        <li><strong>Subdominio contra subdirectorio.</strong> Haz lo que sea más fácil de administrar para tu negocio.</li>
                        <li><strong>La supuesta penalización por contenido duplicado.</strong> Tener el mismo contenido en varias URLs es ineficiente, no una acción manual.</li>
                        <li><strong>E-E-A-T como factor de posicionamiento.</strong> Google ha aclarado que no lo es. Es un marco para evaluar calidad, y aun así conviene mostrar quién escribe y con qué experiencia.</li>
                    </ul>
                    <p>
                        Nada de esto significa que la calidad no importe. Significa que la calidad se demuestra
                        escribiendo bien y siendo útil, no ajustando porcentajes. Los errores que sí cuestan tráfico los
                        reunimos en <a href="/blog/errores-de-seo-que-matan-tu-trafico">errores de SEO</a>.
                    </p>
                </section>

