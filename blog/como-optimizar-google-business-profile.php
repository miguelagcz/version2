                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Cuánto cuesta tener un perfil en Google Business Profile?</summary>
                        <p>Nada. Crear, verificar y mantener tu ficha es gratuito, y no hay una versión de paga que te ponga más arriba en Google Maps. Google lo dice de forma explícita: no se puede pedir ni pagar una mejor posición local.</p>
                        <p>Lo que sí existe son anuncios que pueden aparecer en Maps y en los resultados locales, marcados como patrocinados. Pueden servirte para ganar visibilidad mientras tu ficha madura, pero no mejoran tu posición orgánica. Si alguien te cobra por "subir tu ficha" con un pago a Google, desconfía.</p>
                    </details>

                    <details>
                        <summary>¿Puedo tener ficha si no tengo local o trabajo desde casa?</summary>
                        <p>Sí, como negocio de área de servicio. Es el caso de quien va a casa o a la empresa del cliente, como un instalador solar o un consultor. Configuras la zona que atiendes y ocultas tu dirección si no recibes clientes ahí; Google pide que esa zona no pase de unas dos horas de traslado desde tu base.</p>
                        <p>Lo que no se permite son las oficinas virtuales ni los apartados postales. Un espacio de coworking solo cuenta si tiene tu letrero, recibes clientes en horario publicado y hay personal tuyo ahí en ese horario. Dar de alta una dirección que no cumple es de las causas más comunes de suspensión.</p>
                    </details>

                    <details>
                        <summary>¿Cómo consigo más reseñas en Google sin romper las reglas?</summary>
                        <p>Pidiéndoselas a todos tus clientes, no solo a los contentos, y facilitándoles el camino con el enlace directo para dejar reseña. El mejor momento es justo después de entregar algo concreto: la escrituración, la instalación terminada, el trámite resuelto. Un mensaje corto por WhatsApp con el enlace funciona mejor que pedirlo en persona.</p>
                        <p>Lo que no puedes hacer: ofrecer descuentos o regalos a cambio, pedirle reseñas a tus empleados o familiares, ni filtrar para pedírselas solo a quien sabes que te va a calificar bien. Google elimina esas reseñas y puede sancionar la ficha. Más vale crecer despacio con reseñas reales que rápido con reseñas que desaparecen.</p>
                    </details>

                    <details>
                        <summary>¿Se puede borrar una reseña negativa en Google?</summary>
                        <p>Solo si rompe las políticas de Google: si es spam, ofensiva, de alguien con conflicto de interés, como un competidor, o no corresponde a una experiencia real. En esos casos puedes reportarla desde tu ficha para que Google la revise. Una reseña negativa legítima, aunque te parezca injusta, se queda.</p>
                        <p>Lo que sí controlas es tu respuesta. Contesta con calma, reconoce el problema si lo hubo y ofrece resolverlo por un canal privado. Tu respuesta no es para quien se quejó, es para los próximos cien prospectos que la van a leer. Un negocio de alto ticket con una queja bien respondida inspira más confianza que uno con puras cinco estrellas sospechosas.</p>
                    </details>

                    <details>
                        <summary>¿Por qué mi negocio no aparece en Google Maps?</summary>
                        <p>Las causas más comunes son cuatro: la ficha no está verificada, la categoría principal no corresponde a lo que la gente busca, el que busca está lejos de tu ubicación, o tu negocio todavía tiene poca prominencia frente a la competencia, es decir, pocas reseñas, pocas menciones y pocos enlaces.</p>
                        <p>Revisa primero lo que controlas en diez minutos: verificación, categoría, horario y que el nombre sea exactamente el de tu negocio. Si todo está bien, el problema suele ser de prominencia, y eso se trabaja con reseñas constantes, menciones en sitios de tu ciudad y una página en tu sitio que respalde lo que dice la ficha. También revisa que la ficha no esté suspendida.</p>
