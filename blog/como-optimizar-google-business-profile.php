                <section id="que-es">
                    <h2>Qué es Google Business Profile</h2>
                    <p>
                        Es la ficha gratuita de tu negocio en Google, la que antes se llamaba Google My Business. Aparece en Google Maps, en el bloque de mapa de los resultados de búsqueda y en el panel de la derecha cuando alguien busca tu nombre. Ahí van tu dirección, teléfono, horario, fotos, reseñas y servicios.
                    </p>
                    <p>
                        Piensa en ella como el aparador de tu negocio en la calle más transitada de la ciudad. No sustituye a tu sitio web, igual que el aparador no sustituye a la tienda, pero es lo primero que ve la gente y decide si entra o sigue de largo. Por eso conviene tratarla como una página más de tu sitio, no como un trámite.
                    </p>
                    <p>
                        Es la base del SEO local. Si vendes en una zona concreta, lo explicamos aplicado al caso inmobiliario en <a href="/blog/seo-local-para-inmobiliarias">SEO local para inmobiliarias</a>.
                    </p>
                </section>

                <section id="como-decide-google">
                    <h2>Cómo decide Google a quién mostrar</h2>
                    <p>
                        Google lo explica en su ayuda con tres factores:
                    </p>
                    <ul>
                        <li><strong>Relevancia.</strong> Qué tan bien coincide tu ficha con lo que se busca. Una ficha completa, con la categoría correcta y servicios bien descritos, le da a Google más elementos para conectarte con la búsqueda.</li>
                        <li><strong>Distancia.</strong> Qué tan lejos estás de quien busca o de la zona que menciona en su búsqueda. Esta no la controlas, salvo eligiendo bien tu ubicación o tu área de servicio.</li>
                        <li><strong>Prominencia.</strong> Qué tan conocido es tu negocio. Cuentan las reseñas, su calificación, y también lo que se dice de ti en el resto de internet, incluidos los <a href="/blog/link-building-enlaces-de-calidad">enlaces de otros sitios</a> hacia el tuyo.</li>
                    </ul>
                    <p>
                        Y una aclaración que te ahorra dinero: Google dice de forma explícita que no se puede pagar por una mejor posición local. Los anuncios en Maps existen, van marcados, y no mueven tu lugar orgánico.
                    </p>
                </section>

                <section id="paso-a-paso">
                    <h2>Cómo optimizar tu ficha paso a paso</h2>

                    <h3>1. Reclámala y verifícala</h3>
                    <p>
                        Busca tu negocio en Google Maps; si ya existe una ficha, reclámala, y si no, créala. La verificación le confirma a Google que tienes derecho a representar ese negocio y hace más probable que aparezcas. Sin verificar, todo lo demás vale poco.
                    </p>

                    <h3>2. Usa tu nombre real, sin adornos</h3>
                    <p>
                        El nombre debe ser el que usas en tu letrero, tu sitio y tus facturas. Nada de agregarle "Mejor Dentista CDMX" o "Abogados Laborales 24 horas". Google prohíbe meter frases de mercadotecnia, zonas o descripciones de servicio en el nombre, y es de las causas más comunes de suspensión.
                    </p>

                    <h3>3. Elige la categoría principal con cuidado</h3>
                    <p>
                        La categoría principal pesa mucho en las búsquedas en las que apareces. Escoge la más específica que describa tu actividad principal, como si completaras la frase "este negocio es un...". Agrega pocas secundarias, solo las que de verdad describen lo que haces, y nunca uses categorías como si fueran palabras clave.
                    </p>

                    <h3>4. Dirección o área de servicio</h3>
                    <p>
                        Si recibes clientes en un lugar, pon la dirección exacta y asegúrate de que tu letrero esté ahí. Si vas tú con el cliente, configúrate como negocio de área de servicio, define la zona y oculta la dirección. Las oficinas virtuales y los apartados postales no califican.
                    </p>

                    <h3>5. Horarios, incluidos los especiales</h3>
                    <p>
                        Horario normal, horarios de temporada y días festivos. Pocas cosas generan peor reseña que manejar media hora para encontrar cerrado un negocio que Google decía abierto.
                    </p>

                    <h3>6. Servicios y descripción en el idioma de tu cliente</h3>
                    <p>
                        Describe tus servicios con las palabras que usa tu cliente, no con las tuyas. Si no sabes cuáles son, empieza por una <a href="/blog/como-hacer-investigacion-de-palabras-clave">investigación de palabras clave</a>. Escribe una descripción clara de lo que haces, para quién y en qué zona, sin repetir palabras clave como lista.
                    </p>

                    <h3>7. Fotos y videos reales</h3>
                    <p>
                        Fachada, interior, equipo, trabajos terminados. Google pide que muestren lo que ofreces y cuenten la historia de tu negocio, y para tu prospecto son la primera prueba de que existes. Las fotos de banco de imágenes no le dicen nada a nadie.
                    </p>

                    <h3>8. Enlaza a la página correcta de tu sitio</h3>
                    <p>
                        El botón de sitio web no tiene que llevar a tu página principal. Si tienes una página por sucursal o por servicio, enlaza a la que corresponde. Agrega parámetros de seguimiento al enlace para que en Analytics distingas las visitas que llegan desde tu ficha.
                    </p>

                    <h3>9. Publica novedades</h3>
                    <p>
                        Las publicaciones de la ficha sirven para anunciar ofertas, eventos o noticias. No hacen milagros en la posición, pero una ficha con actividad reciente transmite que el negocio está vivo, y a tu prospecto eso le importa.
                    </p>
                </section>

                <section id="resenas">
                    <h2>Reseñas: cómo conseguirlas sin romper reglas</h2>
                    <p>
                        Las reseñas son la parte de la prominencia que más puedes trabajar. La regla de oro es pedírselas a todos tus clientes, en el momento en que entregaste algo concreto, con el enlace directo para que les tome un minuto.
                    </p>
                    <p>
                        Google es muy claro con lo que no se vale, y vale la pena tenerlo presente porque se sanciona:
                    </p>
                    <ul>
                        <li><strong>Ofrecer algo a cambio</strong>, sea descuento, regalo o pago, por dejar una reseña o por cambiar una negativa.</li>
                        <li><strong>Reseñas de gente con conflicto de interés</strong>: empleados, exempleados, familiares, socios o proveedores.</li>
                        <li><strong>Filtrar a quién le pides reseña</strong>, pidiéndosela solo a los clientes que sabes que están contentos.</li>
                        <li><strong>Presionar en el momento</strong> o ponerle metas de reseñas a tu equipo.</li>
                    </ul>
                    <p>
                        Y contesta todas, las buenas y las malas. Responder demuestra que te importa la opinión de tus clientes, y una respuesta profesional a una queja convence más que diez cinco estrellas sin comentario.
                    </p>
                </section>

                <section id="errores-comunes">
                    <h2>Errores comunes</h2>
                    <p>
                        Ordenados por lo que más cuestan:
                    </p>
                    <ol>
                        <li><strong>Meter palabras clave en el nombre.</strong> Funciona un tiempo y termina en suspensión, que es mucho peor que no haberlo hecho.</li>
                        <li><strong>Usar una dirección que no califica.</strong> Oficina virtual, apartado postal o casa de un familiar. Otra vía rápida a la suspensión.</li>
                        <li><strong>Comprar o inventar reseñas.</strong> Google las detecta, las borra y puede marcar la ficha.</li>
                        <li><strong>Datos distintos en cada lugar.</strong> Un teléfono en la ficha, otro en el sitio y otro en los directorios. Nombre, dirección y teléfono deben ser idénticos en todos lados, también en los <a href="/blog/schema-markup-que-es">datos estructurados</a> de tu sitio.</li>
                        <li><strong>Fichas duplicadas.</strong> Una por cada vez que alguien la dio de alta. Solo debe existir una por ubicación.</li>
                        <li><strong>Crearla y olvidarla.</strong> Horarios viejos, fotos de hace cinco años y reseñas sin responder le dicen al prospecto que nadie está del otro lado.</li>
                    </ol>
                </section>

                <section id="por-industria">
                    <h2>Cómo se ve esto en tu industria</h2>

                    <h3>Clínicas y consultorios</h3>
                    <p>
                        La clínica tiene su ficha, y los médicos que atienden pueden tener la suya como profesionales. Cuida que las categorías sean de especialidad, no genéricas, y que el horario sea el de atención real. En salud, las reseñas pesan muchísimo en la decisión: pídelas al cerrar cada tratamiento, no en la primera consulta.
                    </p>

                    <h3>Despachos jurídicos y contables</h3>
                    <p>
                        La categoría principal decide si apareces en "abogado laboral" o en "abogado" a secas, que es mucho más competida. Describe cada área de práctica como servicio, y contesta las reseñas con cuidado: nunca reveles detalles del caso de un cliente al responder.
                    </p>

                    <h3>Empresas de energía solar</h3>
                    <p>
                        Casi siempre son negocios de área de servicio: vas a la casa o a la empresa del cliente. Configura bien la zona que cubres y oculta la dirección si no tienes sala de exhibición. Las fotos de instalaciones terminadas, con permiso del cliente, son tu mejor argumento.
                    </p>

                    <h3>Desarrolladoras inmobiliarias</h3>
                    <p>
                        La oficina de ventas o el departamento muestra de cada proyecto puede tener su ficha si tiene letrero, horario de atención y personal en ese horario. Un terreno en obra sin nadie que atienda no califica. Cuando el proyecto se vende, márcalo como cerrado en vez de dejar una ficha abandonada. Lo complementa la estructura de páginas de <a href="/blog/seo-para-desarrollos-inmobiliarios">SEO para desarrollos inmobiliarios</a>.
                    </p>
                </section>

                <section id="como-medirlo">
                    <h2>Cómo medirlo y qué esperar</h2>
                    <p>
                        Dentro de tu ficha, el apartado de rendimiento te muestra cuánta gente la vio, con qué búsquedas te encontró, y cuántas llamadas, solicitudes de ruta y clics al sitio generó. Esas acciones son las que importan: una vista no es un cliente, una llamada sí puede serlo.
                    </p>
                    <p>
                        Complementa con Analytics, gracias a los parámetros de seguimiento del paso 8, y con una revisión mensual de reseñas: cuántas nuevas, qué calificación promedio y cuántas respondiste. Si quieres saber cómo apareces en distintas zonas de tu ciudad, busca desde el celular en varios puntos; la posición en el mapa cambia según dónde está quien busca.
                    </p>
                    <p>
                        Los cambios de datos se reflejan en días. La posición tarda más, porque la prominencia se construye con reseñas y menciones mes a mes. Una ficha completa y verificada suele empezar a ganar llamadas en semanas; ganarle a un competidor con años de reseñas toma meses.
                    </p>
                </section>

