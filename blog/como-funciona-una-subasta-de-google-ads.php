                    </details>

                    <details>
                        <summary>¿El Nivel de Calidad que veo en mi cuenta es exactamente el mismo que usa Google en la subasta?</summary>
                        <p>No exactamente. El número que ves en tu cuenta (del 1 al 10) es una herramienta de diagnóstico para que tú entiendas, en términos generales, cómo se compara tu anuncio con el de otros anunciantes. En el momento real de cada subasta, Google recalcula versiones más específicas de esos mismos componentes (CTR esperada, relevancia y experiencia de la página de destino) según el contexto exacto de esa búsqueda en particular. Por eso puedes tener un Nivel de Calidad de 7 en tu cuenta y aun así ver variaciones en cómo te va subasta a subasta: el número que ves es un promedio útil para diagnosticar, no una copia exacta de lo que pasa en cada subasta individual.</p>
                    </details>

                    <details>
                        <summary>¿Conviene enfocarse en bajar el CPC o en mejorar las conversiones?</summary>
