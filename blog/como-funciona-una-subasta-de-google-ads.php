                <section id="que-pasa-en-la-busqueda">
                    <h2>¿Qué pasa exactamente cuando alguien busca?</h2>
                    <p>
                        Cuando alguien escribe una búsqueda en Google, el sistema revisa todos los anuncios cuyas palabras clave coinciden con esa búsqueda. De esa lista, primero descarta los que no son aptos por alguna razón (por ejemplo, anuncios dirigidos a otro país o anuncios rechazados por incumplir alguna política). De los que quedan, solo se muestran los que tienen un Ranking del Anuncio lo suficientemente alto.
                    </p>
                    <p>
                        Aquí está el detalle importante que casi nadie explica bien: Google no calcula el Ranking del Anuncio una sola vez por búsqueda. Lo calcula por cada posición disponible en la página. Los anuncios que aparecen arriba de los resultados orgánicos compiten en una subasta distinta a la de los anuncios que aparecen abajo, y tu anuncio puede aparecer una sola vez en cada posición, aunque en teoría podría mostrarse en varios lugares distintos de esa misma página de resultados.
                    </p>
                </section>

                <section id="factores-del-ranking">
                    <h2>Los factores que determinan el Ranking del Anuncio</h2>
                    <p>
                        Según la propia documentación de Google Ads, el Ranking del Anuncio se calcula a partir de estos elementos:
                    </p>
                    <ul>
                        <li><strong>Tu puja.</strong> El monto máximo que estás dispuesto a pagar por un clic. Puedes cambiarlo en cualquier momento.</li>
                        <li><strong>La calidad de tu anuncio y de tu página de destino.</strong> Esto se resume en lo que Google llama tu Nivel de Calidad, que veremos a detalle en la siguiente sección.</li>
                        <li><strong>El umbral mínimo del Ranking del Anuncio.</strong> Un piso de calidad que tu anuncio debe superar para siquiera entrar a competir, sin importar cuánto pujes.</li>
                        <li><strong>La competitividad de esa subasta en particular.</strong> Si dos anunciantes tienen un ranking muy parecido, ambos tienen posibilidades similares de ganar esa posición. Entre más grande sea la diferencia entre dos anunciantes, más probable es que gane el de ranking más alto, aunque eso también puede significar un costo por clic mayor para quien gana con más margen.</li>
                        <li><strong>El contexto de la búsqueda.</strong> Los términos exactos que usó la persona, su ubicación, el tipo de dispositivo, la hora del día y otras señales que ayudan a Google a decidir qué tan relevante eres para ese momento específico.</li>
                        <li><strong>El impacto esperado de tus extensiones y otros formatos de anuncio.</strong> Cosas como agregar tu número de teléfono, enlaces a páginas específicas de tu sitio, o una dirección, pueden mejorar tu ranking si Google calcula que le van a aportar valor real a quien busca.</li>
                    </ul>
                    <p>
                        Ninguno de estos seis factores actúa solo. Se combinan en cada subasta, lo que explica por qué dos negocios con presupuestos parecidos pueden tener resultados muy distintos.
                    </p>
                </section>

                <section id="nivel-de-calidad">
                    <h2>¿Qué es el Nivel de Calidad?</h2>
                    <p>
                        El Nivel de Calidad es la forma en que Google resume qué tan bueno es tu anuncio comparado con el de otros anunciantes que compiten por la misma búsqueda. Se basa en tres cosas: el porcentaje de clics que se espera que reciba tu anuncio, qué tan relevante es tu anuncio para lo que la persona buscó, y qué tan buena es la experiencia de la página a la que mandas a esa persona después del clic.
                    </p>
                    <p>
                        Vale la pena aclarar algo que confunde a mucha gente: el número de Nivel de Calidad que ves en tu cuenta no es, en sí mismo, un factor que entra directo en la fórmula de la subasta. Es una herramienta de diagnóstico que te ayuda a entender, de forma aproximada, cómo estás parado frente a la competencia. Pero los componentes que lo forman (esa CTR esperada, la relevancia y la experiencia de la página de destino) sí forman parte real del cálculo del Ranking del Anuncio. Este tema es tan importante que le dedicaremos su propia guía completa.
                    </p>
                </section>

                <section id="que-es-el-cpc">
                    <h2>¿Qué es el CPC y por qué casi nunca pagas tu puja máxima?</h2>
                    <p>
                        CPC son las siglas de costo por clic: lo que efectivamente pagas cada vez que alguien le da clic a tu anuncio. Junto con el CPM (costo por mil impresiones) y el CTR (porcentaje de clics), es una de las métricas básicas que vas a ver todo el tiempo en tu cuenta de Google Ads.
                    </p>
                    <p>
                        La puja que configuras es un tope máximo, no lo que realmente vas a pagar. En la mayoría de los casos terminas pagando menos, porque el costo real depende de qué tan cerca está el ranking del anunciante justo debajo de ti en esa subasta, y de tu propio Nivel de Calidad. Dicho de forma simple: si tu anuncio es notablemente mejor que el del competidor que va justo detrás de ti, puedes ganar esa posición pagando bastante menos que tu puja máxima. Si están casi empatados, es más probable que termines pagando cerca de ese tope.
                    </p>
                    <p>
                        Esto tiene una implicación práctica enorme: subir tu puja no es la única palanca que tienes para bajar tu costo por clic. Mejorar la relevancia de tu anuncio y la experiencia de tu página de destino puede lograr resultados parecidos, o mejores, sin gastar más.
                    </p>
                </section>

                <section id="ejemplo-aplicado">
                    <h2>Un ejemplo aplicado</h2>
                    <p>
                        Imagina dos desarrolladoras inmobiliarias pujando por la búsqueda "departamentos en preventa en Zapopan". La primera puja 40 pesos por clic, pero su anuncio es genérico y manda a la persona a la página principal de su sitio, sin mencionar Zapopan en ningún lado. La segunda puja 28 pesos, pero su anuncio menciona la zona exacta, el precio de entrada y manda directo a una página dedicada a ese desarrollo específico.
                    </p>
                    <p>
                        Es muy probable que la segunda desarrolladora termine con un Nivel de Calidad más alto, porque su anuncio y su página de destino son mucho más relevantes para esa búsqueda exacta. Eso puede compensar por completo la diferencia de 12 pesos en la puja, y en muchos casos hasta ganarle la posición a la primera, pagando menos por cada clic.
                    </p>
                </section>

