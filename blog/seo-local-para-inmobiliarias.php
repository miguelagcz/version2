                <section id="que-es-seo-local">
                    <h2>¿Qué es el SEO local?</h2>
                    <p>
                        El SEO local es la parte del posicionamiento orgánico enfocada en aparecer en búsquedas que tienen intención geográfica: "inmobiliaria en Guadalajara", "departamentos cerca de mí", "desarrollos en preventa en Zapopan". Google trata estas búsquedas distinto a una búsqueda genérica, porque asume que a la persona le importa la ubicación tanto como el producto.
                    </p>
                    <p>
                        Para una inmobiliaria esto no es un extra, es prácticamente todo el juego. Nadie compra un departamento en una ciudad donde no piensa vivir solo porque el sitio de esa desarrolladora tenía buen contenido. El comprador ya trae la zona decidida (o casi decidida) antes de buscar en Google, así que la pregunta real es si tu desarrollo aparece cuando esa persona busca en esa zona.
                    </p>
                </section>

                <section id="como-rankea-google">
                    <h2>Los 3 factores que usa Google para rankear resultados locales</h2>
                    <p>
                        Google mismo explica que el orden de los resultados locales (los que aparecen con el mapa arriba de los resultados normales) se basa en tres cosas, y ninguna de ellas se puede comprar:
                    </p>
                    <ul>
                        <li><strong>Relevancia.</strong> Qué tan bien coincide la información de tu ficha con lo que la persona está buscando. Si vendes departamentos y tu ficha dice "constructora", ya perdiste puntos antes de empezar.</li>
                        <li><strong>Distancia.</strong> Qué tan lejos está tu negocio del punto de búsqueda o de la ubicación que la persona compartió. Esto es literal: entre más cerca, más probabilidades.</li>
                        <li><strong>Popularidad (o prominencia).</strong> Qué tan conocida es tu empresa según señales como enlaces que apuntan a tu sitio y, sobre todo, la cantidad y calidad de tus reseñas.</li>
                    </ul>
                    <p>
                        Lo importante aquí es que Google es explícito en que no se puede pagar por un mejor posicionamiento local. No hay una versión de Google Ads para esto. Se gana con información completa, cercanía real y reputación, no con presupuesto.
                    </p>
                </section>

                <section id="ficha-de-negocio">
                    <h2>Tu ficha de Perfil de Negocio en Google</h2>
                    <p>
                        Este es el punto de partida obligatorio y, en la práctica, el que más inmobiliarias dejan a medias. Una ficha completa (dirección exacta, categoría de negocio correcta, horario real, fotos de las torres o casas muestra, y una descripción que use las palabras que realmente busca la gente) le da a Google la información que necesita para decidir que eres relevante.
                    </p>
                    <p>
                        Google tarda hasta un mes en posicionar una ficha nueva, y hasta tres días en reflejar cualquier cambio que hagas. Esto significa que no vale la pena crear la ficha una semana antes de un lanzamiento y esperar visibilidad inmediata. Le dedicamos una guía completa a este tema en <a href="/blog/como-optimizar-google-business-profile">cómo optimizar tu ficha de Google Business Profile</a>, con el paso a paso de qué llenar y en qué orden.
                    </p>
                </section>

                <section id="contenido-por-zona">
                    <h2>Páginas y contenido por desarrollo o zona</h2>
                    <p>
                        Aquí es donde el SEO local se cruza con el SEO on-page normal. Si tienes desarrollos en Guadalajara, Zapopan y Riviera de Chapala, tener una sola página genérica de "nuestros desarrollos" obliga a Google a adivinar en qué zona posicionarte. Una página dedicada por desarrollo, con el nombre de la zona en el título y en el contenido, le da a Google una señal mucho más clara de para qué búsqueda mostrar esa página específica.
                    </p>
                    <p>
                        No se trata de repetir el nombre de la ciudad veinte veces, eso raya en el exceso de palabras clave y Google lo penaliza. Se trata de escribir con naturalidad sobre lo que de verdad importa en esa zona: distancia a vialidades, plusvalía del área, amenidades cercanas. Cubrimos la estructura completa de cómo optimizar cada página en nuestra <a href="/blog/seo-on-page-checklist">checklist de SEO on-page</a>.
                    </p>
                </section>

                <section id="resenas">
                    <h2>Reseñas: la señal que más pesa</h2>
                    <p>
                        De los tres factores de posicionamiento local, la popularidad es el único que se construye principalmente fuera de tu sitio web, y las reseñas son su ingrediente más fuerte. Google lo dice sin rodeos: entre más reseñas positivas acumules, mejor puede ser tu posicionamiento local.
                    </p>
                    <p>
                        Para una inmobiliaria esto tiene una ventaja natural: ya tienes clientes que acaban de vivir una decisión de compra grande y emocional. Pedirle una reseña a alguien que acaba de firmar la escritura de su nueva casa suele ser mucho más fácil que pedírsela a un cliente de compra rápida. El error común es no pedirla nunca, o pedirla meses después cuando el entusiasmo ya bajó.
                    </p>
                </section>

