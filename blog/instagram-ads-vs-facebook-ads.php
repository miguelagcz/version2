                <section id="errores-comunes">
                    <h2>Errores comunes</h2>
                    <p>
                        Ordenados por lo que más cuestan:
                    </p>
                    <ol>
                        <li><strong>Decidir por gusto personal.</strong> "Yo no uso Facebook" no dice nada de dónde está tu cliente. Los datos de tu cuenta sí.</li>
                        <li><strong>Usar el mismo creativo horizontal en todas las ubicaciones.</strong> Se ve recortado en historias y Reels, rinde mal, y terminas culpando a Instagram. La guía de formato está en <a href="/blog/instagram-reels-ads-high-ticket">Instagram Reels Ads para alto ticket</a>.</li>
                        <li><strong>Separar plataformas con presupuestos chicos.</strong> Dos campañas a medias aprenden peor que una completa.</li>
                        <li><strong>Comparar por costo por clic.</strong> La ubicación con clics baratos puede ser la que trae los peores prospectos.</li>
                        <li><strong>No revisar el desglose por ubicación.</strong> El Administrador de Anuncios te lo da gratis y casi nadie lo abre. Te explicamos dónde está en <a href="/blog/como-leer-ads-manager">cómo leer el Ads Manager</a>.</li>
                    </ol>
                </section>

                <section id="por-industria">
                    <h2>Cómo se ve esto en tu industria</h2>

                    <h3>Desarrolladoras inmobiliarias</h3>
                    <p>
                        Los recorridos en video vertical rinden muy bien en Instagram para generar interés, y Facebook suele traer al comprador de mayor edad que decide la inversión. Marketplace merece una prueba propia para unidades en venta o renta. La estrategia completa está en <a href="/blog/facebook-ads-para-inmobiliarias">Facebook Ads para inmobiliarias</a>.
                    </p>

                    <h3>Clínicas y consultorios</h3>
                    <p>
                        Tratamientos estéticos y especialidades con resultados visibles tienen en Instagram su terreno natural. Especialidades donde el paciente es mayor o donde decide un familiar, como cuidados de adultos mayores, suelen necesitar Facebook. En ambas, el especialista explicando una duda real convence más que cualquier diseño.
                    </p>

                    <h3>Empresas de energía solar</h3>
                    <p>
                        El dueño de casa que paga un recibo alto suele estar en Facebook; el video de una instalación terminada y el antes y después del recibo funcionan en las dos. Aquí la diferencia la hace el formulario más que la plataforma, como explicamos en <a href="/blog/facebook-ads-para-energia-solar">Facebook Ads para energía solar</a>.
                    </p>

                    <h3>Despachos y servicios B2B</h3>
                    <p>
                        Facebook tiende a rendir mejor en frío para servicios profesionales, e Instagram para la marca personal del socio o del especialista. Para los dos, el uso más rentable suele ser el remarketing a quien ya visitó tu sitio o leyó tu contenido.
                    </p>
                </section>

                <section id="como-medirlo">
                    <h2>Cómo medirlo y qué esperar</h2>
                    <p>
                        En el Administrador de Anuncios, usa el <strong>desglose por plataforma y por ubicación</strong>. Te muestra cuánto gastaste, cuántos resultados obtuviste y a qué costo en cada lugar. Revísalo cuando cada ubicación haya acumulado suficientes resultados para comparar, no a los tres días.
                    </p>
                    <p>
                        Después, cruza esos datos con tu CRM: de qué plataforma vino cada prospecto y cuántos llegaron a cita o a venta. Esa es la métrica que decide. Si una ubicación trae leads más caros pero que cierran más, es la buena. Para bajar el costo de las que no rinden, revisa <a href="/blog/como-bajar-costo-por-lead-facebook-ads">cómo bajar el costo por lead</a>.
                    </p>
                </section>

