                <section id="misma-plataforma">
                    <h2>Una sola plataforma, muchas ubicaciones</h2>
                    <p>
                        Lo primero que hay que entender: Instagram Ads y Facebook Ads no son dos plataformas de publicidad distintas. Las dos son de Meta, se compran en el mismo Administrador de Anuncios, usan el mismo Pixel, los mismos públicos y el mismo presupuesto. Lo que cambia es la <strong>ubicación</strong>, es decir, el lugar donde se ve tu anuncio.
                    </p>
                    <p>
                        En Facebook, tu anuncio puede aparecer en el feed, en las historias, en Reels, en Marketplace, en los resultados de búsqueda, en los videos y en la columna derecha de la computadora. En Instagram, en el feed, en las historias, en Reels, en Explorar, en el perfil y en la búsqueda. Meta también ofrece Messenger, Threads y su red de aplicaciones externas.
                    </p>
                    <p>
                        Piénsalo como un centro comercial con varios pasillos. No estás eligiendo entre dos centros comerciales; estás eligiendo en qué pasillos poner tu aparador. La cuenta, la estructura y la medición son las mismas, como explicamos en <a href="/blog/como-estructurar-cuenta-meta-ads">cómo estructurar una cuenta de Meta Ads</a>.
                    </p>
                </section>

                <section id="diferencias">
                    <h2>En qué se diferencian de verdad</h2>

                    <h3>El formato</h3>
                    <p>
                        Instagram es visual y vertical. El anuncio que funciona ahí parece una publicación más: video corto, imagen limpia, poco texto encima. Facebook tolera más texto, más enlaces y formatos horizontales, y tiene ubicaciones que Instagram no tiene, como Marketplace, que para inmobiliarias y autos es un mundo aparte.
                    </p>

                    <h3>El momento en que te ve</h3>
                    <p>
                        En Instagram la gente pasa rápido, en modo de entretenimiento e inspiración. En Facebook hay más lectura, más grupos, más búsqueda de cosas concretas. No es una regla absoluta, pero cambia el tipo de mensaje que funciona: en Instagram ganas con lo que se ve en tres segundos, en Facebook puedes permitirte explicar un poco más.
                    </p>

                    <h3>El público</h3>
                    <p>
                        En general, Instagram concentra más público joven y Facebook conserva a muchos usuarios de 35 años en adelante, que en negocios de alto ticket suelen ser los que deciden y pagan. Pero esto varía tanto por ciudad, nivel socioeconómico y producto que no conviene asumirlo: el desglose por edad y ubicación de tu propia cuenta te lo dice en una semana.
                    </p>

                    <h3>El costo</h3>
                    <p>
                        No hay una plataforma más barata para todos. El costo por mil impresiones y por clic cambia según la competencia, el público y qué tan bien encaja tu creativo en cada formato. Comparar costos por clic entre las dos plataformas sin ver qué pasa después del clic es la forma más común de tomar la decisión equivocada.
                    </p>
                </section>

                <section id="ubicaciones-automaticas">
                    <h2>Dejar que Meta reparta o separar</h2>
                    <p>
                        Meta ofrece las <strong>ubicaciones Advantage+</strong>: dejas que el sistema reparta tus anuncios entre todas sus ubicaciones según dónde encuentre mejores resultados. Si no eliges ubicaciones a mano, el sistema las considera todas, y su propia documentación aclara que puede ir agregando nuevas conforme aparecen.
                    </p>
                    <p>
                        Para la mayoría de las cuentas es el punto de partida correcto, porque concentra el presupuesto y los datos en vez de dividirlos. La condición es tener <strong>un creativo para cada formato</strong>: al menos una versión vertical para historias y Reels y una cuadrada o vertical para los feeds. Si subes un video horizontal y lo dejas correr en Reels, el sistema lo va a mostrar ahí recortado y va a parecer que Instagram no funciona, cuando el problema es el formato.
                    </p>
                    <p>
                        Separar Instagram y Facebook en campañas distintas tiene sentido cuando ya tienes datos que lo justifican, no como punto de partida. Cada división adicional reparte tu presupuesto en más conjuntos de anuncios, y cada uno necesita su propio volumen de resultados para que Meta aprenda. Cuánto presupuesto hace falta para eso lo calculamos en <a href="/blog/presupuesto-minimo-meta-ads-por-industria">presupuesto mínimo para Meta Ads según tu industria</a>.
                    </p>
                </section>

                <section id="cuando-conviene">
                    <h2>Cuándo conviene cada una</h2>
                    <ul>
                        <li><strong>Tu producto se vende por los ojos.</strong> Interiores, amenidades, antes y después, resultados visibles. Instagram suele llevar la delantera, sobre todo con video.</li>
                        <li><strong>Quien decide la compra tiene más de 40 años.</strong> Facebook casi siempre tiene que estar en la mezcla, aunque te parezca que "ya nadie lo usa".</li>
                        <li><strong>Vendes o rentas propiedades, autos o equipo.</strong> Marketplace es una ubicación de Facebook con intención de compra que Instagram no tiene.</li>
                        <li><strong>Construyes marca personal del fundador o del especialista.</strong> Instagram favorece el contenido de persona a persona y es donde mejor rinde ese formato.</li>
                        <li><strong>Vendes a otras empresas.</strong> Las dos sirven para remarketing a quien ya visitó tu sitio, pero para llegar en frío a puestos de decisión, Meta no es el único canal ni siempre el mejor.</li>
                    </ul>
