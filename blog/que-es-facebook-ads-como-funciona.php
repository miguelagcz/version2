                <section id="kpis-y-roas">
                    <h2>KPIs, ROAS y cómo leer los resultados de tu campaña</h2>
                    <p>
                        Un KPI (indicador clave de rendimiento) es cualquier métrica que uses para saber si tu campaña está cumpliendo su objetivo. Dentro del Administrador de Anuncios puedes revisar tus KPIs a nivel de campaña, conjunto de anuncios o anuncio individual, y personalizar qué columnas quieres ver según tu objetivo de negocio.
                    </p>
                    <p>
                        Entre las métricas que vas a revisar con más frecuencia están:
                    </p>
                    <ul>
                        <li><strong>Resultados.</strong> Cuántas veces tu anuncio logró la acción para la que fue optimizado.</li>
                        <li><strong>Costo por resultado.</strong> El importe gastado total dividido entre el número de resultados; te dice qué tan rentable fue la campaña.</li>
                        <li><strong>Alcance e impresiones.</strong> El alcance mide a cuántas personas distintas llegó tu anuncio, mientras que las impresiones cuentan cada vez que se mostró, incluyendo repeticiones a la misma persona.</li>
                        <li><strong>ROAS (retorno de la inversión publicitaria).</strong> Cuánto generaste en ventas por cada peso invertido en publicidad; es probablemente el indicador más importante para cualquier negocio de alto ticket.</li>
                    </ul>
                    <p>
                        El Administrador de Anuncios también te permite crear informes personalizados con filtros, desgloses por periodo, datos demográficos o tipo de acción, programarlos para que lleguen a tu correo, y exportarlos en formato XLSX o CSV para compartirlos con tu equipo.
                    </p>
                    <p>
                        Para interpretar estos números con más profundidad y evitar los errores que más dinero le cuestan a las cuentas nuevas, revisa <a href="/blog/errores-comunes-cpa-meta-ads">errores comunes que disparan tu CPA en Meta Ads</a> y, cuando ya tengas resultados estables, <a href="/blog/como-escalar-campana-meta-ads">cómo escalar una campaña de Meta Ads sin perder rentabilidad</a>.
                    </p>
