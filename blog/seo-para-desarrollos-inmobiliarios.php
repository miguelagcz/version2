                <section id="faq" class="post-flova-faq">
                    <h2>Preguntas frecuentes</h2>

                    <details>
                        <summary>¿Conviene un micrositio propio para cada desarrollo?</summary>
                        <p>Para la mayoría de las desarrolladoras, no. Un dominio nuevo arranca sin autoridad, sin enlaces y sin historial, y todo lo que gane muere cuando se agote el inventario y el sitio se apague. Una subcarpeta dentro del dominio de la desarrolladora hereda la confianza acumulada por los proyectos anteriores y se queda como portafolio cuando el proyecto se entrega.</p>
                        <p>La excepción es el proyecto de escala grande que va a operar como marca independiente durante años, con su propia prensa y su propia operación. Ahí el dominio propio se justifica, siempre que exista el compromiso de mantener el sitio vivo después de vender la última unidad. Si nadie va a pagar ese hosting en tres años, no lo hagas.</p>
                    </details>

                    <details>
                        <summary>¿Cómo posiciono un desarrollo que todavía está en preventa?</summary>
                        <p>Construyendo el contenido alrededor de lo que sí existe: la zona, el proceso de compra y el respaldo de quien construye. Nadie puede escribir una reseña de vivir en tu torre todavía, pero sí puedes publicar el análisis de plusvalía de la colonia, los tiempos de traslado reales a los corredores de oficina, la obra pública en camino y el comparativo de rentas actuales. Eso atrae al comprador en la etapa en la que todavía está decidiendo zona, que es cuando puedes ganarlo.</p>
                        <p>En paralelo, publica avance de obra con fecha y fotos reales cada mes. Es el contenido más fácil de producir en preventa, es el que más desconfianza desactiva, y le da al buscador señales constantes de que la página se actualiza. Un proyecto con dieciocho meses de avance documentado vende distinto a uno con tres renders y un teléfono.</p>
                    </details>

                    <details>
                        <summary>¿Qué hago con la página cuando se vende todo el inventario?</summary>
                        <p>Déjala viva y conviértela en prueba. Cambias el estado a proyecto entregado, subes fotos del resultado construido, sumas testimonios de residentes y agregas un bloque que dirija al proyecto activo más parecido. Las visitas que sigan llegando son de gente investigando tu seriedad antes de comprarte otra cosa, y esa es la audiencia más valiosa que tienes.</p>
                        <p>Lo que no debes hacer es borrar la URL ni apagar el sitio. Con eso pierdes las notas de prensa que te enlazaron, las menciones en portales del sector y el historial que Google ya tenía de esa página. Si por una razón de peso tiene que desaparecer, aplica una redirección permanente hacia la página del portafolio o hacia el proyecto sucesor, nunca hacia la portada.</p>
                    </details>

                    <details>
                        <summary>¿El SEO sirve si mi desarrollo se vende en doce meses?</summary>
                        <p>Sirve, pero no como canal principal de ese proyecto en particular. En doce meses las páginas de marca posicionan a tiempo y aportan cierre de demanda, mientras que las páginas de zona y tipología apenas estarán agarrando fuerza cuando ya vendiste. Para llenar un proyecto rápido, la pauta hace el trabajo pesado.</p>
                        <p>El cálculo cambia si lo ves a nivel empresa en lugar de a nivel proyecto. Lo que construyes en el dominio de la desarrolladora lo hereda el proyecto siguiente, y el siguiente. Visto así, el SEO de un desarrollo no se paga con la venta de ese desarrollo: se paga con el arranque más barato del que viene atrás. Los tiempos completos los explicamos en la guía sobre <a href="/blog/cuanto-tarda-el-seo-en-dar-resultados">cuánto tarda el SEO en dar resultados</a>.</p>
                    </details>

                    <details>
                        <summary>¿Me conviene publicar en portales inmobiliarios o en mi propio sitio?</summary>
                        <p>Los dos, y con papeles distintos. Los portales te dan volumen inmediato de contactos y compiten muy bien por las búsquedas genéricas de compra, que es una pelea que un sitio de desarrolladora rara vez gana de frente. Úsalos para generación de leads inmobiliarios desde el día uno.</p>
                        <p>Tu sitio hace otra cosa: es donde el prospecto verifica que el proyecto es real y que tú lo puedes entregar, y es el único activo que te pertenece. Del portal te vas cuando dejas de pagar la cuota, con todo y el historial de contactos. La regla práctica es que el portal atrae y el sitio propio convence, y el contenido de cada uno debería escribirse pensando en ese papel.</p>
                    </details>
