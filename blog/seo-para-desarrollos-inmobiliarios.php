                <section id="que-cambia-en-un-desarrollo">
                    <h2>Qué hace distinto a un desarrollo</h2>
                    <p>
                        Un desarrollo tiene tres características que rompen el manual estándar de posicionamiento web orgánico.
                    </p>
                    <p>
                        <strong>Vende algo que no existe todavía.</strong> En preventa no tienes fotos del producto terminado ni clientes que hablen de cómo se vive ahí. Tienes renders, una ubicación y una promesa. Eso limita mucho el contenido que puedes producir sobre el inmueble, y obliga a construirlo alrededor de la zona, el momento de compra y el retorno esperado.
                    </p>
                    <p>
                        <strong>Tiene fecha de caducidad.</strong> Un despacho contable puede posicionar la misma página diez años. Tu torre se agota en dieciocho meses. Si el activo digital muere con el inventario, nunca acumulas nada.
                    </p>
                    <p>
                        <strong>El ciclo de decisión es largo y el ticket es alto.</strong> Nadie compra un departamento de siete millones en la primera visita. Van a buscarte por nombre después de ver tu anuncio, van a comparar tu zona contra otras dos, y van a buscar si alguien se quejó de ti. Tu trabajo en Google no es solo aparecer: es controlar lo que encuentran cuando ya los despertó otro canal.
                    </p>
                    <p>
                        Eso último es lo que casi nadie considera al armar un plan de marketing para inmobiliaria. La pauta genera la demanda, y la búsqueda es donde esa demanda se confirma o se cae. Si inviertes fuerte en <a href="/blog/facebook-ads-lanzamiento-desarrollo-inmobiliario">anuncios para el lanzamiento de un desarrollo</a> y quien busca el nombre del proyecto no encuentra nada serio, estás pagando por llevar gente a un vacío.
                    </p>
                </section>

                <section id="arquitectura-del-sitio">
                    <h2>Micrositio o subcarpeta: la decisión que define todo</h2>
                    <p>
                        Es la primera pregunta y la más cara de corregir después. Las opciones reales son tres.
                    </p>
                    <h3>Dominio propio para cada proyecto</h3>
                    <p>
                        Es lo que hace la mayoría. Funciona para la marca y es un desastre para el SEO: cada proyecto arranca sin historia, sin enlaces y sin autoridad, y cuando se vende todo, el dominio se abandona o se apaga. Tiene sentido en un solo caso, cuando el proyecto es tan grande que va a operar como marca independiente por años, con su propio equipo y su propia prensa.
                    </p>
                    <h3>Subcarpeta dentro del sitio de la desarrolladora</h3>
                    <p>
                        La estructura es <code>tudesarrolladora.com/proyectos/nombre-del-proyecto/</code>. Cada proyecto nuevo nace con la autoridad que ya tiene el dominio, y cuando se agota el inventario, la página no desaparece: se convierte en portafolio y en prueba de que entregas. El quinto proyecto arranca con cuatro proyectos de historial detrás.
                    </p>
                    <p>
                        Para casi todas las desarrolladoras mexicanas con las que trabajamos, esta es la opción correcta. La marca del proyecto se sostiene con el diseño de la página, no con el dominio.
                    </p>
                    <h3>Subdominio</h3>
                    <p>
                        <code>proyecto.tudesarrolladora.com</code>. Es el punto medio y suele quedarse con lo malo de ambos: los buscadores lo tratan con cierta independencia del dominio principal y la marca tampoco queda tan separada como en un dominio propio. Lo elegimos solo cuando hay una restricción técnica del sistema que administra el sitio.
                    </p>
                    <p>
                        <strong>Si ya tienes micrositios sueltos</strong>, no los borres. Migra el contenido a subcarpetas y aplica redirecciones permanentes de cada URL vieja a su equivalente nueva, no todas a la portada. Google tiene una herramienta de cambio de dirección en Search Console justo para avisarle del traslado, y su documentación es explícita en que las redirecciones deben ir hacia la página más cercana. Hacerlo mal es una de las causas clásicas de las <a href="/blog/errores-de-seo-que-matan-tu-trafico">caídas de tráfico que nadie explica</a>.
                    </p>
                </section>

                <section id="paginas-que-necesita">
                    <h2>Las páginas que sí posicionan</h2>
                    <p>
                        Un desarrollo no necesita treinta páginas. Necesita seis bien hechas, cada una apuntando a un tipo de búsqueda distinto.
                    </p>
                    <ul>
                        <li><strong>La página del proyecto.</strong> Captura las búsquedas de marca, las que llegan después de ver tu publicidad inmobiliaria. Aquí va todo lo que el prospecto confirma: ubicación exacta, etapas, fecha de entrega, amenidades, quién construye.</li>
                        <li><strong>Una página por tipología.</strong> Departamentos de dos recámaras, penthouse, lotes residenciales. Cada tipología es una búsqueda distinta y merece su propia URL, con su propio precio desde y su propia planta arquitectónica.</li>
                        <li><strong>La página de la zona.</strong> Es la que más tráfico frío trae y casi nadie la hace. Quien busca dónde vivir en una colonia todavía no conoce tu proyecto.</li>
                        <li><strong>La página de la desarrolladora.</strong> Quién eres, qué has entregado, con qué respaldo. La visitan justo antes de dejar el enganche y es donde se cae la venta si está vacía.</li>
                        <li><strong>Una página de proceso de compra.</strong> Cómo funciona la preventa, qué esquemas de pago hay, qué pasa si el crédito no sale. Responde las dudas que frenan al comprador y atrae búsquedas informativas de gente que ya está en el proceso.</li>
                        <li><strong>Las páginas de avance de obra.</strong> Contenido nuevo cada mes sin inventar nada: fotos reales, porcentaje de avance, fecha. Es lo único que en preventa demuestra que el proyecto se está construyendo de verdad.</li>
                    </ul>
                    <p>
                        Antes de escribir cualquiera de estas, cada página necesita una consulta objetivo asignada. Dos páginas peleando por la misma búsqueda se estorban entre ellas. El método está en la guía de <a href="/blog/como-hacer-investigacion-de-palabras-clave">investigación de palabras clave</a>, y la estructura interna de cada página en el <a href="/blog/seo-on-page-checklist">checklist de SEO on page</a>.
                    </p>
                </section>

                <section id="contenido-de-zona">
                    <h2>Contenido de zona: lo que vende en preventa</h2>
                    <p>
                        En preventa no vendes el departamento, vendes la decisión de vivir o invertir ahí. Por eso el contenido de zona es el que mejor rinde, y además es el único que puedes producir en volumen cuando todavía no hay obra que mostrar.
                    </p>
                    <p>
                        Los temas que funcionan son los que el comprador se pregunta en voz baja: cuánto se ha apreciado la zona en los últimos cinco años, qué escuelas hay a menos de quince minutos, cómo está el tráfico a la hora pico hacia el corredor de oficinas, qué obra pública viene en camino, cuánto se renta hoy un dos recámaras a la vuelta. Datos, no adjetivos.
                    </p>
                    <p>
                        Esto es también lo que separa un blog inmobiliario que genera leads calificados de uno que junta visitas inútiles. Un artículo sobre las mejores zonas para invertir en tu ciudad atrae a alguien con capital. Uno sobre cómo decorar una sala pequeña atrae a alguien que ya tiene casa. Los dos suman tráfico y solo uno paga la nómina.
                    </p>
                    <p>
                        Ese contenido, además, es el que te gana enlaces. Un estudio propio de plusvalía por colonia, con números que nadie más publicó, lo citan medios locales y portales del sector. Eso vale más que cien enlaces comprados, y el razonamiento completo está en la guía de <a href="/blog/link-building-enlaces-de-calidad">link building con enlaces de calidad</a>.
                    </p>
                </section>

                <section id="lo-tecnico-minimo">
                    <h2>Lo técnico mínimo</h2>
                    <p>
                        Los sitios de desarrollos fallan siempre en los mismos tres puntos, y todos vienen de priorizar lo visual.
                    </p>
                    <p>
                        <strong>Peso de las imágenes.</strong> Los renders salen del despacho de arquitectura en archivos enormes y se suben tal cual. Una galería de veinte imágenes sin comprimir es un sitio que tarda ocho segundos en abrir desde el celular, que es donde tu prospecto lo va a ver después de dar clic en un anuncio. Lo que Google mide de esa experiencia está en la guía de <a href="/blog/core-web-vitals">Core Web Vitals</a>.
                    </p>
                    <p>
                        <strong>Contenido atrapado en el visor.</strong> Recorridos virtuales, planos interactivos y galerías que cargan por JavaScript suelen dejar al rastreador sin nada que leer. Google pide como requisito mínimo que su rastreador pueda acceder a la página y que esta responda correctamente. Si el texto de tu tipología solo existe dentro de un componente que se carga después, para el buscador esa página está casi vacía. El detalle de esta capa está en la guía de <a href="/blog/seo-tecnico-velocidad-indexacion-errores">SEO técnico</a>.
                    </p>
                    <p>
                        <strong>Sin datos estructurados.</strong> Los datos estructurados son el formato con el que le dices explícitamente a Google qué es cada elemento de tu página. Para un desarrollo tiene sentido marcar la empresa, la ubicación, las preguntas frecuentes y los datos de contacto. No es un truco de posicionamiento: es quitarle trabajo de interpretación al buscador. Lo desarrollamos en la guía de <a href="/blog/schema-markup-que-es">qué es el schema markup</a>.
                    </p>
                </section>

                <section id="ciclo-de-vida">
                    <h2>Cuando se vende la última unidad</h2>
                    <p>
                        Aquí es donde se distingue una estrategia inmobiliaria de una campaña. La página de un proyecto agotado sigue recibiendo búsquedas de su nombre por años, y esas visitas valen mucho: son de gente que investiga si eres confiable antes de comprarte otra cosa.
                    </p>
                    <p>Lo que hacemos al cerrar un proyecto:</p>
                    <ul>
                        <li><strong>La página se queda viva.</strong> Cambia el encabezado a proyecto entregado, se suman fotos reales del resultado final y testimonios de residentes. Deja de ser una ficha de venta y se vuelve tu mejor prueba.</li>
                        <li><strong>Redirige la demanda, no la borres.</strong> Un bloque visible que mande al proyecto activo más parecido, en zona y en precio. El interés que llega ahí ya está calificado.</li>
                        <li><strong>Nunca borres la URL.</strong> Borrarla mata los enlaces externos que ganó, las menciones de prensa y el historial acumulado. Si por alguna razón tiene que desaparecer, redirige de forma permanente hacia la página del portafolio, no hacia la portada.</li>
                        <li><strong>Deja el contenido de zona intacto.</strong> Ese no caduca con el inventario y va a alimentar la venta del siguiente proyecto en la misma ciudad.</li>
                    </ul>
                    <p>
                        Después de tres o cuatro proyectos manejados así, la página de la desarrolladora posiciona sola, porque tiene historial verificable detrás. Eso es lo que ninguna campaña de <a href="/blog/google-ads-para-inmobiliarias">Google Ads para inmobiliarias</a> compra por más presupuesto que le pongas.
                    </p>
                </section>

                <section id="como-medir">
                    <h2>Cómo medirlo y qué esperar</h2>
                    <p>
                        La métrica que importa no son las visitas totales. Es cuántas solicitudes de información llegan del canal orgánico y qué tan buenas son comparadas con las de la pauta.
                    </p>
                    <p>
                        Separa dos grupos desde el principio en Search Console. Uno es el de las búsquedas de marca, que incluyen el nombre del proyecto o de la desarrolladora: esas miden qué tan bien estás cerrando la demanda que genera tu publicidad para desarrollos inmobiliarios. El otro es el de las búsquedas sin marca, tipo zona, tipología o rango de precio: esas miden si estás generando demanda nueva. Mezclarlas en un solo número esconde el problema real, que suele ser que todo el tráfico es de marca y el trabajo orgánico no está aportando prospectos nuevos.
                    </p>
                    <p>
                        En cuanto a tiempos, sé honesto con tus expectativas. Las páginas de marca posicionan rápido, en semanas, porque casi nadie compite por el nombre de tu proyecto. Las de zona y tipología pelean contra portales grandes y toman de seis a doce meses en un mercado como el de Guadalajara o Ciudad de México. Por eso el arranque de un desarrollo se sostiene con pauta mientras el orgánico madura, que es exactamente la decisión que tratamos en <a href="/blog/seo-vs-sem-cuando-invertir-en-cada-uno">SEO o SEM, cuándo invertir en cada uno</a>.
                    </p>
