                <section id="pagina-de-facebook">
                    <h2>Paso 1: crea tu página comercial de Facebook</h2>
                    <p>
                        Toda cuenta de Meta Ads empieza con una página comercial de Facebook, incluso si tu negocio se va a anunciar principalmente en Instagram. Para crearla, usas tu perfil personal de Facebook (o creas uno nuevo exclusivamente para administrar el negocio), y desde ahí generas la página con el nombre, la foto de perfil y la foto de portada de tu marca. En cuanto la página existe, Meta te asigna automáticamente una cuenta del Administrador de Anuncios, con un identificador de cuenta, una divisa y una zona horaria según la ubicación de tu negocio.
                    </p>
                    <p>
                        Un detalle importante que muchas cuentas descubren demasiado tarde: si cambias la divisa o la zona horaria después, Meta no las modifica dentro de la misma cuenta, sino que crea una cuenta publicitaria completamente nueva y te pide desactivar la anterior. Por eso conviene confirmar bien estos datos desde el primer día, sobre todo si tu negocio eventualmente va a anunciarse en más de un país.
                    </p>
                </section>

                <section id="meta-business-suite">
                    <h2>Paso 2: configura Meta Business Suite</h2>
                    <p>
                        Meta Business Suite (también llamado Meta Business Manager o Facebook Business Manager) es el panel central donde vas a administrar tu página, tu cuenta publicitaria, tu catálogo de productos, tu WhatsApp Business y los accesos de todo tu equipo desde un solo lugar. Si tu negocio ya tiene una página pero nunca configuró Business Suite, es el primer paso antes de tocar cualquier otra cosa, porque es ahí donde vas a vincular la cuenta publicitaria, agregar a tu equipo o agencia, y conectar herramientas como el Pixel de Meta o el catálogo de Instagram Shopping.
                    </p>
                </section>

                <section id="configuracion-de-la-cuenta">
                    <h2>Paso 3: revisa la configuración de la cuenta publicitaria</h2>
                    <p>
                        Antes de crear tu primera campaña, entra a la configuración de la cuenta publicitaria dentro del Administrador de Anuncios y confirma que toda la información esté correcta: el nombre del negocio, la dirección fiscal, la divisa y la zona horaria. Este paso parece administrativo, pero es exactamente donde más cuentas nuevas cometen errores que después son difíciles de corregir sin crear una cuenta desde cero.
                    </p>
                </section>

                <section id="forma-de-pago">
                    <h2>Paso 4: configura tu forma de pago</h2>
                    <p>
                        Dentro de la configuración de pago del Administrador de Anuncios puedes agregar tu método de pago (tarjeta de crédito o débito), consultar tu saldo, revisar el historial de actividad de pago de cada cuenta publicitaria, y confirmar los datos fiscales de tu negocio. Sin una forma de pago configurada y verificada, simplemente no vas a poder publicar ningún anuncio, así que este paso es obligatorio antes de crear tu primera campaña, no algo que se pueda dejar para después.
                    </p>
                </section>

                <section id="permisos-y-roles">
                    <h2>Paso 5: asigna permisos basados en tareas</h2>
                    <p>
                        Conforme tu equipo crece, o si trabajas con una agencia de marketing digital externa, vas a necesitar dar acceso a distintas personas sin entregar el control total de tu cuenta. Meta Business Suite permite conceder permisos basados en tareas específicas: alguien puede tener acceso solo para publicar contenido, otra persona solo para administrar anuncios, y alguien más solo para consultar estadísticas, sin que ninguno tenga acceso a la configuración de pago o a eliminar la página completa. Definir estos permisos de forma correcta desde el inicio evita dos problemas comunes: que una sola persona concentre demasiado acceso sin necesidad, o que un colaborador que ya no trabaja contigo siga teniendo acceso a la cuenta.
                    </p>
                </section>

                <section id="arquitectura-de-campanas">
                    <h2>Paso 6: define tu arquitectura de campañas</h2>
                    <p>
                        Los anuncios que creas en el Administrador de Anuncios se organizan en tres niveles que juntos forman la estructura de la campaña: campaña, conjunto de anuncios y anuncio. Entender bien esta jerarquía es la base de una cuenta ordenada:
                    </p>
                    <ul>
                        <li><strong>Nivel de campaña.</strong> Define el objetivo (reconocimiento, tráfico, interacción, clientes potenciales, promoción de la app o ventas). Una buena práctica es una campaña por objetivo de negocio, no una campaña distinta por cada variación menor.</li>
                        <li><strong>Nivel de conjunto de anuncios.</strong> Define el público, el presupuesto, las ubicaciones y el calendario. Aquí es donde se agrupan los distintos públicos que quieres probar dentro de un mismo objetivo.</li>
                        <li><strong>Nivel de anuncio.</strong> Define el contenido final: formato, imagen o video, texto y llamada a la acción. Dentro de un mismo conjunto puedes tener varias variantes de anuncio para comparar cuál rinde mejor.</li>
                    </ul>
                    <p>
                        Una estructura ordenada agrupa las campañas por objetivo de negocio, los conjuntos de anuncios por público o por temperatura de tráfico, y los anuncios por variante de creativo o mensaje, en lugar de mezclar todo dentro de una sola campaña gigante difícil de leer y optimizar.
                    </p>
                </section>

                <section id="nomenclatura">
                    <h2>Paso 7: crea una nomenclatura consistente</h2>
                    <p>
                        Un error muy común en cuentas que crecen rápido es nombrar las campañas de forma improvisada ("Campaña nueva", "prueba 2", "campaña buena"), lo que hace prácticamente imposible auditar la cuenta unos meses después. Una nomenclatura consistente incluye, de forma ordenada, el objetivo, la industria o vertical (si manejas más de una), el público y la fecha de lanzamiento, por ejemplo: "Leads - Inmobiliaria - Frío - Guadalajara - Ago2026". Esto no es solo un tema de orden estético: te permite filtrar y comparar el rendimiento entre campañas dentro del Administrador de Anuncios de forma mucho más rápida cuando la cuenta ya tiene docenas de campañas activas o pausadas.
                    </p>
                </section>

                <section id="pixel-desde-el-inicio">
                    <h2>Paso 8: instala el Pixel antes de anunciarte, no después</h2>
                    <p>
                        El Pixel de Meta y, de preferencia, la API de Conversiones deben instalarse en tu sitio web antes de lanzar tu primera campaña, no como un ajuste posterior. Instalarlo desde el día uno te permite empezar a acumular datos de visitantes desde el primer clic, lo que acelera la construcción de públicos personalizados y públicos similares más adelante. Muchas cuentas pierden semanas de datos valiosos por instalar el Pixel hasta que ya llevan tiempo corriendo campañas, cuando ese periodo inicial de datos ya no se puede recuperar.
                    </p>
                </section>

                <section id="estructura-por-industria">
                    <h2>Ejemplo de estructura por industria</h2>
                    <p>
                        Para una desarrolladora inmobiliaria que maneja varios proyectos al mismo tiempo, una estructura ordenada suele separar las campañas por desarrollo (cada proyecto con su propia campaña de generación de leads), y dentro de cada una, conjuntos de anuncios separados por temperatura de tráfico y por zona geográfica de origen del público (local, nacional, o internacional para desarrollos con vocación de inversión). Para una agencia de marketing digital que administra varias cuentas de clientes, cada cliente debería vivir en su propia cuenta publicitaria dentro de Meta Business Suite, nunca mezclado con las campañas de otro cliente dentro de la misma cuenta, tanto por claridad como por temas de privacidad de datos y facturación.
                    </p>
                </section>

