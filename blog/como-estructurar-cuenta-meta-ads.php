                    <details>
                        <summary>¿Cuántas campañas debo tener activas al mismo tiempo?</summary>
                        <p>No existe un número fijo correcto para todos los negocios, pero sí una lógica general: es mejor tener pocas campañas bien estructuradas, cada una con un objetivo de negocio claro y varios conjuntos de anuncios probando distintos públicos dentro de ella, que muchas campañas pequeñas y fragmentadas compitiendo entre sí por el mismo presupuesto y el mismo público. Fragmentar demasiado una cuenta también dificulta que cada conjunto de anuncios acumule suficientes conversiones para salir de la fase de aprendizaje de forma eficiente. Como referencia, una cuenta de tamaño mediano para un negocio de alto ticket, como una desarrolladora inmobiliaria con dos o tres proyectos activos, suele operar de forma saludable con entre 3 y 6 campañas activas al mismo tiempo, cada una alineada a un objetivo y un proyecto específico.</p>
                    </details>

                    <details>
                        <summary>¿Qué pasa si cambio la divisa o la zona horaria de mi cuenta después de crearla?</summary>
                        <p>Meta no permite modificar la divisa ni la zona horaria dentro de la misma cuenta publicitaria una vez creada; en su lugar, el sistema crea automáticamente una cuenta publicitaria completamente nueva con los nuevos parámetros y te pide desactivar la cuenta anterior. Esto significa que pierdes la continuidad del historial de esa cuenta anterior dentro del Administrador de Anuncios (aunque sigues pudiendo consultarla, ya no podrás publicar anuncios desde ella), y tienes que reconstruir tus públicos personalizados, tu historial de aprendizaje del algoritmo y tu configuración de campañas desde cero en la nueva cuenta. Por esta razón, es mucho mejor confirmar la divisa y la zona horaria correctas desde el momento en que se crea la página, especialmente si existe alguna posibilidad de que el negocio se expanda a otro país en el corto o mediano plazo.</p>
                    </details>

                    <details>
                        <summary>¿Debo dar acceso de administrador completo a mi agencia de marketing digital?</summary>
                        <p>No es necesario, y de hecho no es lo más recomendable desde un punto de vista de seguridad. Los permisos basados en tareas de Meta Business Suite te permiten dar a tu agencia exactamente el nivel de acceso que necesita para hacer su trabajo (crear y administrar anuncios, ver estadísticas, subir contenido) sin necesidad de entregarle acceso de administrador total sobre tu página, tu forma de pago o la posibilidad de eliminar la cuenta completa. Una agencia seria y transparente no debería tener ningún problema en trabajar bajo permisos delimitados; de hecho, es una señal de que la relación de trabajo está bien estructurada desde ambos lados. Si en algún momento decides dejar de trabajar con esa agencia, revocar el acceso es tan sencillo como eliminar sus permisos desde la configuración de Business Suite, sin que eso afecte el resto de tu cuenta.</p>
                    </details>

                    <details>
                        <summary>¿Es mejor tener una sola campaña grande o varias campañas pequeñas por vertical?</summary>
                        <p>Depende de cuántas verticales o líneas de negocio realmente distintas manejes, pero la recomendación general es separar por objetivo de negocio real, no crear divisiones artificiales solo por orden. Si tu agencia atiende tanto clientes inmobiliarios como de energía solar, cada vertical debería vivir en cuentas publicitarias distintas (una por cliente, como ya mencionamos), no combinadas en una sola campaña. Pero dentro de la cuenta de un mismo cliente, sí conviene consolidar el presupuesto en menos campañas bien estructuradas por objetivo, en lugar de crear una campaña separada por cada pequeña variación de público o de creativo, porque eso fragmenta los datos y dificulta que el algoritmo de Meta optimice con eficiencia. La regla general es: separa por negocio o cliente a nivel de cuenta, y consolida por objetivo a nivel de campaña dentro de cada cuenta.</p>
                    </details>
