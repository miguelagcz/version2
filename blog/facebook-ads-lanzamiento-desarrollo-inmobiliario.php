                <section id="por-que-lanzar-distinto">
                    <h2>Por qué un lanzamiento necesita una estrategia distinta a una campaña continua</h2>
                    <p>
                        Una campaña de Facebook Ads para un desarrollo ya en venta activa se mide, en gran parte, por su costo por lead y su costo por resultado sostenido en el tiempo. Una campaña de lanzamiento se mide por algo distinto: qué tan grande y qué tan calificada es la lista de personas interesadas en el momento exacto en que las unidades salen a la venta. El objetivo no es solo generar leads, es generar una sensación real de demanda antes de que exista producto disponible, algo que cuando se hace bien se traduce directamente en mejores precios de preventa y en una velocidad de venta mucho más alta en las primeras semanas.
                    </p>
                </section>

                <section id="estudio-de-mercado-previo">
                    <h2>El estudio de mercado antes del primer anuncio</h2>
                    <p>
                        Antes de lanzar cualquier campaña, un estudio de mercado bien hecho sobre la zona, el perfil de comprador y los desarrollos competidores en preventa te dice qué precio de entrada es competitivo, qué amenidades realmente importan a tu público objetivo, y qué objeciones vas a tener que resolver desde el primer anuncio. Un lanzamiento sin esta investigación previa suele fijar precios o mensajes basados en suposiciones internas del equipo de ventas, en lugar de en lo que el mercado real está dispuesto a pagar y valorar.
                    </p>
                </section>

                <section id="fase-1-lista-de-espera">
                    <h2>Fase 1: la lista de espera</h2>
                    <p>
                        Semanas o incluso meses antes de que el desarrollo abra su venta, la primera fase de campaña debe enfocarse exclusivamente en construir una lista de espera. El anuncio no vende nada todavía; ofrece la posibilidad de anotarse para recibir precios preferenciales de preventa, elegir primero entre las mejores unidades, o acceder a un evento de lanzamiento exclusivo. Esta oferta de bajo compromiso, dirigida principalmente a tráfico frío con segmentación por ubicación e intereses relacionados con bienes raíces e inversión, suele generar un costo por lead considerablemente más bajo que cualquier campaña posterior, precisamente porque no le pide a nadie una decisión de compra todavía.
                    </p>
                    <p>
                        Durante esta fase, el Pixel de Meta empieza a acumular datos valiosos sobre quién muestra interés real, lo que después permite construir públicos personalizados y públicos similares de mucha mejor calidad para las siguientes fases, como explicamos en <a href="/blog/publicos-personalizados-y-lookalike">públicos personalizados y lookalike</a>.
                    </p>
                </section>

                <section id="fase-2-apertura">
                    <h2>Fase 2: apertura de ventas y urgencia real</h2>
                    <p>
                        Cuando el desarrollo abre oficialmente su venta, la campaña cambia de objetivo: ahora se trata de convertir a esa lista de espera (y a nuevo tráfico similar) en citas y apartados reales. Aquí es donde la urgencia empieza a jugar un papel legítimo, siempre que sea real y no fabricada: número limitado de unidades en preventa, precio que sube en una fecha específica, o acceso prioritario solo para quienes ya estaban en la lista de espera. Un remarketing agresivo hacia la lista de espera construida en la fase anterior suele ser la campaña con mejor rendimiento de todo el lanzamiento, porque le habla a personas que ya llevan semanas esperando este momento.
                    </p>
                </section>

                <section id="fase-3-venta-activa">
                    <h2>Fase 3: venta activa y sostenimiento</h2>
                    <p>
                        Una vez que pasa el impulso inicial del lanzamiento, la campaña entra en una fase de sostenimiento más parecida a la publicidad continua que cubrimos en <a href="/blog/facebook-ads-para-inmobiliarias">Facebook Ads para inmobiliarias</a>: generación constante de nuevos leads, contenido de avance de obra como prueba social, y retargeting permanente hacia quienes visitaron la landing page sin convertir. El mensaje en esta fase debe evolucionar del entusiasmo del lanzamiento hacia evidencia real de que el proyecto avanza, algo especialmente importante para sostener la confianza de quienes todavía están decidiendo varios meses después del lanzamiento inicial.
                    </p>
                </section>

                <section id="publico-objetivo-lanzamiento">
                    <h2>Público objetivo: local, nacional e inversión</h2>
                    <p>
                        Un lanzamiento bien planeado suele segmentar su público objetivo en al menos tres grupos con mensajes distintos: compradores locales que buscan una nueva vivienda en la zona, compradores de otras ciudades del país interesados en reubicarse o invertir, y en desarrollos con vocación de segunda residencia o inversión, un público internacional (frecuentemente de Estados Unidos) con vínculos familiares o interés en el mercado mexicano. Cada uno de estos públicos responde a un ángulo de mensaje distinto: el comprador local valora la ubicación y el estilo de vida, mientras que el comprador de inversión valora la plusvalía proyectada y el retorno esperado.
                    </p>
                </section>

                <section id="landing-page-de-lanzamiento">
                    <h2>La landing page de preventa</h2>
                    <p>
                        Durante la fase de lista de espera, la landing page no necesita ser tan completa como la de un desarrollo en venta activa: su único objetivo es capturar el contacto de la persona a cambio de la promesa de acceso preferencial. Renders de alta calidad, un mapa de ubicación y un formulario corto suelen ser suficientes en esta etapa. Conforme avanza hacia la fase de apertura de ventas, la landing page debe crecer para incluir plano de unidades, amenidades, avance de obra si ya existe, y testimonios o menciones de prensa que refuercen la seriedad del desarrollo.
                    </p>
                </section>

                <section id="errores-de-lanzamiento">
                    <h2>Errores que arruinan un lanzamiento</h2>
                    <p>
                        El error más costoso es empezar la campaña de captación demasiado tarde, dejando muy poco tiempo para construir una lista de espera con volumen suficiente antes de la apertura de ventas. El segundo error más común es fabricar urgencia falsa (fechas límite que después se extienden, "últimas unidades" cuando en realidad quedan muchas), lo que destruye la confianza tan pronto como el prospecto lo nota, algo que sucede con más frecuencia de la que muchos desarrolladores creen. El tercer error es no tener listo el equipo de ventas para atender el volumen de leads que genera un buen lanzamiento, dejando que prospectos calificados esperen días para recibir seguimiento y perdiendo el momentum que la campaña había construido.
                    </p>
                </section>

